def test_unsend_and_typing_have_no_python_caller():
    """The bridge serves them and their fixtures pin its shapes, but nothing in
    Nora calls either today. If that changes, the new caller needs a test here
    against `unsend_*` / `typing_*`, which this test exists to prompt."""
    sources = "\n".join(
        p.read_text() for p in (_ROOT / "nora" / "platform" / "instagram").glob("*.py")
    )
    code = re.sub(r'"""[\s\S]*?"""|#[^\n]*', "", sources)
    assert "/typing" not in code
    assert ".delete(" not in code
    pinned = {"unsend_ok.json", "unsend_unconfirmed.json", "typing_ok.json"}
    assert pinned <= set(_thread_fixtures())
