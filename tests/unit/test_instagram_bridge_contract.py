@pytest.mark.parametrize("name", _names("members"))
async def test_a_roster_read_against_the_bridges_own_bodies(bridge, name):
    fake, base = bridge
    fx = _fixture(name)
    fake.load(fx)
    thread, _ = _path_ids(fx["path"])

    with _tracer.start_as_current_span("turn") as span:
        roster = await InstagramRoster(base).roster(conversation_id=thread)

    _assert_one_call(fake, fx, span)
    if fx["status"] == 200:
        assert roster.available is True
        # One frozenset per member, holding the MESSAGING fbid only.
        fbids = [m["fbid"] for m in fx["body"]["members"]]
        assert roster.members == tuple(frozenset({f}) for f in fbids)
    else:
        assert roster.available is False
        assert roster.members == ()


