"""Nora's Instagram adapter against the bridge's OWN bytes, for every thread
route.

`tests/fixtures/instagram_bridge/{members,messages,reaction,unsend,typing}_*`
are GENERATED by the Go handlers (`deploy/instagram-bridge/cmd/instagram-bridge/
contract_fixtures_test.go`), each carrying the route, the path, the request a
write was generated from, the status and the body. This module reads the SAME
files:

* the fake bridge below serves EXACTLY the routes those fixtures name, and
  answers each with the fixture's status and body. Any other path is the Go
  mux's plain-text 404 and is recorded, so an adapter still calling a deleted
  verb path (`/send`, `/send-media`, `/react`) fails here;
* the adapter must send, for the message a fixture describes, EXACTLY the
  fixture's request body. A renamed request field fails on both sides: the
  bridge's fixture test when the handler changes, this one when the adapter
  does;
* each fixture's `upstream` block is what the bridge handed Instagram for that
  request (recorded by the Go test from its fake client). The body the adapter
  sent is checked against it field by field, so the fixture binds the adapter's
  field names to what the bridge actually READ, not only to what it echoed;
* every write carries the turn's `traceparent`, so one trace still spans Nora
  and the bridge;
* the adapter's outcome for each status is the one the bridge's status table
  means: 409 needs a human and is never retried, 503 is retried, everything
  else that is not a 200 is a failure that is not retried.

Unsend and typing have no Python caller (the second-to-last test holds that
claim); their fixtures pin the bridge's shapes for the first one.
"""

from __future__ import annotations

import base64
import json
import re
from pathlib import Path

import aiohttp
import pytest
from aiohttp import web
from aiohttp.test_utils import TestServer
from opentelemetry.sdk.trace import TracerProvider

from nora.domain.models import ConversationTarget
from nora.domain.ports import Mention, OutboundAttachment, OutboundQuote
from nora.platform.instagram.react import InstagramReactor
from nora.platform.instagram.roster import InstagramRoster
from nora.platform.instagram.send import InstagramSender

_ROOT = Path(__file__).resolve().parents[2]
_FIXTURES = _ROOT / "tests" / "fixtures" / "instagram_bridge"

#: The bridge's thread routes, as its router registers them.
THREAD_ROUTES = (
    "GET /threads/{thread_fbid}/members",
    "POST /threads/{thread_fbid}/messages",
    "DELETE /threads/{thread_fbid}/messages/{message_id}",
    "PUT /threads/{thread_fbid}/messages/{message_id}/reaction",
    "PUT /threads/{thread_fbid}/typing",
)

_tracer = TracerProvider().get_tracer("test")


def _fixture(name: str) -> dict:
    return json.loads((_FIXTURES / name).read_text())


def _names(prefix: str) -> list[str]:
    return sorted(p.name for p in _FIXTURES.glob(f"{prefix}_*.json"))


def _thread_fixtures() -> list[str]:
    return [n for prefix in ("members", "messages", "reaction", "unsend", "typing")
            for n in _names(prefix)]


def _path_ids(path: str) -> tuple[str, str | None]:
    """`(thread, message_id)` out of a fixture's path."""
    match = re.fullmatch(r"/threads/([^/]+)(?:/messages(?:/([^/]+))?)?(?:/\w+)?", path)
    assert match, path
    return match.group(1), match.group(2)


class FixtureBridge:
    """Serves exactly `THREAD_ROUTES`, each answering the fixture loaded for
    it. Records `(route, path, body, traceparent)` per call; anything else is
    recorded in `unrouted` and answered the way Go's mux answers an unmatched
    path: a plain-text 404."""

    def __init__(self) -> None:
        self.answers: dict[str, dict] = {}
        self.calls: list[tuple[str, str, object, str | None]] = []
        self.unrouted: list[tuple[str, str]] = []

    def load(self, fx: dict) -> None:
        self.answers[fx["route"]] = fx

    def _handler(self, route: str):
        async def handle(request: web.Request) -> web.Response:
            raw = await request.read()
            body = json.loads(raw) if raw else None
            self.calls.append((route, request.path, body, request.headers.get("traceparent")))
            fx = self.answers[route]
            return web.json_response(fx["body"], status=fx["status"])
        return handle

    async def _unrouted(self, request: web.Request) -> web.Response:
        self.unrouted.append((request.method, request.path))
        return web.Response(status=404, text="404 page not found\n")

    def app(self) -> web.Application:
        app = web.Application()
        for route in THREAD_ROUTES:
            method, path = route.split(" ", 1)
            app.router.add_route(method, path, self._handler(route))
        app.router.add_route("*", "/{tail:.*}", self._unrouted)
        return app


@pytest.fixture
async def bridge():
    fake = FixtureBridge()
    server = TestServer(fake.app())
    await server.start_server()
    yield fake, str(server.make_url("")).rstrip("/")
    await server.close()


def _trace_id(span) -> str:
    return format(span.get_span_context().trace_id, "032x")


def _assert_one_call(
    fake: FixtureBridge, fx: dict, span,
) -> tuple[str, str, object, str | None]:
    assert fake.unrouted == [], (
        f"the adapter called a path the bridge does not serve: {fake.unrouted}"
    )
    assert len(fake.calls) == 1, fake.calls
    route, path, body, traceparent = fake.calls[0]
    assert (route, path) == (fx["route"], fx["path"])
    assert traceparent is not None and _trace_id(span) in traceparent, (
        "a write left without the turn's trace context"
    )
    return route, path, body, traceparent


# ---- the fixtures and the fake agree about the routes ----------------------


def test_the_fake_serves_exactly_the_routes_the_bridge_fixtures_name():
    """If the bridge renames a thread route, its regenerated fixtures name the
    new one and this fake no longer serves it: the drift fails here first."""
    named = {_fixture(n)["route"] for n in _thread_fixtures()}
    assert named == set(THREAD_ROUTES)


def test_no_thread_fixture_carries_ok():
    """Success is the resource and the status says it succeeded; failure is
    the envelope. A body with `ok` is a shape nothing reads."""
    for name in _thread_fixtures():
        body = _fixture(name)["body"]
        assert "ok" not in body, name
        if _fixture(name)["status"] != 200:
            assert set(body) == {"error"} and {"code", "message"} <= set(body["error"]), name


async def test_a_deleted_verb_path_is_the_muxs_404(bridge):
    """The negative control for every test below: the fake genuinely refuses
    an old path, so an adapter on one cannot pass."""
    fake, base = bridge
    fake.load(_fixture("messages_text_ok.json"))

    async with aiohttp.ClientSession() as session:
        for path in ("/send", "/send-media", "/react"):
            async with session.post(f"{base}{path}", json={"room_id": "1", "text": "x"}) as resp:
                assert resp.status == 404
    assert fake.unrouted == [("POST", "/send"), ("POST", "/send-media"), ("POST", "/react")]
    assert fake.calls == []


# ---- POST /threads/{thread_fbid}/messages ----------------------------------


def _send_args(fx: dict) -> tuple[ConversationTarget, str, dict]:
    """The message a fixture's request describes, as the adapter is asked to
    send it. The text one is DRAFTED with a display name and a `Mention` that
    carries the account's handle: the adapter's mention rendering is what turns
    it into the fixture's `@handle` text and span (`send.py`)."""
    thread, _ = _path_ids(fx["path"])
    target = ConversationTarget("instagram", thread, "group")
    request = fx["request"]
    if "media" in request:
        media = request["media"]
        attachment = OutboundAttachment(
            content=base64.b64decode(media["data_base64"]),
            media_type=media["mimetype"], filename=media["filename"],
        )
        return target, "", {"attachments": (attachment,)}
    wire = request["mentions"][0]
    handle_text = request["text"][wire["offset"]:wire["offset"] + wire["length"]]
    assert handle_text.startswith("@")
    drafted_name = "@Example Friend"          # what Nora writes: a name, not a handle
    drafted = drafted_name + request["text"][wire["offset"] + wire["length"]:]
    mention = Mention(
        start=0, length=len(drafted_name), recipient=wire["fbid"], handle=handle_text[1:],
    )
    quote = OutboundQuote(ts=1, author_id="x", platform_message_id=request["reply_to"])
    return target, drafted, {"mentions": (mention,), "quote": quote}


@pytest.mark.parametrize("name", _names("messages"))
async def test_a_send_against_the_bridges_own_bodies(bridge, name):
    fake, base = bridge
    fx = _fixture(name)
    fake.load(fx)
    target, text, kwargs = _send_args(fx)

    with _tracer.start_as_current_span("turn") as span:
        result = await InstagramSender(base).send(target, text, **kwargs)

    _route, _path, body, _tp = _assert_one_call(fake, fx, span)
    assert body == fx["request"], "the adapter's request is not the one the bridge accepts"
    _assert_reaches_upstream(body, fx)
    status = fx["status"]
    if status == 200:
        assert result.ok is True
        # The one field the adapter reads from a 200.
        assert result.timestamp == fx["body"]["timestamp_ms"]
    else:
        assert result.ok is False
        # 503 is the bridge healing itself; everything else is not retried,
        # 409 above all (a challenged account must not be hammered).
        assert result.retryable is (status == 503)


def _assert_reaches_upstream(body: dict, fx: dict) -> None:
    """The body the adapter sent, against what the bridge handed Instagram for
    the same body (`upstream`). On a refusal nothing reached Instagram, except
    where the refusal came FROM Instagram (the send itself failed)."""
    calls = {c["call"]: c for c in fx["upstream"]}
    if "SendMessage" not in calls and "SendMedia" not in calls:
        assert fx["status"] != 200
        return
    if "media" in body:
        upload = calls["Upload"]
        assert (upload["filename"], upload["mimetype"]) == (
            body["media"]["filename"], body["media"]["mimetype"],
        )
        assert upload["bytes"] == len(base64.b64decode(body["media"]["data_base64"]))
        sent = calls["SendMedia"]
    else:
        sent = calls["SendMessage"]
        assert sent["text_length"] == len(body["text"])
        assert sent["mentions"] == [
            {"fbid": int(m["fbid"]), "offset": m["offset"], "length": m["length"]}
            for m in body.get("mentions", [])
        ]
    assert sent.get("reply_to_message_id") == body.get("reply_to")
    assert sent["thread_id"] == _path_ids(fx["path"])[0]


# ---- PUT /threads/{thread_fbid}/messages/{message_id}/reaction ---------------


@pytest.mark.parametrize("name", _names("reaction"))
async def test_a_reaction_against_the_bridges_own_bodies(bridge, name):
    fake, base = bridge
    fx = _fixture(name)
    fake.load(fx)
    thread, message = _path_ids(fx["path"])
    request = fx["request"]

    with _tracer.start_as_current_span("turn") as span:
        result = await InstagramReactor(base).react(
            target=ConversationTarget("instagram", thread, "group"),
            emoji=request.get("emoji", ""), to_message_id=message or "",
            remove=request.get("remove", False),
        )

    _route, _path, body, _tp = _assert_one_call(fake, fx, span)
    # Unconditional. The 400 fixture's request carries no emoji at all; the
    # adapter asked with an empty emoji sends the key empty, which the bridge
    # refuses the same way, and nothing reaches Instagram (`upstream: []`).
    assert body == {"emoji": "", **request}
    upstream = fx["upstream"]
    if fx["status"] == 200:
        [call] = upstream
        assert call["call"] == "SendReaction"
        assert (call["thread_id"], call["message_id"]) == (thread, message)
        assert call["emoji"] == body["emoji"]
        # `remove` must reach Instagram as the mutation's status, not merely be
        # echoed back.
        assert call["reaction_status"] == ("deleted" if body["remove"] else "created")
    else:
        assert upstream == []
    assert result.supported is True
    # `confirmed: false` is still a 200, and a 200 is a success.
    assert result.ok is (fx["status"] == 200)


