@pytest.mark.parametrize("status, code, kind", [
    (409, "needs_human", FailureKind.HALT),
    (409, "thread_lookup_failed", FailureKind.UNAVAILABLE),
    (502, "upstream_rejected", FailureKind.BACK_OFF),
    (502, None, FailureKind.UNAVAILABLE),
    (429, None, FailureKind.BACK_OFF),
    (501, "stale_query", FailureKind.STALE_QUERY),
    (501, "unsupported", FailureKind.UNSUPPORTED),
    (404, "not_found", FailureKind.NOT_FOUND),
    (404, None, FailureKind.UNAVAILABLE),
    (503, "unavailable", FailureKind.UNAVAILABLE),
    (500, "internal", FailureKind.UNAVAILABLE),
    (400, "invalid_id", FailureKind.UNAVAILABLE),
])
async def test_every_route_types_each_failure(bridge, route, call, status, code, kind) -> None:
    fake, source = bridge
    fake.answers[route] = _failure_fixture(status, code)
    got = await call(source)
    assert isinstance(got, Failed) and got.kind is kind


async def test_the_recorded_bridge_failures_map_as_the_bridge_sends_them(bridge) -> None:
    fake, source = bridge
    for name, route, kind in (
        ("account_checkpointed_409.json", "account", FailureKind.HALT),
        ("account_reconnecting_503.json", "account", FailureKind.UNAVAILABLE),
        ("story_stale_query_501.json", "story", FailureKind.STALE_QUERY),
        ("story_unconfigured_501.json", "story", FailureKind.UNSUPPORTED),
        ("items_stale_query_501.json", "items", FailureKind.STALE_QUERY),
        ("items_unconfigured_501.json", "items", FailureKind.UNSUPPORTED),
        ("items_checkpointed_409.json", "items", FailureKind.HALT),
        ("posts_upstream_rejected_502.json", "post", FailureKind.BACK_OFF),
        ("posts_not_found_404.json", "post", FailureKind.NOT_FOUND),
    ):
        fake.answers[route] = fixture(name)
        call = {
            "account": lambda: source.probe(account=_ACCOUNT),
            "story": lambda: source.story(account=_ACCOUNT),
            "items": lambda: source.list_items(account=_ACCOUNT, after=None),
            "post": lambda: source.read_item(ref=_REF),
        }[route]
        got = await call()
        assert isinstance(got, Failed) and got.kind is kind, name


