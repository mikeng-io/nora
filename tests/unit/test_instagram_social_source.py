def fixture(name: str) -> dict[str, Any]:
    return json.loads((_FIXTURES / name).read_text())


class FakeBridge:
    """Answers each path with the fixture loaded for its route. Records
    `(method, path_qs, headers)` for every request."""

    def __init__(self) -> None:
        self.answers: dict[str, dict[str, Any]] = {
            "account": fixture("account_ok.json"),
            "story": fixture("story_found.json"),
            "items": fixture("items_ok.json"),
            "post": fixture("posts_carousel_ok.json"),
        }
        self.calls: list[tuple[str, str, dict[str, str]]] = []

    def _respond(self, route: str, request: web.Request) -> web.Response:
        self.calls.append((request.method, request.path_qs, dict(request.headers)))
        fx = self.answers[route]
        if "raw" in fx:
            return web.Response(status=fx["status"], text=fx["raw"], content_type="text/plain")
        return web.json_response(fx["body"], status=fx["status"])

    def app(self) -> web.Application:
        app = web.Application()
        for route, path in (
            ("account", "/accounts/{igid}"), ("story", "/accounts/{igid}/story"),
            ("items", "/accounts/{igid}/items"), ("post", "/posts/{shortcode}"),
        ):
            async def handler(request: web.Request, route: str = route) -> web.Response:
                return self._respond(route, request)
            app.router.add_get(path, handler)
        return app


@pytest.fixture
async def bridge() -> AsyncIterator[tuple[FakeBridge, InstagramSocialSource]]:
    fake = FakeBridge()
    async with TestServer(fake.app()) as server:
        yield fake, InstagramSocialSource(base_url=str(server.make_url("")), timeout_seconds=5)


def _failure_fixture(status: int, code: str | None) -> dict[str, Any]:
    body = {"error": {"code": code, "message": "m"}} if code else None
    return {"status": status, "body": body} if body else {
        "status": status, "raw": "no", "body": None}


