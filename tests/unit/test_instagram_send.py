async def test_a_room_id_is_ONE_path_segment():
    """The room key is quoted into the path, so no conversation id can address
    a different route (`../send` would otherwise climb out of the thread)."""
    seen: list[str] = []

    async def anything(request: web.Request) -> web.Response:
        seen.append(request.raw_path)
        return web.json_response(_OK_BODY)

    app = web.Application()
    app.router.add_route("*", "/{tail:.*}", anything)
    server = TestServer(app)
    await server.start_server()
    try:
        sender = InstagramSender(str(server.make_url("")).rstrip("/"))
        await sender.send(ConversationTarget("instagram", "../send", "group"), "hi")
    finally:
        await server.close()
    assert seen == ["/threads/..%2Fsend/messages"]


async def test_an_unreachable_bridge_returns_a_failure_rather_than_raising():
    """`Deliverer` needs the outcome distinction to record a FAILED delivery
    status; an exception loses it."""
    sender = InstagramSender("http://127.0.0.1:1", timeout=0.2)

    result = await sender.send(GROUP, "hello")

    assert result.ok is False
