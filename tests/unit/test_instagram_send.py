async def test_a_mention_is_FORWARDED_as_fbid_offset_length(bridge):
    """Unlike WhatsApp v1, which accepts and ignores them. The wire takes
    them and round-trips them."""
    box, sender = bridge

    await sender.send(GROUP, "@nora hi", mentions=(Mention(start=0, length=5, recipient="1784"),))

    _room, body = box["calls"][0]
    assert body["mentions"] == [{"fbid": "1784", "offset": 0, "length": 5}]


async def test_a_mention_with_a_handle_REWRITES_the_text_to_the_username(bridge):
    """A correctly-resolved fbid must not go out as plain text ("@Miles
    Novak…") with no ping: Instagram's mention API renders a chip only when
    the span at `offset:offset+length` reads, literally, `"@" + the account's
    own username` (upstream mautrix-meta; see `nora.platform.instagram.send`).
    With a `Mention.handle` the WIRE text must read `"@nka_bpumvg"`, not the
    display name Nora wrote, and the offset/length that ride beside it must
    describe THAT string.

    PROBE: delete the `if m.handle:` branch in `_apply_mention_handles` (fall
    through to the `else`) and this goes red — `body["text"]` keeps the
    display name and `length` stays 8, not 11.
    """
    box, sender = bridge
    mention = Mention(start=0, length=len("@Miles Novak"), recipient="1784", handle="nka_bpumvg")

    await sender.send(GROUP, "@Miles Novak 同一條友嚟㗎，唔使歡迎兩次", mentions=(mention,))

    _room, body = box["calls"][0]
    assert body["text"] == "@nka_bpumvg 同一條友嚟㗎，唔使歡迎兩次"
    assert body["mentions"] == [{"fbid": "1784", "offset": 0, "length": len("@nka_bpumvg")}]


async def test_a_mention_with_no_handle_is_forwarded_with_the_text_unchanged(bridge):
    """No `username` on file for this fbid yet (the ordinary state until an
    operator opts a person in) — degraded but not wrong:
    the metadata still names the right fbid, the text stays whatever Nora
    wrote, and no chip renders."""
    box, sender = bridge
    mention = Mention(start=0, length=len("@Miles Novak"), recipient="1784", handle=None)

    await sender.send(GROUP, "@Miles Novak 你好", mentions=(mention,))

    _room, body = box["calls"][0]
    assert body["text"] == "@Miles Novak 你好"
    assert body["mentions"] == [{"fbid": "1784", "offset": 0, "length": 12}]


async def test_two_mentions_one_substituted_shifts_the_LATER_offset_correctly(bridge):
    """The cascading case: `"@Miles Novak"` (12 units) becomes `"@nka_bpumvg"` (11
    units), 1 unit SHORTER — so the second mention, unsubstituted, has to
    report an offset 1 unit further left than the one it was drafted at, or
    it would point one unit into "@Ada Lawson" instead of at its "@".

    PROBE: revert `_apply_mention_handles` to the naive per-mention `m.start`
    (no running `delta`) and this goes red — the second mention's `offset`
    comes back 17, not 16, and no longer names its own span in the rewritten
    text.
    """
    box, sender = bridge
    miles = Mention(start=0, length=len("@Miles Novak"), recipient="1784", handle="nka_bpumvg")
    ada = Mention(start=17, length=len("@Ada Lawson"), recipient="2222", handle=None)

    await sender.send(GROUP, "@Miles Novak and @Ada Lawson hi", mentions=(miles, ada))

    _room, body = box["calls"][0]
    assert body["text"] == "@nka_bpumvg and @Ada Lawson hi"
    assert body["mentions"] == [
        {"fbid": "1784", "offset": 0, "length": len("@nka_bpumvg")},
        {"fbid": "2222", "offset": 16, "length": len("@Ada Lawson")},
    ]
    offset, length = body["mentions"][1]["offset"], body["mentions"][1]["length"]
    assert body["text"][offset:offset + length] == "@Ada Lawson"


