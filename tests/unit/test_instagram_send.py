"""`nora.platform.instagram.send.InstagramSender` against the bridge's
`POST /threads/{thread_fbid}/messages`.

The stand-in bridge RECORDS EVERY REQUEST, because the properties that matter
here are about what reached the wire: that the text went as its own message
and not as a caption nothing would carry, that the room key is the short
thread id, and that a 409 never produces a retry. A fake that answered 200 to
everything without inspecting the body would let all three regress green.

It serves ONLY the new route, so a sender still on `/send` or `/send-media`
gets aiohttp's 404 and every success test below goes red. Its answers are the
bridge's own bodies, read from `tests/fixtures/instagram_bridge/messages_*`
(generated by the Go handlers). `test_instagram_bridge_contract.py` holds the
adapter to those fixtures' REQUESTS too.
"""

from __future__ import annotations

import base64
import json
from pathlib import Path

import pytest
from aiohttp import web
from aiohttp.test_utils import TestServer

from nora.domain.models import ConversationTarget
from nora.domain.ports import Mention, OutboundAttachment, OutboundQuote
from nora.platform.instagram.send import InstagramSender

ROOM = "1183780976338188"
GROUP = ConversationTarget("instagram", ROOM, "group")
DM = ConversationTarget("instagram", ROOM, "dm")
PNG = OutboundAttachment(content=b"\x89PNG\r\n", media_type="image/png", filename="a.png")


_FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "instagram_bridge"


def _fixture(name: str) -> dict:
    return json.loads((_FIXTURES / name).read_text())


# The bridge's own answers, by status: its 200 body, and the envelope it sends
# with each failure status.
_OK_BODY = _fixture("messages_text_ok.json")["body"]
_ENVELOPES = {
    fx["status"]: fx["body"]
    for fx in map(_fixture, [
        "messages_checkpointed_409.json", "messages_reconnecting_503.json",
        "messages_too_long_413.json", "messages_internal_500.json",
        "messages_no_message_id_502.json",
    ])
}


def _kind(body: dict) -> str:
    """Which message a recorded body is: `text` or `media`."""
    return "media" if "media" in body else "text"


@pytest.fixture
async def bridge():
    """`(box, sender)`. `box["calls"]` is `[(room, body), …]` in order."""
    box: dict = {"status": 200, "calls": [], "body": dict(_OK_BODY)}

    async def handler(request: web.Request) -> web.Response:
        box["calls"].append((request.match_info["thread_fbid"], await request.json()))
        if box["status"] != 200:
            envelope = _ENVELOPES.get(
                box["status"], {"error": {"code": "internal", "message": "x"}},
            )
            return web.json_response(envelope, status=box["status"])
        return web.json_response(box["body"])

    app = web.Application()
    app.router.add_post("/threads/{thread_fbid}/messages", handler)
    server = TestServer(app)
    await server.start_server()
    yield box, InstagramSender(str(server.make_url("")).rstrip("/"))
    await server.close()


# --- the text path -----------------------------------------------------------


async def test_a_plain_send_posts_the_short_room_id_and_the_text(bridge):
    box, sender = bridge

    result = await sender.send(GROUP, "hello")

    assert result.ok is True
    assert box["calls"] == [(ROOM, {"text": "hello"})]


async def test_the_platforms_own_sent_timestamp_is_reported(bridge):
    """What a later reply's quote resolves against."""
    _box, sender = bridge

    result = await sender.send(GROUP, "hello")

    assert result.timestamp == _OK_BODY["timestamp_ms"]


async def test_a_missing_timestamp_does_not_turn_a_delivered_send_into_a_failure(bridge):
    box, sender = bridge
    box["body"] = {"id": _OK_BODY["id"]}

    result = await sender.send(GROUP, "hello")

    assert result.ok is True
    assert result.timestamp is None


# --- the media path: the caption inversion -----------------------------------


async def test_text_and_media_are_TWO_calls_and_the_text_goes_FIRST(bridge):
    """The inversion against WhatsApp. `SendMediaRequest` has no text field of
    any kind, so WhatsApp's caption-on-the-first-attachment shape would drop
    the words silently, with a 200 on every call."""
    box, sender = bridge

    result = await sender.send(GROUP, "look at this", attachments=(PNG,))

    assert result.ok is True
    assert [_kind(body) for _, body in box["calls"]] == ["text", "media"]
    assert box["calls"][0][1]["text"] == "look at this"


async def test_send_media_carries_NO_caption_field(bridge):
    """The wire has nowhere to put one and the bridge ignores it. A caption
    key here would be a field that reads like it works."""
    box, sender = bridge

    await sender.send(GROUP, "look", attachments=(PNG,))

    _room, media_body = box["calls"][1]
    assert "caption" not in media_body and "caption" not in media_body["media"]
    assert "text" not in media_body


async def test_the_attachment_bytes_ride_base64_with_their_declared_type(bridge):
    box, sender = bridge

    await sender.send(GROUP, "look", attachments=(PNG,))

    room, media_body = box["calls"][1]
    media = media_body["media"]
    assert base64.b64decode(media["data_base64"]) == b"\x89PNG\r\n"
    assert media["mimetype"] == "image/png"
    assert media["filename"] == "a.png"
    assert room == ROOM


async def test_a_failed_TEXT_send_does_not_then_post_the_media(bridge):
    """The words did not land. Posting the image anyway would put it in the
    room with nothing explaining it, and would report the text's failure as a
    success."""
    box, sender = bridge
    box["status"] = 500

    result = await sender.send(GROUP, "look", attachments=(PNG,))

    assert result.ok is False
    assert [_kind(body) for _, body in box["calls"]] == ["text"]


async def test_an_attachment_with_no_text_skips_the_text_call(bridge):
    box, sender = bridge

    result = await sender.send(GROUP, "", attachments=(PNG,))

    assert result.ok is True
    assert [_kind(body) for _, body in box["calls"]] == ["media"]


