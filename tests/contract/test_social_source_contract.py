"""One suite, every implementation of `SocialSource`.

The port has two implementations, `InstagramSocialSource` and
`FakeSocialSource`, so both are held to the same answers here (AGENTS.md: a
port never gains a second implementation without a shared contract suite).
The poller's tests drive the fake, and they are only evidence about
production if the fake answers the way the adapter does.

Each arm is built over the SAME world, from its own inputs: the Instagram arm
from the bridge's own bodies (`tests/fixtures/instagram_bridge/*.json`,
generated by the Go handlers) over a local server, the fake from the values
those bodies carry. One account, `10000001`, with a story marker and counts
and no story up. Every id is synthetic.
"""

from __future__ import annotations

import json
from collections.abc import AsyncIterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import pytest
from aiohttp import web
from aiohttp.test_utils import TestServer

from nora.domain.ports import SocialSource
from nora.domain.social_stream import (
    Account,
    Failed,
    FailureKind,
    Probe,
    StorySnapshot,
)
from nora.infra.social.instagram_source import InstagramSocialSource
from nora.testing import FakeSocialSource

_FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "instagram_bridge"
_IGID = "10000001"
_ACCOUNT = Account(id=_IGID)
_PROBE = Probe(
    latest_reel_media=1700000000, media_count=42, total_clips_count=2,
    counts_available=True,
)


def _fixture(name: str) -> dict[str, Any]:
    return json.loads((_FIXTURES / name).read_text())


@dataclass
class _Bridge:
    """Answers each route with its fixture, and `/health` with a session."""

    answers: dict[str, dict[str, Any]] = field(default_factory=lambda: {
        "account": _fixture("account_ok.json"),
        "story": _fixture("story_not_found.json"),
    })
    session: str = "authenticated"

    def app(self) -> web.Application:
        app = web.Application()

        async def health(_: web.Request) -> web.Response:
            return web.json_response({"ok": True, "session": self.session})

        def route(name: str) -> Any:
            async def handler(_: web.Request) -> web.Response:
                fx = self.answers[name]
                return web.json_response(fx["body"], status=fx["status"])
            return handler

        app.router.add_get("/health", health)
        app.router.add_get("/accounts/{igid}", route("account"))
        app.router.add_get("/accounts/{igid}/story", route("story"))
        return app


class _Arm:
    """One implementation and the means to put its world in a state."""

    source: SocialSource

    def unknown_account(self) -> None: ...

    def checkpoint(self) -> None: ...

    def rotate_story_query(self) -> None: ...


class _InstagramArm(_Arm):
    def __init__(self, bridge: _Bridge, source: InstagramSocialSource) -> None:
        self.bridge = bridge
        self.source = source

    def unknown_account(self) -> None:
        self.bridge.answers["account"] = _fixture("account_not_found_404.json")

    def checkpoint(self) -> None:
        self.bridge.session = "checkpointed"
        self.bridge.answers["account"] = _fixture("account_checkpointed_409.json")
        self.bridge.answers["story"] = _fixture("story_checkpointed_409.json")

    def rotate_story_query(self) -> None:
        self.bridge.answers["story"] = _fixture("story_stale_query_501.json")


class _FakeArm(_Arm):
    def __init__(self) -> None:
        self.fake = FakeSocialSource()
        self.fake.probes[_IGID] = _PROBE
        self.fake.stories[_IGID] = StorySnapshot(found=False)
        self.source = self.fake

    def unknown_account(self) -> None:
        del self.fake.probes[_IGID]

    def checkpoint(self) -> None:
        self.fake.checkpointed = True

    def rotate_story_query(self) -> None:
        self.fake.stories[_IGID] = Failed(FailureKind.STALE_QUERY, "stale_query")


@pytest.fixture(params=["fake", "instagram"])
async def arm(request: Any) -> AsyncIterator[_Arm]:
    if request.param == "fake":
        yield _FakeArm()
        return
    bridge = _Bridge()
    async with TestServer(bridge.app()) as server:
        yield _InstagramArm(
            bridge, InstagramSocialSource(base_url=str(server.make_url("")), timeout_seconds=5),
        )


def test_both_satisfy_the_port() -> None:
    assert isinstance(FakeSocialSource(), SocialSource)
    assert isinstance(InstagramSocialSource(base_url="http://bridge.invalid"), SocialSource)


async def test_a_probe_reads_the_marker_and_both_counts(arm: _Arm) -> None:
    assert await arm.source.probe(account=_ACCOUNT) == _PROBE


async def test_no_story_up_is_a_completed_read_that_found_nothing(arm: _Arm) -> None:
    assert await arm.source.story(account=_ACCOUNT) == StorySnapshot(found=False)


async def test_an_account_the_platform_does_not_know_is_not_found(arm: _Arm) -> None:
    arm.unknown_account()
    got = await arm.source.probe(account=_ACCOUNT)
    assert isinstance(got, Failed) and got.kind is FailureKind.NOT_FOUND


async def test_a_healthy_session_says_so(arm: _Arm) -> None:
    assert await arm.source.healthy() is True


async def test_a_checkpointed_session_halts_every_read_and_is_not_healthy(arm: _Arm) -> None:
    arm.checkpoint()
    for got in (
        await arm.source.probe(account=_ACCOUNT), await arm.source.story(account=_ACCOUNT),
    ):
        assert isinstance(got, Failed) and got.kind is FailureKind.HALT
    assert await arm.source.healthy() is False


async def test_a_rotated_story_query_halts_that_read_only(arm: _Arm) -> None:
    """The login is fine: the probe still answers."""
    arm.rotate_story_query()
    got = await arm.source.story(account=_ACCOUNT)
    assert isinstance(got, Failed) and got.kind is FailureKind.STALE_QUERY
    assert await arm.source.probe(account=_ACCOUNT) == _PROBE
