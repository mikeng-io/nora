"""Alembic's two jobs: build the schema from nothing, and detect drift.

`alembic check` is NOT the schema gate — see tests/infra/test_schema_parity.py.
What it is good for is column presence, column type and server defaults, and
that is all this file claims for it.

The SQLite-era per-revision batch-rebuild tests (0002/0003/0004) are gone with
the squash to one Postgres-native baseline (design/20 §2): there is no batch
mode on Postgres and no chain to walk.
"""

from __future__ import annotations

import uuid

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from nora.infra.sql.migrations_runner import (
    alembic_config,
    current_revision,
    head_revision,
    run_migrations,
    sync_url_for,
)

ALEMBIC_INI = __import__("pathlib").Path(__file__).resolve().parents[2] / "alembic.ini"


def _messages_ddl(url: str) -> str:
    engine = sa.create_engine(sync_url_for(url))
    try:
        with engine.connect() as conn:
            checks = conn.execute(sa.text(
                "SELECT pg_get_constraintdef(oid) FROM pg_constraint "
                "WHERE conrelid = 'messages'::regclass AND contype = 'c'"
            )).scalars().all()
    finally:
        engine.dispose()
    return " ".join(checks)


def test_upgrade_head_builds_the_schema_from_nothing(pg_url):
    run_migrations(pg_url)
    assert "conversation_type" in _messages_ddl(pg_url)


def test_upgrade_head_reaches_the_head_revision(pg_url):
    run_migrations(pg_url)
    assert current_revision(pg_url) == head_revision()


def test_upgrade_is_idempotent(pg_url):
    run_migrations(pg_url)
    run_migrations(pg_url)
    assert current_revision(pg_url) == head_revision()


def test_a_migrated_database_passes_alembic_check(pg_url):
    """Also the proof that `include_object` suppresses the phantom index pair:
    without the hook this raises on every run because `idx_messages_conv_ts`'s
    `ts DESC` reflects as a plain column and autogenerate reports drift."""
    run_migrations(pg_url)
    command.check(alembic_config(pg_url))     # raises if drift is detected


def test_alembic_check_detects_a_missing_column(pg_url, monkeypatch):
    """Proof the check gate is wired to real metadata and not a no-op."""
    from nora.infra.sql import schema

    run_migrations(pg_url)

    trimmed = sa.MetaData()
    sa.Table(
        "messages", trimmed,
        *[c._copy() for c in schema.MESSAGES.columns if c.name != "raw_json"],
    )
    monkeypatch.setattr(schema, "METADATA", trimmed)
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(alembic_config(pg_url))


def test_the_x_db_override_redirects_the_target(pg_url, pg_admin):
    """`-x db=` overrides the target with a full URL, so a command meant for a
    scratch database never runs against the one the Config carries. Build a
    second, empty database, upgrade THAT via the override, and confirm the
    Config's own database was left untouched."""
    import psycopg

    scratch = "t_" + uuid.uuid4().hex
    with psycopg.connect(pg_admin.dsn(pg_admin.maintenance_db), autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{scratch}"')
    scratch_sync = (
        f"postgresql+psycopg://{pg_admin.user}:{pg_admin.password}"
        f"@{pg_admin.host}:{pg_admin.port}/{scratch}"
    )
    try:
        cfg = alembic_config(pg_url)          # config points at pg_url…
        cfg.cmd_opts = type("O", (), {"x": [f"db={scratch_sync}"]})()
        command.upgrade(cfg, "head")          # …but the override sends it to scratch

        # scratch got the schema; pg_url (the Config's own url) did not.
        assert current_revision(scratch_sync) == head_revision()
        assert current_revision(pg_url) is None
    finally:
        with psycopg.connect(
            pg_admin.dsn(pg_admin.maintenance_db), autocommit=True
        ) as conn:
            conn.execute(
                "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                "WHERE datname = %s AND pid <> pg_backend_pid()",
                (scratch,),
            )
            conn.execute(f'DROP DATABASE IF EXISTS "{scratch}"')


def test_alembic_ini_does_not_point_at_the_production_database():
    """A bare `uv run alembic ...` must not be able to touch the production
    `nora` database: Alembic creates alembic_version before most commands report
    anything, so it mutates first and complains second."""
    ini = ALEMBIC_INI.read_text()
    url_lines = [ln for ln in ini.splitlines() if ln.strip().startswith("sqlalchemy.url")]
    assert url_lines, "alembic.ini has no sqlalchemy.url"
    assert all("scratch" in ln for ln in url_lines), url_lines
    assert not any("nora-db" in ln for ln in url_lines), url_lines
