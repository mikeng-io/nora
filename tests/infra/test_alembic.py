"""Alembic's two jobs: build the schema from nothing, and detect drift.

`alembic check` is NOT the schema gate — see tests/infra/test_schema_parity.py.
What it is good for is column presence, column type and server defaults, and
that is all this file claims for it.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path
from types import SimpleNamespace

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from nora.infra.sql.migrations_runner import (
    alembic_config,
    current_revision,
    head_revision,
    run_migrations,
)

PROD_DB = Path(__file__).resolve().parents[2] / "data" / "messages.db"
ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"


def _table_sql(path: Path) -> str:
    with sqlite3.connect(path) as conn:
        return conn.execute(
            "SELECT sql FROM sqlite_master WHERE type='table' AND name='messages'"
        ).fetchone()[0]


def test_upgrade_head_builds_the_schema_from_nothing(tmp_path):
    path = tmp_path / "new.db"
    run_migrations(path)
    sql = _table_sql(path)
    assert "AUTOINCREMENT" in sql
    assert "CHECK (conversation_type IN ('group','dm'))" in sql


def test_upgrade_head_reaches_the_head_revision(tmp_path):
    path = tmp_path / "new.db"
    run_migrations(path)
    assert current_revision(path) == head_revision()


def test_upgrade_is_idempotent(tmp_path):
    path = tmp_path / "new.db"
    run_migrations(path)
    run_migrations(path)
    assert current_revision(path) == head_revision()


def test_a_migrated_database_passes_alembic_check(tmp_path):
    """Also the proof that `include_object` suppresses the phantom index pair:
    without the hook this raises on every run, forever. Verified 2026-08-05."""
    path = tmp_path / "new.db"
    run_migrations(path)
    command.check(alembic_config(path))     # raises if drift is detected


def test_a_copy_of_the_production_database_passes_alembic_check(tmp_path):
    """The trap this exists for: naive metadata passes against a fresh database
    and fails against production, because SQLite's INTEGER PRIMARY KEY
    AUTOINCREMENT has notnull=0. Run against a COPY, never a fresh database
    only, and never against the live file."""
    if not PROD_DB.exists():
        pytest.skip("no production database on this host")
    copy = tmp_path / "prod-copy.db"
    # `shutil.copy` is WRONG for a WAL database: it takes only the main file
    # and leaves the -wal sidecar behind, so the copy reflects whatever was
    # last checkpointed rather than the real schema. That silently checked a
    # STALE schema — a migration applied but not yet checkpointed was invisible
    # here, which can produce a false PASS as easily as a false failure.
    # SQLite's backup API is WAL-aware and does not mutate the source.
    with sqlite3.connect(PROD_DB) as src, sqlite3.connect(copy) as dst:
        src.backup(dst)
    with sqlite3.connect(copy) as conn:     # stamped in Task 10; stamp the copy here
        conn.execute(
            "CREATE TABLE IF NOT EXISTS alembic_version "
            "(version_num VARCHAR(32) NOT NULL)"
        )
        conn.execute("DELETE FROM alembic_version")
        conn.execute("INSERT INTO alembic_version VALUES (?)", (head_revision(),))
    command.check(alembic_config(copy))


def test_alembic_check_detects_a_missing_column(tmp_path, monkeypatch):
    """Proof the check gate is wired to real metadata and not a no-op."""
    import sqlalchemy as sa

    from nora.infra.sql import schema

    path = tmp_path / "new.db"
    run_migrations(path)

    trimmed = sa.MetaData()
    sa.Table(
        "messages", trimmed,
        *[c._copy() for c in schema.MESSAGES.columns if c.name != "raw_json"],
        sqlite_autoincrement=True,
    )
    monkeypatch.setattr(schema, "METADATA", trimmed)
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(alembic_config(path))


def _index_xinfo(path: Path, index: str) -> list[tuple]:
    with sqlite3.connect(path) as conn:
        return conn.execute(f"PRAGMA index_xinfo({index})").fetchall()


def _columns(path: Path) -> list[str]:
    with sqlite3.connect(path) as conn:
        return [r[1] for r in conn.execute("PRAGMA table_info(messages)")]


def test_0003_adds_quoted_ts_without_disturbing_the_ts_desc_index(tmp_path):
    """The table-rebuild trap, asserted rather than trusted.

    A SQLite table rebuild recreates the indexes from *reflection*, and
    `schema.py` documents that reflection is exactly what cannot see
    `idx_messages_conv_ts`'s `ts DESC`. A rebuild therefore silently downgrades
    the one index that matters to ASC — `alembic check` reports nothing, and
    `recent`'s `ORDER BY ts DESC` goes from an index scan to a sort.

    This asserts the index SHAPE either side of the migration rather than the
    form of the call, which is what makes it catch a rebuild however it is
    reached. Probed 2026-08-06: swapping `op.add_column` for
    `op.batch_alter_table(..., recreate="always")` turns `ts`'s xinfo `desc`
    flag from 1 to 0 and this goes red. (A *bare* `batch_alter_table` does not:
    `recreate="auto"` skips the copy for a plain ADD COLUMN — see 0003's
    docstring, which corrects 0002's blanket phrasing.)
    """
    path = tmp_path / "upgrade.db"
    command.upgrade(alembic_config(path), "0002_person_id")
    before = _index_xinfo(path, "idx_messages_conv_ts")
    named = {r[2]: r for r in before if r[2] is not None}
    assert named["ts"][3] == 1, "precondition: ts is already DESC at 0002"
    assert "quoted_ts" not in _columns(path)

    command.upgrade(alembic_config(path), "head")

    assert _index_xinfo(path, "idx_messages_conv_ts") == before
    assert _columns(path)[-1] == "quoted_ts", "ADD COLUMN appends; it must be last"


def test_0003_on_a_copy_of_the_production_database_preserves_ts_desc(tmp_path):
    """Against a COPY of the live file, never the live file — and via SQLite's
    WAL-aware backup API rather than `shutil.copy`, for the reason
    `test_a_copy_of_the_production_database_passes_alembic_check` documents."""
    if not PROD_DB.exists():
        pytest.skip("no production database on this host")
    copy = tmp_path / "prod-copy.db"
    with sqlite3.connect(PROD_DB) as src, sqlite3.connect(copy) as dst:
        src.backup(dst)
    before = _index_xinfo(copy, "idx_messages_conv_ts")
    command.upgrade(alembic_config(copy), "head")
    assert _index_xinfo(copy, "idx_messages_conv_ts") == before
    assert _columns(copy)[-1] == "quoted_ts"


def test_0003_downgrade_also_leaves_the_index_alone(tmp_path):
    path = tmp_path / "roundtrip.db"
    run_migrations(path)
    before = _index_xinfo(path, "idx_messages_conv_ts")
    command.downgrade(alembic_config(path), "0002_person_id")
    assert "quoted_ts" not in _columns(path)
    assert _index_xinfo(path, "idx_messages_conv_ts") == before


def test_alembic_ini_does_not_point_at_the_production_database():
    """A bare `uv run alembic ...` must not be able to touch data/messages.db:
    Alembic creates alembic_version before most commands report anything, so it
    mutates first and complains second. This has happened once already."""
    ini = ALEMBIC_INI.read_text()
    url_lines = [ln for ln in ini.splitlines() if ln.strip().startswith("sqlalchemy.url")]
    assert url_lines, "alembic.ini has no sqlalchemy.url"
    assert not any("data/messages.db" in ln for ln in url_lines), url_lines


def test_the_x_db_override_is_wired(tmp_path):
    """The override the ini's comment documents must actually work — it was
    accepted-but-ignored before, which is what made the default dangerous."""
    scratch = tmp_path / "override.db"
    unused = tmp_path / "unused.db"
    cfg = alembic_config(unused)
    cfg.cmd_opts = SimpleNamespace(x=[f"db={scratch}"])
    command.upgrade(cfg, "head")
    assert scratch.exists(), "-x db= was ignored; the override is not wired"
    assert not unused.exists()
