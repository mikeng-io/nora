def test_the_x_db_override_redirects_the_target(pg_admin):
    """`-x db=` overrides the target with a full URL, so a command meant for a
    scratch database never runs against the one the Config carries. Build TWO
    empty databases, upgrade one via the override, and confirm the Config's own
    was left untouched.

    **Both databases are created here rather than taking `pg_url`**, and that
    is a requirement rather than a style choice: `pg_url` hands out a CLONE of
    an already-migrated template, so "untouched" cannot be expressed as
    `current_revision(...) is None` — the fixture's database arrives at head.
    This test is the one place in the suite that genuinely needs an EMPTY
    database, so it makes its own."""
    import psycopg

    scratch = "t_" + uuid.uuid4().hex
    target = "t_" + uuid.uuid4().hex
    with psycopg.connect(pg_admin.dsn(pg_admin.maintenance_db), autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{scratch}"')
        conn.execute(f'CREATE DATABASE "{target}"')
    pg_url = (
        f"postgresql+asyncpg://{pg_admin.user}:{pg_admin.password}"
        f"@{pg_admin.host}:{pg_admin.port}/{target}"
    )
    scratch_sync = (
        f"postgresql+psycopg://{pg_admin.user}:{pg_admin.password}"
        f"@{pg_admin.host}:{pg_admin.port}/{scratch}"
    )
    try:
        cfg = alembic_config(pg_url)          # config points at pg_url…
        cfg.cmd_opts = type("O", (), {"x": [f"db={scratch_sync}"]})()
        command.upgrade(cfg, "head")          # …but the override sends it to scratch

        # scratch got the schema; pg_url (the Config's own url) did not.
        assert current_revision(scratch_sync) == head_revision()
        assert current_revision(pg_url) is None
    finally:
        with psycopg.connect(
            pg_admin.dsn(pg_admin.maintenance_db), autocommit=True
        ) as conn:
            for dbname in (scratch, target):
                conn.execute(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = %s AND pid <> pg_backend_pid()",
                    (dbname,),
                )
                conn.execute(f'DROP DATABASE IF EXISTS "{dbname}"')


def test_alembic_ini_does_not_point_at_the_production_database():
    """A bare `uv run alembic ...` must not be able to touch the production
    `nora` database: Alembic creates alembic_version before most commands report
    anything, so it mutates first and complains second."""
    ini = ALEMBIC_INI.read_text()
    url_lines = [ln for ln in ini.splitlines() if ln.strip().startswith("sqlalchemy.url")]
    assert url_lines, "alembic.ini has no sqlalchemy.url"
    assert all("scratch" in ln for ln in url_lines), url_lines
    assert not any("nora-db" in ln for ln in url_lines), url_lines


def test_pre_0033_row_inserted_before_kind_columns_gets_the_reminder_default(pg_url):
    """Migration compatibility, against the REAL migration path: a row written
    BEFORE 0033 (no `kind`, no `payload` — the raw INSERT omits both) upgrades
    through the migration and reads back with `kind='reminder'`,
    `payload=NULL`. The server default does the backfill; no rewrite pass is
    needed."""
    from alembic import command as alembic_command

    from nora.infra.sql.migrations_runner import alembic_config

    run_migrations(pg_url)
    # Take the schema back to 0032, before `kind` and `payload` (DEC-139).
    alembic_command.downgrade(alembic_config(pg_url), "0032_media_objects")

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            conn.execute(sa.text(
                "INSERT INTO reminders (id, requester_person_id, platform, "
                "conversation_id, conversation_type, text, created_at, due_at, "
                "state, recurrence, occurrence) VALUES "
                "(:id, 'miles', 'signal', 'conv-1', 'group', '記得食藥', "
                "now(), now() + interval '1 hour', 'pending', 'none', 0)"
            ), {"id": str(uuid.uuid4())})
            conn.commit()
    finally:
        engine.dispose()

    # Bring 0033 back: `kind` gains its server default `'reminder'`.
    run_migrations(pg_url)

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            row = conn.execute(sa.text(
                "SELECT kind, payload FROM reminders WHERE text = '記得食藥'"
            )).one()
    finally:
        engine.dispose()
    assert row.kind == "reminder"
    assert row.payload is None


