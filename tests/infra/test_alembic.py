def test_alembic_check_detects_a_missing_column(pg_url, monkeypatch):
    """Proof the check gate is wired to real metadata and not a no-op."""
    from nora.infra.sql import schema

    run_migrations(pg_url)

    trimmed = sa.MetaData()
    sa.Table(
        "messages", trimmed,
        *[c._copy() for c in schema.MESSAGES.columns if c.name != "raw_json"],
    )
    monkeypatch.setattr(schema, "METADATA", trimmed)
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(alembic_config(pg_url))


def test_the_x_db_override_redirects_the_target(pg_admin):
    """`-x db=` overrides the target with a full URL, so a command meant for a
    scratch database never runs against the one the Config carries. Build TWO
    empty databases, upgrade one via the override, and confirm the Config's own
    was left untouched.

    **Both databases are created here rather than taking `pg_url`**, and that
    is a requirement rather than a style choice: since 2026-08-21 `pg_url`
    hands out a CLONE of an already-migrated template, so "untouched" could no
    longer be expressed as `current_revision(...) is None` — the fixture's
    database arrives at head. This test is the one place in the suite that
    genuinely needs an EMPTY database, so it makes its own."""
    import psycopg

    scratch = "t_" + uuid.uuid4().hex
    target = "t_" + uuid.uuid4().hex
    with psycopg.connect(pg_admin.dsn(pg_admin.maintenance_db), autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{scratch}"')
        conn.execute(f'CREATE DATABASE "{target}"')
    pg_url = (
        f"postgresql+asyncpg://{pg_admin.user}:{pg_admin.password}"
        f"@{pg_admin.host}:{pg_admin.port}/{target}"
    )
    scratch_sync = (
        f"postgresql+psycopg://{pg_admin.user}:{pg_admin.password}"
        f"@{pg_admin.host}:{pg_admin.port}/{scratch}"
    )
    try:
        cfg = alembic_config(pg_url)          # config points at pg_url…
        cfg.cmd_opts = type("O", (), {"x": [f"db={scratch_sync}"]})()
        command.upgrade(cfg, "head")          # …but the override sends it to scratch

        # scratch got the schema; pg_url (the Config's own url) did not.
        assert current_revision(scratch_sync) == head_revision()
        assert current_revision(pg_url) is None
    finally:
        with psycopg.connect(
            pg_admin.dsn(pg_admin.maintenance_db), autocommit=True
        ) as conn:
            for dbname in (scratch, target):
                conn.execute(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = %s AND pid <> pg_backend_pid()",
                    (dbname,),
                )
                conn.execute(f'DROP DATABASE IF EXISTS "{dbname}"')


def test_alembic_ini_does_not_point_at_the_production_database():
    """A bare `uv run alembic ...` must not be able to touch the production
    `nora` database: Alembic creates alembic_version before most commands report
    anything, so it mutates first and complains second."""
    ini = ALEMBIC_INI.read_text()
    url_lines = [ln for ln in ini.splitlines() if ln.strip().startswith("sqlalchemy.url")]
    assert url_lines, "alembic.ini has no sqlalchemy.url"
    assert all("scratch" in ln for ln in url_lines), url_lines
    assert not any("nora-db" in ln for ln in url_lines), url_lines


def test_pre_0033_row_inserted_before_kind_columns_gets_the_reminder_default(pg_url):
    """03-reminder-schema's migration compatibility claim, against the REAL
    migration path: a row written BEFORE 0033 (no `kind`, no `payload` — the
    raw INSERT omits both) upgrades through the migration and reads back with
    `kind='reminder'`, `payload=NULL`. The server default does the backfill;
    no rewrite pass is needed."""
    from alembic import command as alembic_command

    from nora.infra.sql.migrations_runner import alembic_config

    run_migrations(pg_url)
    # Take the schema back to 0032, the state a pre-DEC-139 database had.
    alembic_command.downgrade(alembic_config(pg_url), "0032_media_objects")

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            conn.execute(sa.text(
                "INSERT INTO reminders (id, requester_person_id, platform, "
                "conversation_id, conversation_type, text, created_at, due_at, "
                "state, recurrence, occurrence) VALUES "
                "(:id, 'miles', 'signal', 'conv-1', 'group', '記得食藥', "
                "now(), now() + interval '1 hour', 'pending', 'none', 0)"
            ), {"id": str(uuid.uuid4())})
            conn.commit()
    finally:
        engine.dispose()

    # Bring 0033 back: `kind` gains its server default `'reminder'`.
    run_migrations(pg_url)

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            row = conn.execute(sa.text(
                "SELECT kind, payload FROM reminders WHERE text = '記得食藥'"
            )).one()
    finally:
        engine.dispose()
    assert row.kind == "reminder"
    assert row.payload is None


def test_0062_backfills_source_fold_on_a_pre_existing_revision(pg_url):
    """design/dreamer-agent-loop/26-standing.md, dated section 2026-09-25: a
    `standing_revision` row written before the `source` column existed is,
    by construction, a fold — `SqlStandingStore.write` had exactly one
    caller shape until this migration's sibling method landed. The server
    default does the backfill in the same `ADD COLUMN` statement; no rewrite
    pass is needed, mirroring `test_pre_0033_row_inserted_before_kind_
    columns_gets_the_reminder_default` one migration family over.
    """
    from alembic import command as alembic_command

    run_migrations(pg_url)
    alembic_command.downgrade(alembic_config(pg_url), "0061_video_readings")

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            conn.execute(sa.text(
                "INSERT INTO standing_revision "
                "(platform, conversation_id, body, fold_count, updated_at) "
                "VALUES ('signal', 'pre-0062', 'a position', 1, 1000)"
            ))
            conn.commit()
    finally:
        engine.dispose()

    run_migrations(pg_url)

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            source = conn.execute(sa.text(
                "SELECT source FROM standing_revision "
                "WHERE conversation_id = 'pre-0062'"
            )).scalar_one()
    finally:
        engine.dispose()
    assert source == "fold"


def test_0062_downgrade_drops_the_source_column_and_its_check(pg_url):
    """The falsification side: downgrading past 0062 removes both the
    constraint and the column, and the migration chain still reaches the
    same head afterward when re-applied — `run_migrations` is idempotent
    per `test_upgrade_is_idempotent`, so a downgrade/upgrade round trip
    proves the pair is reversible rather than merely additive."""
    from alembic import command as alembic_command

    run_migrations(pg_url)
    alembic_command.downgrade(alembic_config(pg_url), "0061_video_readings")

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            columns = conn.execute(sa.text(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_name = 'standing_revision'"
            )).scalars().all()
    finally:
        engine.dispose()
    assert "source" not in columns

    run_migrations(pg_url)
    assert current_revision(pg_url) == head_revision()


def test_0060_backfills_the_platform_handle_from_raw_json(pg_url):
    """design/message-edits/01 §2: an edit names its target by the platform's
    handle, and a message stored BEFORE 0060 had it only inside `raw_json`.
    Without the backfill, every edit to a message sent before the deploy is an
    orphan. Each platform keeps it under its own key — `id` for WhatsApp and
    Discord (Discord's is a JSON NUMBER), `message_id` for Instagram — and
    Signal has none. A row whose `raw_json` is not JSON must not abort the
    migration, and Nora's own rows are not envelopes."""
    from alembic import command as alembic_command

    run_migrations(pg_url)
    alembic_command.downgrade(alembic_config(pg_url), "0059_standing_revision")

    rows = [
        ("whatsapp", '{"id": "3EB0A", "type": "message"}', 0),
        ("discord", '{"id": 1234567890123456789, "content": "hi"}', 0),
        ("instagram", '{"message_id": "mid.$m", "kind": "message"}', 0),
        ("signal", '{"envelope": {"timestamp": 1}}', 0),
        ("whatsapp", "not json at all", 0),
        ("whatsapp", '{"id": "nora-own"}', 1),
    ]
    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            for i, (platform, raw, is_nora) in enumerate(rows):
                conn.execute(sa.text(
                    "INSERT INTO messages (platform, conversation_id, "
                    "conversation_type, sender_id, ts, body, is_nora, raw_json) "
                    "VALUES (:p, 'c', 'group', 's', :ts, 'b', :n, :raw)"
                ), {"p": platform, "ts": i, "n": is_nora, "raw": raw})
            conn.commit()
    finally:
        engine.dispose()

    run_migrations(pg_url)

    engine = sa.create_engine(sync_url_for(pg_url))
    try:
        with engine.connect() as conn:
            got = conn.execute(sa.text(
                "SELECT platform_message_id FROM messages ORDER BY ts"
            )).scalars().all()
    finally:
        engine.dispose()
    assert got == ["3EB0A", "1234567890123456789", "mid.$m", None, None, None]
