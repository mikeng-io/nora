"""Write the generated documentation views from frontmatter (docs/engineering/documents.md).

- docs/README.md: every document by class, with its subject;
- docs/design/README.md: the bundle map, meaning bundle, subject, code area and tracker;
- docs/glossary.md: every owned term, with its definition, plain word and owner.

usage: python -m scripts.generate_docs_index --write | --check
"""

from __future__ import annotations

import sys
from pathlib import Path

from scripts.check_documents import CLASS_HOME, GENERATED, ROOT, documents, frontmatter

HEADER = "<!-- Generated by scripts/generate_docs_index.py from frontmatter. Do not edit. -->\n"


def _cell(value: object) -> str:
    return str(value or "").replace("|", "\\|").replace("\n", " ").strip()


def render(files: dict[str, str]) -> dict[str, str]:
    """The three generated views for a tree of documents, keyed by path."""
    metas = {
        path: meta
        for path, text in files.items()
        if path.startswith("docs/") and path not in GENERATED and (meta := frontmatter(text))
    }
    order = list(CLASS_HOME)
    index = ["# Documentation\n", HEADER, "| class | document | subject |", "|---|---|---|"]
    for path, meta in sorted(
        metas.items(), key=lambda item: (order.index(item[1].get("class", order[0]))
                                         if item[1].get("class") in order else len(order), item[0])
    ):
        index.append(f"| {_cell(meta.get('class'))} | [{path[5:]}]({path[5:]}) | {_cell(meta.get('subject'))} |")
    bundles = ["# Design\n", HEADER, "| bundle | subject | code area | tracked by |", "|---|---|---|---|"]
    for path, meta in sorted(metas.items()):
        parts = path.split("/")
        if len(parts) == 4 and parts[1] == "design" and parts[3] == "README.md":
            bundles.append(
                f"| [{parts[2]}]({parts[2]}/README.md) | {_cell(meta.get('subject'))} "
                f"| {_cell(meta.get('area'))} | {_cell(meta.get('tracked_by'))} |"
            )
    plain = {}
    for meta in metas.values():
        if isinstance(meta.get("plain"), dict):
            plain.update({str(k).lower(): v for k, v in meta["plain"].items()})
    terms = []
    for path, meta in metas.items():
        for entry in meta.get("owns") or []:
            for term, definition in (entry.items() if isinstance(entry, dict) else [(entry, "")]):
                terms.append((str(term), definition, path))
    glossary = ["# Glossary\n", HEADER, "| term | definition | plain word | owner |", "|---|---|---|---|"]
    for term, definition, path in sorted(terms, key=lambda t: t[0].lower()):
        glossary.append(
            f"| {_cell(term)} | {_cell(definition)} | {_cell(plain.get(term.lower()))} "
            f"| [{path[5:]}]({path[5:]}) |"
        )
    return {
        "docs/README.md": "\n".join(index) + "\n",
        "docs/design/README.md": "\n".join(bundles) + "\n",
        "docs/glossary.md": "\n".join(glossary) + "\n",
    }


def stale(root: Path, files: dict[str, str]) -> list[str]:
    """Generated files present on disk that differ from their regeneration."""
    return [
        path for path, text in render(files).items()
        if (root / path).exists() and (root / path).read_text(encoding="utf-8") != text
    ]


def main() -> int:
    mode = sys.argv[1:]
    files = documents()
    if mode == ["--write"]:
        for path, text in render(files).items():
            (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / path).write_text(text, encoding="utf-8")
        return 0
    if mode == ["--check"]:
        if found := stale(ROOT, files):
            print(f"stale generated documents; run --write: {found}", file=sys.stderr)
            return 1
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
