def extract_strings(data: bytes) -> str:
    ascii_runs = re.findall(rb"[\x20-\x7e\t]{6,}", data)
    utf16_runs = re.findall(rb"(?:[\x20-\x7e]\x00){6,}", data)
    parts = [r.decode("ascii") for r in ascii_runs]
    parts += [r.decode("utf-16-le", "replace") for r in utf16_runs]
    return "\n".join(parts)


# Printable runs of valid UTF-8, multi-byte sequences included: a CJK name
# inside a binary, or in a text file with one bad byte, is text the
# denylist can read (`extract_strings` is ASCII-only).
_UTF8_RUN = re.compile(
    rb"(?:[\x20-\x7e\t]|[\xc2-\xdf][\x80-\xbf]|[\xe0-\xef][\x80-\xbf]{2}"
    rb"|[\xf0-\xf4][\x80-\xbf]{3}){4,}"
)


def _utf16_text(data: bytes) -> str:
    """A UTF-16 blob decoded whole: by its BOM, else by where the NULs of
    its ASCII sit (odd offsets: little-endian)."""
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return data.decode("utf-16", "replace")
    head = data[:8192]
    le = head[1::2].count(0) >= head[0::2].count(0)
    return data.decode("utf-16-le" if le else "utf-16-be", "replace")


def readable_spellings(data: bytes, why: str, inner: list[str]) -> str:
    """Everything the scanner can read in a blob it could not decode as
    text, for the denylist alone: ASCII and UTF-16 strings, UTF-8 runs, the
    whole blob as UTF-16 when it is UTF-16, and whatever its containers
    yielded (`inner`, empty when they could not be opened)."""
    parts = [extract_strings(data)]
    parts += [r.decode("utf-8", "replace") for r in _UTF8_RUN.findall(data) if len(r) >= 6]
    if why == "utf16":
        parts.append(_utf16_text(data))
    return "\n".join(parts + list(inner))


def spellings_of(blob: bytes | None) -> str:
    """readable_spellings for an old version (a parent's copy)."""
    if blob is None:
        return ""
    text, why = _decode(blob)
    if text is not None:
        return text
    try:
        inner = expand_binary(blob)[0]
    except DecodeError:
        inner = []
    return readable_spellings(blob, why, inner)


def _tiff_has_gps(buf: bytes, base: int) -> bool:
    try:
        endian = buf[base : base + 2]
        if endian not in (b"II", b"MM"):
            return False
        bo = "little" if endian == b"II" else "big"
        off = int.from_bytes(buf[base + 4 : base + 8], bo)
        count = int.from_bytes(buf[base + off : base + off + 2], bo)
        for i in range(min(count, 512)):
            e = base + off + 2 + i * 12
            if int.from_bytes(buf[e : e + 2], bo) == 0x8825:
                gps_off = int.from_bytes(buf[e + 8 : e + 12], bo)
                gcount = int.from_bytes(buf[base + gps_off : base + gps_off + 2], bo)
                for j in range(min(gcount, 64)):
                    g = base + gps_off + 2 + j * 12
                    if int.from_bytes(buf[g : g + 2], bo) in (2, 4):  # GPSLatitude / GPSLongitude
                        return True
    except (IndexError, ValueError):
        return False
    return False


# An ISO 6709 point as QuickTime writes it, in `©xyz` or in the
# `com.apple.quicktime.location.ISO6709` metadata key: `+22.2831+114.1588/`.
_ISO6709_BYTES = re.compile(rb"[+-]\d{2}\.\d{2,}[+-]\d{3}\.\d{2,}(?:[+-]\d+(?:\.\d+)?)?/")


def _png_chunks(data: bytes):
    pos = 8
    while pos + 8 <= len(data):
        n = int.from_bytes(data[pos : pos + 4], "big")
        typ = data[pos + 4 : pos + 8]
        yield typ, data[pos + 8 : pos + 8 + n]
        pos += 12 + n
        if typ == b"IEND":
            return


def media_has_gps(data: bytes) -> bool:
    """EXIF GPS in a JPEG/TIFF or a PNG `eXIf` chunk, or an ISO 6709 point
    anywhere in the file (QuickTime `©xyz` or `mdta` location keys). A single
    photo taken at home is a residence."""
    for m in re.finditer(rb"Exif\x00\x00", data[: 1 << 20]):
        if _tiff_has_gps(data, m.end()):
            return True
    if data[:4] in (b"II*\x00", b"MM\x00*") and _tiff_has_gps(data, 0):
        return True
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        for typ, body in _png_chunks(data):
            if typ == b"eXIf" and (_tiff_has_gps(body, 0) or _tiff_has_gps(body, 6)):
                return True
    return bool(_ISO6709_BYTES.search(data))


class DecodeError(Exception):
    pass


# One blob's whole expansion shares one budget -- decompressed bytes across
# every member and every level, members opened, wall time -- and a push
# shares another, so many small members cannot each stay under a per-member
# cap and still cost minutes. Past any of them it is an ERROR.
MAX_MEMBERS = 2000
DECODE_SECONDS = 10.0
_BUDGET: dict = {}
_PUSH_DECODED = [0]


def _spend(nbytes: int) -> None:
    b = _BUDGET
    b["bytes"] -= nbytes
    _PUSH_DECODED[0] += nbytes
    if b["bytes"] < 0:
        raise DecodeError(f"expands past NORA_PII_DECODE_MAX={DECODE_MAX} bytes in total")
    if _PUSH_DECODED[0] > DECODE_PUSH_MAX:
        raise DecodeError(
            f"this run expanded past NORA_PII_DECODE_PUSH_MAX={DECODE_PUSH_MAX} bytes"
        )
    if time.monotonic() > b["deadline"]:
        raise DecodeError(f"expansion took longer than {DECODE_SECONDS:.0f} s")


def _bounded(dec, data: bytes) -> bytes:
    """Decompress within what is left of the blob's budget."""
    left = max(0, _BUDGET["bytes"])
    out = dec.decompress(data, left + 1)
    if len(out) > left:
        raise DecodeError(f"expands past NORA_PII_DECODE_MAX={DECODE_MAX} bytes in total")
    _spend(len(out))
    return out


def expand_binary(data: bytes, depth: int = 0) -> tuple[list[str], bool]:
    if depth == 0:
        _BUDGET.update(
            bytes=DECODE_MAX, members=MAX_MEMBERS, deadline=time.monotonic() + DECODE_SECONDS
        )
    return _expand(data, depth)


def _expand(data: bytes, depth: int) -> tuple[list[str], bool]:
    """(texts, gps) inside a binary: its printable strings; the text chunks of
    a PNG (tEXt, zTXt and iTXt, decompressed, UTF-8); the members of a zip
    (xlsx, docx, jar) and the payload of gzip, bzip2 and xz, each decoded or
    expanded again. Raises DecodeError when a container is corrupt or too
    big to open: that is an ERROR, never a skip."""
    texts = [extract_strings(data)]
    gps = media_has_gps(data)
    inner: list[bytes] = []
    try:
        if data[:8] == b"\x89PNG\r\n\x1a\n":
            for typ, body in _png_chunks(data):
                if typ == b"tEXt":
                    texts.append(body.replace(b"\x00", b" ").decode("latin-1"))
                elif typ == b"zTXt":
                    k, _, rest = body.partition(b"\x00")
                    z = _bounded(zlib.decompressobj(), rest[1:])
                    texts.append(k.decode("latin-1") + " " + z.decode("latin-1"))
                elif typ == b"iTXt":
                    k, _, rest = body.partition(b"\x00")
                    comp, rest = rest[0], rest[2:]
                    _lang, _, rest = rest.partition(b"\x00")
                    _tk, _, txt = rest.partition(b"\x00")
                    if comp:
                        txt = _bounded(zlib.decompressobj(), txt)
                    texts.append(k.decode("latin-1") + " " + txt.decode("utf-8", "replace"))
        elif data[:2] == b"\x1f\x8b":
            inner.append(_bounded(zlib.decompressobj(16 + zlib.MAX_WBITS), data))
        elif data[:3] == b"BZh":
            inner.append(_bounded(bz2.BZ2Decompressor(), data))
        elif data[:6] == b"\xfd7zXZ\x00":
            inner.append(_bounded(lzma.LZMADecompressor(), data))
        elif data[:4] == b"PK\x03\x04":
            with zipfile.ZipFile(io.BytesIO(data)) as zf:
                infos = zf.infolist()
                _BUDGET["members"] -= len(infos)
                if _BUDGET["members"] < 0:
                    raise DecodeError(f"more than {MAX_MEMBERS} archive members")
                if sum(i.file_size for i in infos) > _BUDGET["bytes"]:
                    raise DecodeError(
                        f"expands past NORA_PII_DECODE_MAX={DECODE_MAX} bytes in total"
                    )
                for i in infos:
                    if not i.is_dir():
                        texts.append(i.filename)
                        with zf.open(i) as fh:
                            member = fh.read(max(0, _BUDGET["bytes"]) + 1)
                        _spend(len(member))
                        inner.append(member)
    except (
        OSError,
        EOFError,
        ValueError,
        zlib.error,
        lzma.LZMAError,
        zipfile.BadZipFile,
        IndexError,
        RuntimeError,
        NotImplementedError,
    ) as exc:
        raise DecodeError(f"container could not be opened: {type(exc).__name__}") from exc
    for blob in inner:
        t, _ = _decode(blob)
        if t is not None:
            texts.append(t)
            gps = gps or bool(_ISO6709_BYTES.search(blob))
        elif depth < 2:
            sub, sub_gps = _expand(blob, depth + 1)
            texts += sub
            gps = gps or sub_gps
        else:
            raise DecodeError("containers nested more than two deep")
    return texts, gps


