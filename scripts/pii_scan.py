#!/usr/bin/env python3
"""Identifier detector for what is about to enter a commit (#283).

`5694a035` took the identifier gate out of the test suite because it re-read
every git object on every run (5.77 GB RSS, OOM). Its job moved here, where the
look is what a commit ADDS and the cost is seconds: the staged blobs
(pre-commit), the commit message and the author/committer identity
(commit-msg), and every commit a push introduces (pre-push, the backstop for a
commit made with --no-verify or before the hooks were installed).

Wired from `.githooks/` (installed by `make hooks`). Stdlib only, run with
`python3`, resolved against `git rev-parse --show-toplevel`, like the
commit-subject checker next to it.

Three verdicts, three exit codes, never merged:

    0  PASS   everything it was asked to look at, it looked at, and found nothing
    1  FAIL   it found something
    2  ERROR  it could not look (no denylist, undecodable blob, symlink, a judge
              that did not answer). An ERROR is never a PASS.

What it knows, in the order it is applied:

1. **The private denylist** — the real values, from the deployment's
   `identity.toml` and the scrub map, generated by
   `scripts/pii_denylist_build.py` into a file OUTSIDE the repo
   (`~/.config/nora/pii-denylist.txt`, or `$NORA_PII_DENYLIST`). Matched after
   normalisation (case, separators, full-width digits, dashless UUIDs, JID and
   bare-local phone forms, base64url). A hit is a hard FAIL: it cannot be
   acknowledged, and it is never sent to any model. A missing denylist is an
   ERROR unless `NORA_PII_DENYLIST_ABSENT=<reason>` says why this machine has
   none; the reason is printed on every run.
2. **Shape detectors** for what the denylist does not know: phone numbers (any
   country), emails, platform snowflakes, UUIDs, WhatsApp JIDs, Signal group
   ids, Tailscale names and addresses, GPS in media metadata, and COORDINATE
   TABLES read as number fields and scored on dwell — fixes per place, and
   dwell rows x dwell places — not on a literal count (#283 criterion 1).
3. **An optional commit judge** (`NORA_PII_JUDGE=laya|jev`, off by default;
   `scripts/pii_judge.py`): it reads the whole commit at commit-msg time and
   can RAISE a finding, never clear one.

A finding that is not a denylist hit and not an ERROR can be decided by
`scripts/pii_adjudicate.py`: a read-only coding agent reads the staged change
and the repository's history and answers real / fake / unsure per finding.
Only `fake` becomes an acknowledgement, recorded as a `PII-Ack:` trailer with
the agent's reason; `real` and `unsure` stay blocked.

Only what a change ADDS is judged: a value already present in the parent's copy
of the file, as often, is not new. That is what lets the ~2,000 residue hits
already in the tree (the scrub track's job, not this one's) sit there without
blocking an unrelated commit — and what makes swapping a table's coordinates
for different ones a FAIL, where the old gate's size pin stayed green
(#283 criterion 2).

Declarations (`.githooks/pii-allowlist.txt`) and the placeholder source
(`identity.example.toml`) are read from the newest ancestor the remote
already has, never from HEAD or from the range being pushed: a declaration
added beside, amended into, or pushed with the payload it would exempt does
not exempt it (#283 criterion 3).

A finding the author has looked at and judged harmless is acknowledged by its
id — `NORA_PII_ACK=<id>[,<id>]` — and the commit-msg hook writes a
`PII-Ack: <id>` trailer for each, so the decision is in the history and
pre-push can re-derive it. The id hashes the path and the line, so it
acknowledges that line and nothing else.

Output names the path, the line and the RULE, and masks the value: hook output
lands in terminals and agent transcripts.
"""

