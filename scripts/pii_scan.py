@dataclass
class TextScan:
    findings: list  # Finding (FAIL), keyed
    coords: CoordResult | None = None


class LineIndex:
    """Offset -> 1-based line number in O(log n); a per-hit `count("\\n")` is
    quadratic on a large file with many hits."""

    def __init__(self, text: str):
        self.starts = [0] + [m.end() for m in re.finditer("\n", text)]

    def line(self, pos: int) -> int:
        return bisect.bisect_right(self.starts, pos)


class Spans:
    """Accepted spans, so a later (less specific) rule never re-reports a
    stretch an earlier rule or the denylist already claimed."""

    def __init__(self, spans=()):
        self.items = sorted(spans)

    def free(self, s: int, e: int) -> bool:
        i = bisect.bisect_left(self.items, (s, e))
        for a, b in self.items[max(0, i - 8) : i + 8]:
            if not (e <= a or s >= b):
                return False
        # a long earlier span may still cover s
        return all(not (a < s < b) for a, b in self.items[:i][-64:])

    def add(self, s: int, e: int) -> None:
        bisect.insort(self.items, (s, e))


_GAP = re.compile(r"[\s_\-.@/:#*'\"+,]*")


def _match_tokens(t: str, toks: list, i: int, cand: tuple) -> int | None:
    """End offset when `cand` starts at token i: consecutive tokens, short
    punctuation-only gaps, and one single-letter token (a middle initial,
    `Given Q. Family`) may be skipped per gap."""
    p = i
    for j in range(1, len(cand)):
        nxt = p + 1
        if nxt < len(toks) and toks[nxt][2] != cand[j] and len(toks[nxt][2]) == 1:
            nxt += 1
        if nxt >= len(toks) or toks[nxt][2] != cand[j]:
            return None
        gap = t[toks[p][1] : toks[nxt][0]]
        if len(gap) > 20 or not _GAP.fullmatch(
            re.sub(r"(?<![A-Za-z])[A-Za-z](?![A-Za-z])", "", gap)
        ):
            return None
        p = nxt
    return toks[p][1]


class Scanner:
    def __init__(self, deny: Denylist, allow: Allowlist, placeholders: set[str]):
        self.deny = deny
        self.allow = allow
        self.placeholders = placeholders

    # denylist ---------------------------------------------------------------
    def denylist_hits(self, text: str) -> list[tuple[int, int, str, str]]:
        """(start, end, kind, key) of every denylisted value, in every
        spelling: the text as written (folded: dashes, spaces, look-alike
        letters, Traditional/Simplified), and each encoded layer of each line
        decoded (JSON escapes, URL and HTML encoding, base64). A hit in a
        decoded layer is reported on its line. Keep-phrases are masked out
        first, in the text and in every decoded layer: only the exact
        phrase; the rest of its line is matched as usual."""
        text = self.mask_keep(text)
        hits = self._direct_hits(match_view(text))
        pos = 0
        for line in text.split("\n"):
            if len(line) >= 6:
                for layer in decoded_layers(line):
                    for _s, _e, kind, key in self._direct_hits(match_view(self.mask_keep(layer))):
                        hits.append((pos, pos + len(line), kind, key))
            pos += len(line) + 1
        return hits

    def mask_keep(self, text: str) -> str:
        """Every keep-phrase occurrence blanked to spaces (line breaks kept),
        so offsets and line numbers do not move."""
        for rx in (*self.deny.keep, _PROJECT_RX):
            text = rx.sub(lambda m: re.sub(r"[^\n]", " ", m.group()), text)
        return text

    def _direct_hits(self, t: str) -> list[tuple[int, int, str, str]]:
        d = self.deny
        hits: list[tuple[int, int, str, str]] = []
        if d.token_index:
            # `\nName` inside a JSON string: the escape's letter would glue to
            # the name, so blank the escape first (same length, same offsets).
            tt = re.sub(r"\\[ntr]", "  ", t)
            toks = [(m.start(), m.end(), m.group().lower()) for m in _ALNUM_TOKEN.finditer(tt)]
            for i, (s, _e, tok) in enumerate(toks):
                for cand in d.token_index.get(tok, ()):
                    end = _match_tokens(tt, toks, i, cand)
                    if end is not None:
                        hits.append((s, end, "text", " ".join(cand)))
            # camelCase splits too: `givenFamily` is two tokens as well as one.
            # Anchored: unanchored, every lower-case start rescans to the end
            # of the run, and a 100k-character hex line took 26 s.
            for m in re.finditer(r"(?<![A-Za-z0-9])[a-z][a-z0-9]*[A-Z][A-Za-z0-9]*", tt):
                parts = [
                    p.lower() for p in re.findall(r"[A-Z]?[a-z0-9]+|[A-Z]+(?![a-z])", m.group())
                ]
                for i, p in enumerate(parts):
                    for cand in d.token_index.get(p, ()):
                        if tuple(parts[i : i + len(cand)]) == cand:
                            hits.append((m.start(), m.end(), "text", " ".join(cand)))
        if d.nonascii:
            pos = 0
            for line in t.split("\n"):
                if not line.isascii():
                    # spaces and middle dots are not part of a CJK name
                    keep = [
                        k
                        for k, ch in enumerate(line)
                        if not ch.isspace() and ch not in "\u00b7\u30fb\u2027\u2022\uff65"
                    ]
                    compact = "".join(line[k] for k in keep).casefold()
                    for v in d.nonascii:
                        start = compact.find(v)
                        while start != -1:
                            a, b = keep[start], keep[start + len(v) - 1] + 1
                            hits.append((pos + a, pos + b, "text", v))
                            start = compact.find(v, start + 1)
                pos += len(line) + 1
        if d.number_rx is not None:
            # up to four separator characters between digits: `+<cc> NNNN - NNNN`
            for m in re.finditer(r"\d(?:[ \t().\-/]{0,4}\d)*", t):
                dg = digits_of(m.group())
                if len(dg) < 7:
                    continue
                mm = d.number_rx.search(dg)
                if mm:
                    hits.append((m.start(), m.end(), "number", mm.group()))
            # and a number spread out further (`NNNN ----- NNNN`): any gap of
            # up to 8 non-word characters, but only over a phone-sized run, so
            # a long numeric table cannot assemble one by chance
            for m in re.finditer(r"\d(?:[^\w\n]{0,8}\d)*", t):
                dg = digits_of(m.group())
                if 7 <= len(dg) <= 24:
                    mm = d.number_rx.search(dg)
                    if mm:
                        hits.append((m.start(), m.end(), "number", mm.group()))
        if d.uuids or d.hexes:
            for m in re.finditer(
                r"(?<![0-9A-Za-z])[0-9a-fA-F][0-9a-fA-F-]{6,40}[0-9a-fA-F](?![0-9A-Za-z])", t
            ):
                h = m.group().replace("-", "").lower()
                if h in d.uuids or h[:8] in d.hexes or h in d.hexes:
                    hits.append((m.start(), m.end(), "uuid", h))
        if d.b64:
            for m in re.finditer(r"[A-Za-z0-9+/_%-]{20,}={0,2}", t):
                c = b64_canonical(m.group())
                for p in d.b64:
                    if p in c:
                        hits.append((m.start(), m.end(), "b64", p))
                        break
        return hits

    def denied_digits(self, digits: str) -> bool:
        """A shape's digits that contain, or sit inside, a denylisted number."""
        d = self.deny
        if len(digits) < 7 or not d.numbers:
            return False
        return bool(d.number_rx and d.number_rx.search(digits)) or any(
            digits in x for x in d.numbers
        )

    def cleared(self, key: str) -> bool:
        """A shape's value that is known not to be real: a placeholder from
        identity.example.toml, a declared `value`/`value-re`, or a pseudonym
        the scrub map produced. Asked only AFTER the denylist has had its say
        on the same digits, so none of them can clear a real number."""
        return (
            key in self.placeholders
            or self.allow.value_allowed(key)
            or key in self.deny.pseudonyms
            or key.lower() in self.deny.pseudonyms
        )

    # shapes -------------------------------------------------------------------
    def shape_hits(
        self, text: str, taken: list[tuple[int, int]]
    ) -> list[tuple[int, int, str, str]]:
        out: list[tuple[int, int, str, str]] = []
        spans = Spans(taken)
        free = spans.free
        idx = LineIndex(text)
        lines = text.split("\n")
        offsets = []
        pos = 0
        for ln in lines:
            offsets.append(pos)
            pos += len(ln) + 1
        for rule, rx, _ in _SHAPES:
            for m in rx.finditer(text):
                s, e = m.span()
                if not free(s, e):
                    continue
                value = m.group()
                ln = idx.line(s)
                spans.add(s, e)
                if _shape_placeholder(rule, value, lines[ln - 1]):
                    continue
                key = normalise_key(value if rule != "whatsapp-jid" else value.split("@")[0])
                out.append((s, e, rule, key))
        # bare digit runs are a phone only where the line says so
        for n, line in enumerate(lines):
            if not _PHONE_WORDS.search(line):
                continue
            for m in _PHONE_BARE.finditer(line):
                s, e = offsets[n] + m.start(), offsets[n] + m.end()
                if not free(s, e):
                    continue
                d = digits_of(m.group())
                spans.add(s, e)
                if _DATEISH.match(m.group()):
                    continue
                if placeholder_digits(d):
                    continue
                out.append((s, e, "phone", d))
        for n, line in enumerate(lines):
            if not _ID_WORDS.search(line):
                continue
            for m in _UUID_NODASH.finditer(line):
                s, e = offsets[n] + m.start(), offsets[n] + m.end()
                if free(s, e) and not placeholder_hex(m.group()):
                    spans.add(s, e)
                    out.append((s, e, "uuid", m.group().lower()))
        for n, line in enumerate(lines):
            if "group" in line.lower():
                for m in _SIGNAL_URLSAFE.finditer(line):
                    s, e = offsets[n] + m.start(), offsets[n] + m.end()
                    if free(s, e) and not _shape_placeholder("signal-group", m.group() + "=", line):
                        spans.add(s, e)
                        out.append((s, e, "signal-group", b64_canonical(m.group())))
        return out

    def scan_text(
        self, text: str, path: str, *, shapes: bool = True, coords: bool = True
    ) -> TextScan:
        text = normalise_text(text)
        lines = text.split("\n")
        idx = LineIndex(text)
        findings: list[Finding] = []
        deny = sorted(set(self.denylist_hits(text)))
        for s, _e, kind, key in deny:
            ln = idx.line(s)
            findings.append(
                Finding(
                    "FAIL",
                    f"denylist:{kind}",
                    path,
                    ln,
                    mask(key, full=True),
                    finding_id(path, lines[ln - 1]),
                    ackable=False,
                    key=key,
                    text=lines[ln - 1],
                )
            )
        cres = None
        if shapes:
            for s, e, rule, key in self.shape_hits(text, [(a, b) for a, b, _, _ in deny]):
                ln = idx.line(s)
                dg = digits_of(text[s:e])
                if rule in ("phone", "snowflake", "whatsapp-jid") and self.denied_digits(dg):
                    # a shape that overlaps a real number IS that number: a
                    # separator the denylist matcher did not bridge must not
                    # turn it into something an ack can clear
                    findings.append(
                        Finding(
                            "FAIL",
                            "denylist:number",
                            path,
                            ln,
                            mask(dg, full=True),
                            finding_id(path, lines[ln - 1]),
                            ackable=False,
                            key=dg,
                            text=lines[ln - 1],
                        )
                    )
                    continue
                if self.cleared(key):
                    continue
                findings.append(
                    Finding(
                        "FAIL",
                        rule,
                        path,
                        ln,
                        mask(text[s:e]),
                        finding_id(path, lines[ln - 1], rule, key),
                        key=key,
                        text=lines[ln - 1],
                    )
                )
            if coords:
                cres = scan_coords(lines)
        return TextScan(findings, cres)


