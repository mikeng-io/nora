# Placeholder shapes


def placeholder_digits(d: str) -> bool:
    if len(set(d)) <= 2:
        return True
    if re.search(r"(\d)\1{4,}", d):
        return True
    if any(s in d for s in ("1234567", "2345678", "3456789", "9876543", "0123456")):
        return True
    return "55501" in d  # NANP fiction range 555-01xx


_KNOWN_PUBLIC_UUIDS = {
    # uuid.NAMESPACE_DNS/URL/OID/X500 (RFC 4122 appendix C)
    f"6ba7b81{i}9dad11d180b400c04fd430c8" for i in range(5)
}


def placeholder_hex(h: str) -> bool:
    h = h.lower()
    if h in _KNOWN_PUBLIC_UUIDS:
        return True
    if re.search(r"([0-9a-f])\1{4,}", h) or h.count("0") >= 12:
        return True
    return any(s in h for s in ("12345678", "abcdef", "deadbeef", "cafebabe", "feedface"))


