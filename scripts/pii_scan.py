KINDS = ("text", "phone", "number", "uuid", "hex", "b64")


class DenylistError(Exception):
    pass


@dataclass
class Denylist:
    source: str = ""
    count: int = 0
    # text: first token -> list of token tuples
    token_index: dict = field(default_factory=dict)
    nonascii: list = field(default_factory=list)
    numbers: list = field(default_factory=list)  # digit strings (contained-in match)
    number_rx: re.Pattern | None = None
    uuids: set = field(default_factory=set)
    hexes: set = field(default_factory=set)
    b64: list = field(default_factory=list)
    # the operator's private lists (load_private_lists): exact credit lines
    # masked before denylist matching, and known-fake values the scrub map
    # produced, which clear a SHAPE finding (never a denylist hit)
    keep: list = field(default_factory=list)  # compiled keep-phrase patterns
    pseudonyms: set = field(default_factory=set)  # normalise_key()ed values

    @property
    def empty(self) -> bool:
        return self.count == 0


_ALNUM_TOKEN = re.compile(r"[A-Za-z0-9]+")


def _tokens_of(value: str) -> tuple[str, ...]:
    return tuple(t.lower() for t in _ALNUM_TOKEN.findall(value))


# Token-equal to the project name is the project name: `first_last` spelled
# with an underscore cannot be told apart from the author line in LICENSE.
_PROJECT_TOKENS = {_tokens_of(v) for v in PROJECT_IDENTITY}

# Project identity in TEXT is blanked before denylist matching, like a
# keep-phrase: matching drops separators, so an owner's name whose letters
# spell the org stem would otherwise fire inside the org, the domain and the
# project email (repository URLs would otherwise be refused).
# Only the org, the domain and the project email: the bare stem is also a
# personal handle (`@stem`, `github.com/stem`), and another mailbox at the
# domain (`x@domain`) is a person, so neither is blanked. Not glued to a
# letter or digit on either side (`stemFBID` is an app id).
_ORG_TOKEN = next(v for v in PROJECT_IDENTITY if v.endswith("-io"))
_PROJECT_EMAIL = next(v for v in PROJECT_IDENTITY if "@" in v)
_PROJECT_DOMAIN = _PROJECT_EMAIL.split("@", 1)[1]
_PROJECT_RX = re.compile(
    r"(?<![A-Za-z0-9])(?:"
    + re.escape(_PROJECT_EMAIL)
    + "|"
    + re.escape(_ORG_TOKEN)
    + r"|(?<![@.])"
    + re.escape(_PROJECT_DOMAIN)
    + r")(?![A-Za-z0-9])",
    re.IGNORECASE,
)


def phone_forms(digits: str) -> list[str]:
    """E.164 digits plus the bare-local form: the last max(8, n-3) digits,
    which every national spelling of the number contains."""
    forms = [digits]
    if len(digits) >= 10:
        forms.append(digits[-max(8, len(digits) - 3) :])
    return forms


def parse_denylist(text: str, source: str = "") -> Denylist:
    d = Denylist(source=source)
    numbers: set[str] = set()
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            raise DenylistError(f"{source}:{n}: expected `kind<TAB>value`")
        kind, value = line.split("\t", 1)
        value = match_view(normalise_line(value.strip()))
        if kind not in KINDS:
            # the "kind" of a swapped line is the value: never echo it
            raise DenylistError(f"{source}:{n}: unknown kind {mask(kind, full=True)}")
        if (
            not value
            or value.casefold() in PROJECT_IDENTITY
            or _tokens_of(value) in _PROJECT_TOKENS
        ):
            continue
        d.count += 1
        if kind == "text":
            if not value.isascii():
                # CJK and mixed-script values are matched as substrings only:
                # their ASCII fragments (a romanised given name inside a
                # Cantonese nickname) are not identifiers on their own.
                # Whitespace is not part of a CJK name (`陳 大文`).
                d.nonascii.append(re.sub(r"\s+", "", value.casefold()))
                continue
            toks = _tokens_of(value)
            if len(toks) == 1 and len(toks[0]) < 4:
                d.count -= 1
                continue
            if toks:
                variants = {toks}
                if len(toks) in (2, 3):
                    # `Family, Given` and `Family, Given Middle`
                    variants.add((toks[-1], *toks[:-1]))
                    variants.add(tuple(reversed(toks)))
                for v in variants:
                    d.token_index.setdefault(v[0], set()).add(v)
                if len(toks) > 1:
                    joined = ("".join(toks),)
                    d.token_index.setdefault(joined[0], set()).add(joined)
        elif kind == "phone":
            for f in phone_forms(digits_of(value)):
                if len(f) >= 7:
                    numbers.add(f)
        elif kind == "number":
            dg = digits_of(value)
            if len(dg) >= 7:
                numbers.add(dg)
        elif kind == "uuid":
            h = value.replace("-", "").lower()
            if re.fullmatch(r"[0-9a-f]{32}", h):
                d.uuids.add(h)
                d.hexes.add(h[:8])
        elif kind == "hex":
            d.hexes.add(value.lower())
        elif kind == "b64":
            c = b64_canonical(value)
            d.b64.append(c[:20] if len(c) >= 20 else c)
    d.numbers = sorted(numbers, key=len, reverse=True)
    if d.numbers:
        d.number_rx = re.compile("|".join(re.escape(x) for x in d.numbers))
    return d


