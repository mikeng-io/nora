# Acks and output


def apply_acks(findings: list[Finding], acks: set[str]) -> set[str]:
    used = set()
    for f in findings:
        if f.ackable and f.fid and f.fid in acks and not f.state:
            f.state = "ACKED"
            used.add(f.fid)
    return used


def verdict(rep: Report) -> int:
    live = [f for f in rep.findings if not f.state]
    if any(f.status == "ERROR" for f in live):
        return ERROR
    if live:
        return FAIL
    return PASS


def emit(rep: Report, label: str, elapsed: float) -> int:
    for n in rep.notices:
        print(n, file=sys.stderr)
    code = verdict(rep)
    word = {PASS: "PASS", FAIL: "FAIL", ERROR: "ERROR"}[code]
    if rep.findings:
        for f in sorted(rep.findings, key=lambda f: (f.path, f.line, f.rule)):
            print(f.render(), file=sys.stderr)
    print(
        f"pii {label}: {word} — {rep.scanned} blob(s)/message(s), "
        f"{sum(1 for f in rep.findings if not f.state)} open finding(s), {elapsed:.2f}s",
        file=sys.stderr,
    )
    if code != PASS:
        live = [f for f in rep.findings if not f.state]
        denied = any(f.rule.startswith("denylist:") for f in live)
        errors = any(f.status == "ERROR" for f in live)
        print(
            "  Values are masked. A denylist hit is a real value: remove it; it cannot be\n"
            "  acknowledged. An ERROR means the hook could not look: fix what it names.",
            file=sys.stderr,
        )
        if not denied and not errors and label in ("staged", "message"):
            print(
                "  A shape finding is cleared by a human who has LOOKED at the value, by id:\n"
                "      NORA_PII_ACK=<id>[,<id>] git commit ...\n"
                f"  (recorded as a `{ACK_TRAILER}: <id> (human)` trailer). Never acknowledge a\n"
                "  value you have not checked; a coding agent asks its human.",
                file=sys.stderr,
            )
        print(
            f"  Declarations: {ALLOWLIST_PATH}, honoured once PUSHED, never in the change they\n"
            "  cover. See .githooks/README.md.",
            file=sys.stderr,
        )
    return code


def _gitdir() -> str:
    return git("rev-parse", "--git-dir").decode().strip()


def _record_used_acks(rep: Report) -> None:
    with open(os.path.join(_gitdir(), "nora-pii-acks"), "w") as fh:
        for f in sorted((f for f in rep.findings if f.state == "ACKED"), key=lambda f: f.fid):
            fh.write(f"{f.fid}\t{f.note}\n")


def main(argv: list[str]) -> int:
    if len(argv) < 2 or argv[1] in ("-h", "--help"):
        print(__doc__)
        print(
            "usage: pii_scan.py staged | message <file> | push (stdin) | commits <sha>... | "
            "tree [<rev>] [--allowlist-from-worktree] [--inventory <out.tsv>] | "
            "declare-coords <path>"
        )
        return ERROR
    mode = argv[1]
    t0 = time.monotonic()
    try:
        configure()
    except ConfigError as exc:
        rep = Report(
            findings=[Finding("ERROR", "config", "<env>", 0, "", "", ackable=False, note=str(exc))]
        )
        return emit(rep, mode, time.monotonic() - t0)
    if mode == "declare-coords":
        return mode_declare_coords(argv[2])
    deny, err, notice = load_denylist()
    if notice:
        print(notice, file=sys.stderr)
    if err is not None:
        rep = Report(findings=[err])
        return emit(rep, mode, time.monotonic() - t0)
    if deny is None:  # load_denylist returns one or the other
        return ERROR
    try:
        if mode == "staged":
            rep = mode_staged(deny)
            apply_acks(rep.findings, env_acks() | replay_acks())
            _record_used_acks(rep)
        elif mode == "message":
            rep = mode_message(deny, argv[2])
            with open(argv[2], encoding="utf-8", errors="surrogateescape") as fh:
                own = trailer_acks(fh.read())
            apply_acks(rep.findings, env_acks() | own)
            if verdict(rep) == PASS:
                _write_ack_trailers(argv[2], rep)
        elif mode == "push":
            # pre-push passes <remote name> <remote url>; the url is asked
            rep = mode_push(
                deny,
                sys.stdin.read().splitlines(),
                argv[3] if len(argv) > 3 else (argv[2] if len(argv) > 2 else None),
            )
        elif mode == "commits":
            rep = scan_commits(
                deny,
                [
                    git("rev-parse", "--verify", f"{c}^{{commit}}").decode().strip()
                    for c in argv[2:]
                ],
            )
        elif mode == "tree":
            args, rev, inventory = argv[2:], "HEAD", None
            i = 0
            while i < len(args):
                if args[i] == "--inventory":
                    inventory = args[i + 1]
                    i += 2
                    continue
                if not args[i].startswith("--"):
                    rev = args[i]
                i += 1
            rep = mode_tree(deny, rev, "--allowlist-from-worktree" in args)
            if inventory:
                write_inventory(rep, inventory, rev)
                print(
                    f"pii tree: inventory written ({len(rep.findings)} findings)", file=sys.stderr
                )
                return verdict(rep)
        else:
            print(f"pii: unknown mode {mode!r}", file=sys.stderr)
            return ERROR
    except (GitError, OSError, AllowlistError) as exc:
        rep = Report(
            findings=[
                Finding("ERROR", "scanner", "<pii_scan>", 0, "", "", ackable=False, note=str(exc))
            ]
        )
    return emit(rep, mode, time.monotonic() - t0)


def _write_ack_trailers(msg_path: str, rep: Report) -> None:
    """Record every acknowledgement this commit used -- pre-commit's (from the
    per-worktree git dir) and the message's own -- as `PII-Ack: <id> (human)`
    trailers, so the decision is in the history and pre-push re-derives it.
    The side file only carries ids pre-commit already applied from
    NORA_PII_ACK; writing it by hand clears nothing, because a trailer is a
    claim pre-push weighs exactly like a typed one."""
    used = {f.fid for f in rep.findings if f.state == "ACKED"}
    side = os.path.join(_gitdir(), "nora-pii-acks")
    if os.path.exists(side):
        with open(side, encoding="utf-8") as fh:
            for line in fh:
                fid = line.split("\t", 1)[0].strip()
                if re.fullmatch(r"[0-9a-f]{12}", fid):
                    used.add(fid)
        os.remove(side)
    if not used:
        return
    with open(msg_path, encoding="utf-8", errors="surrogateescape") as fh:
        have = trailer_acks(fh.read())
    args = []
    for fid in sorted(used - have):
        args += ["--trailer", f"{ACK_TRAILER}: {fid} (human)"]
    if args:
        git("interpret-trailers", "--in-place", *args, msg_path)


def write_inventory(rep: Report, out: str, rev: str) -> None:
    """Counts and paths only — never a value."""
    by_rule: dict[str, int] = {}
    by_file: dict[str, dict[str, int]] = {}
    for f in rep.findings:
        by_rule[f.rule] = by_rule.get(f.rule, 0) + 1
        by_file.setdefault(f.path, {})
        by_file[f.path][f.rule] = by_file[f.path].get(f.rule, 0) + 1
    with open(out, "w") as fh:
        fh.write(f"# pii residue inventory of {rev} — counts and paths only, never values\n")
        fh.write(f"# files with findings: {len(by_file)}; findings: {len(rep.findings)}\n\n")
        fh.write("## per rule\n")
        for r, n in sorted(by_rule.items(), key=lambda x: -x[1]):
            fh.write(f"{r}\t{n}\n")
        fh.write("\n## per file (total, then per rule)\n")
        for p, rules in sorted(by_file.items(), key=lambda x: -sum(x[1].values())):
            fh.write(
                f"{sum(rules.values())}\t{p}\t"
                + ", ".join(f"{r}={n}" for r, n in sorted(rules.items()))
                + "\n"
            )


def _main_fail_closed(argv: list[str]) -> int:
    """An exception is an ERROR (2), never the FAIL (1) a bare traceback
    would exit with, and never a PASS."""
    try:
        return main(argv)
    except Exception as exc:  # noqa: BLE001 - the whole point is to catch everything
        print(
            f"pii: ERROR — the scanner crashed ({type(exc).__name__}: {exc}); nothing was judged",
            file=sys.stderr,
        )
        return ERROR


if __name__ == "__main__":
    sys.exit(_main_fail_closed(sys.argv))
