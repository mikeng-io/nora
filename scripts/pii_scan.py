def _decode(data: bytes) -> tuple[str | None, str]:
    """(text, why-not). UTF-16 and undecodable bytes are reasons, not skips."""
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return None, "utf16"
    head = data[:8192]
    if head and head.count(b"\x00") * 4 >= len(head):
        return None, "utf16" if re.search(rb"(?:[\x20-\x7e]\x00){4}", head) else "undecodable"
    if b"\x00" in head:
        return None, "undecodable"
    try:
        return data.decode("utf-8"), ""
    except UnicodeDecodeError:
        return None, "undecodable"


def _line_diff(new: list[str], old: list[str]) -> tuple[set[int], list[str]]:
    """(numbers of the new lines that occur more often than in `old`, the old
    lines that occur more often than in `new`). A multiset diff: a moved
    line is neither added nor removed, an edited line is both."""
    c_old = Counter(old)
    seen: Counter = Counter()
    added = set()
    for n, x in enumerate(new, 1):
        seen[x] += 1
        if seen[x] > c_old[x]:
            added.add(n)
    c_new = Counter(new)
    seen = Counter()
    removed = []
    for x in old:
        seen[x] += 1
        if seen[x] > c_new[x]:
            removed.append(x)
    return added, removed


def _coords_findings(
    path: str,
    text: str,
    raw_olds: list,
    added: set[int],
    geo: bool,
    allow: Allowlist,
    raw_path: str | None = None,
) -> list[Finding]:
    """The whole file's location table, against every parent's: a finding
    when it is over the dwell limit, it gained a point, and its content is
    not the declared digest (#283 criterion 2)."""
    cres = scan_coords(normalise_text(text).split("\n"), geo=geo)
    if not cres.over:
        return []
    now = Counter((round(la, 5), round(ln, 5)) for _, la, ln in cres.points)
    # The RESULTING table is judged against each parent on its own: a merge
    # of two branches that each added two fixes in one place assembles a
    # table neither parent had, so it is new unless some parent already held
    # all of it (the union of the parents would call it old).
    for o in raw_olds:
        pts = Counter(
            (round(la, 5), round(ln, 5))
            for _, la, ln in scan_coords([normalise_line(x) for x in (o or [])], geo=geo).points
        )
        if not (now - pts):
            return []
    digest = cres.digest()
    if digest in allow.coords_digest(raw_path or path):
        return []
    first = min((n for n, _, _ in cres.points if n in added), default=cres.points[0][0])
    return [
        Finding(
            "FAIL",
            "coords",
            path,
            first,
            f"rows={cres.rows} clusters={cres.clusters} max-in-one-place={cres.max_rows} "
            f"score={cres.score}",
            finding_id(path, f"<coords {digest}>"),
            note=f"a location table; declare it as `coords {path} sha256={digest}` in a PUSHED "
            "commit, or generate the fixture",
        )
    ]


def path_findings(sc: Scanner, path: str) -> list[Finding]:
    """The path's own components -- directories and file name -- through the
    same denylist, normalisation and shape rules as content (review of #591
    r2: `people/<name>/notes.md` and `<phone>.vcf` passed)."""
    scan = sc.scan_text(path.replace("/", " / "), "<path>", coords=False)
    shown = display_path(path, scan.findings)
    for f in scan.findings:
        f.path, f.line, f.text = shown, 0, path
        f.note = (f.note + "; " if f.note else "") + "in the file's path"
        f.fid = finding_id(shown, path, f.rule, f.key)
    return scan.findings


def display_path(path: str, hits: list | None) -> str:
    """A path is printed, recorded and shown to a model only when nothing in
    it matched; otherwise as an opaque token."""
    if not hits:
        return path
    return f"<path {hashlib.sha256(path.encode('utf-8', 'surrogateescape')).hexdigest()[:10]}>"


def judge_blob(job: BlobJob, sc: Scanner, allow: Allowlist, acks: set[str]) -> Report:
    rep = Report(scanned=1)
    raw_path = job.path
    pf = path_findings(sc, raw_path)
    path = display_path(raw_path, pf)
    if job.new_path:
        rep.findings += pf
    # path-exempt lifts the shape and coordinate rules only: a denylist hit is
    # never exempt, by any declaration (review of #591 r2)
    exempt = allow.path_has("path-exempt", raw_path)
    blob_id = hashlib.sha256(job.new or b"").hexdigest()
    file_fid = finding_id(path, f"<blob {blob_id}>")
    fallback = file_fid in acks  # an acknowledged structural error is scanned the fallback way

    if job.mode == "160000":
        if not (allow.path_has("gitlink", raw_path) or fallback):
            rep.findings.append(
                Finding(
                    "ERROR",
                    "gitlink",
                    path,
                    0,
                    "submodule pointer",
                    file_fid,
                    note="declare it (`gitlink`) in the parent's allowlist",
                )
            )
        return rep
    data = job.new or b""
    if job.mode == "120000" and not (allow.path_has("symlink", raw_path) or fallback):
        rep.findings.append(
            Finding(
                "ERROR",
                "symlink",
                path,
                0,
                "symlink",
                file_fid,
                note="a link is not the content it points at; declare it (`symlink`)",
            )
        )
        return rep
    if len(data) > MAX_BYTES and not (allow.path_has("large", raw_path) or fallback):
        rep.findings.append(
            Finding(
                "ERROR",
                "too-large",
                path,
                0,
                f"{len(data)} bytes",
                file_fid,
                note=f"over NORA_PII_MAX_BYTES={MAX_BYTES}; declare it (`large`)",
            )
        )
        return rep
    text, why = _decode(data)
    binary = text is None
    if binary:
        try:
            inner_texts, gps = expand_binary(data)
        except DecodeError as exc:
            inner_texts, gps = [], media_has_gps(data)
            rep.findings.append(
                Finding(
                    "ERROR",
                    "undecodable-container",
                    path,
                    0,
                    f"{len(data)} bytes",
                    file_fid,
                    note=str(exc),
                )
            )
        if gps:
            rep.findings.append(
                Finding(
                    "FAIL",
                    "media-gps",
                    path,
                    0,
                    "location metadata",
                    file_fid,
                    note="strip EXIF / ©xyz before committing",
                )
            )
        if not (allow.path_has("binary", raw_path) or fallback):
            rep.findings.append(
                Finding(
                    "ERROR",
                    why,
                    path,
                    0,
                    f"{len(data)} bytes",
                    file_fid,
                    note="could not read it as text; declare it (`binary`) and it is "
                    "scanned for embedded strings",
                )
            )
            return rep
        text = "\n".join(inner_texts)
    is_allowlist = raw_path == ALLOWLIST_PATH
    shapes = not (is_allowlist or exempt)
    raw_new = text.split("\n")
    raw_olds: list[list[str] | None] = []
    for old in job.olds:
        if old is None:
            raw_olds.append(None)
            continue
        ot, _ = _decode(old)
        if ot is None:
            try:
                ot = "\n".join(expand_binary(old)[0])
            except DecodeError:
                ot = extract_strings(old)
        raw_olds.append(ot.split("\n"))
    # Only the lines a change adds are read closely: a value is new when it
    # sits on an added line more often than on the lines the change removed,
    # against EVERY parent (a merge adds only what no parent had).
    diffs = [_line_diff(raw_new, o or []) for o in raw_olds] or [
        (set(range(1, len(raw_new) + 1)), [])
    ]
    added = set.intersection(*[a for a, _ in diffs])
    union = sorted(set().union(*[a for a, _ in diffs]))
    scan = sc.scan_text("\n".join(raw_new[n - 1] for n in union), path, shapes=shapes, coords=False)
    for f in scan.findings:
        f.line = union[f.line - 1]

    def keys(findings, lines: set[int] | None = None) -> Counter:
        return Counter((f.rule, f.key) for f in findings if lines is None or f.line in lines)

    new_keys: Counter | None = None
    for added_p, removed_p in diffs:
        gone = (
            sc.scan_text("\n".join(removed_p), path, shapes=shapes, coords=False).findings
            if removed_p
            else []
        )
        net = keys(scan.findings, added_p) - keys(gone)
        new_keys = net if new_keys is None else (new_keys & net)
    new_keys = new_keys or Counter()
    for k in new_keys:
        fs = [f for f in scan.findings if (f.rule, f.key) == k]
        for f in [f for f in fs if f.line in added] or fs:
            if binary:
                f.line = 0
                f.fid = finding_id(path, f"<blob {blob_id}> {f.rule} {f.key}")
            rep.findings.append(f)

    if not binary and shapes and union:
        geo = bool(_GEO_WORDS.search(text))
        probe = scan_coords([normalise_line(raw_new[n - 1]) for n in union], geo=geo)
        if probe.points:
            rep.findings += _coords_findings(path, text, raw_olds, added, geo, allow, raw_path)
    if not binary:
        judged = {n for n in added if _judgeable(raw_new[n - 1])}
        shown = sorted(
            {k for n in judged for k in range(max(1, n - 2), min(len(raw_new), n + 2) + 1)}
        )
        if judged:
            rep.views.append(
                (
                    path,
                    [
                        (k, "+" if k in judged else " ", normalise_line(raw_new[k - 1]))
                        for k in shown
                    ],
                )
            )
    return rep


def _judgeable(line: str) -> bool:
    return len(line.strip()) >= 4 and bool(re.search(r"\w", line))


