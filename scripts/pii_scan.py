# Not after `.` (the tail of a version), not after `d:` (the seconds of a
# clock time), not before `.d` (the head of a version or an IPv4 address).
_NUM_TOKEN = re.compile(r"(?<![\w.])(?<!\d:)([-+]?)(\d+)(?:\.(\d+))?(?!\w|\.\d)")
_DMS = re.compile(
    r"(\d{1,3})\s*°\s*(\d{1,2})\s*['′]\s*(\d{1,2}(?:\.\d+)?)\s*(?:[\"″]|'')?\s*([NSEW])"  # noqa: RUF001 - the prime marks ARE the DMS syntax
)
_ISO6709 = re.compile(r"(?<![\w.])([+-]\d{2}(?:\.\d{3,})?)([+-]\d{3}(?:\.\d{3,})?)")
_PLUS = re.compile(r"(?<![\w+])([23456789CFGHJMPQRVWX]{8})\+([23456789CFGHJMPQRVWX]{2,3})(?![\w])")
_OLC_ALPHA = "23456789CFGHJMPQRVWX"

CELL_DEG = 0.002  # ~220 m: one dwell place
MAX_CLUSTER_ROWS = 2  # three fixes in one place is a residence (#283)
# dwell rows x dwell places: home x2 + work x2 = 8 fails (review of #591);
# one place x2 = 2 passes
MAX_SCORE = 7
MAX_DECIMALS = 10  # a written-out coordinate; 15+ digits is float arithmetic (a metric series)


def _plus_decode(code: str) -> tuple[float, float]:
    lat, lng, res = -90.0, -180.0, 20.0
    for i in range(0, 8, 2):
        lat += _OLC_ALPHA.index(code[i]) * res
        lng += _OLC_ALPHA.index(code[i + 1]) * res
        res /= 20
    return lat + res * 10, lng + res * 10


def _line_candidates(line: str, geo: bool) -> list[tuple[int, str, float]]:
    """Number-like FIELDS that could be one coordinate: decimals, integers
    scaled by 1e6 or 1e7 (microdegrees), and an integer column followed by a
    fraction column (which is also how a comma-decimal reads)."""
    out: list[tuple[int, str, float]] = []
    toks = list(_NUM_TOKEN.finditer(line))
    min_frac = 2 if geo else 3  # 3 decimals is ~110 m: still a building (#166)
    skip = set()
    for i, m in enumerate(toks):
        if i in skip:
            continue
        sign = -1.0 if m.group(1) == "-" else 1.0
        ip, frac = m.group(2), m.group(3)
        if frac is not None:
            if len(ip) <= 3 and min_frac <= len(frac) <= MAX_DECIMALS:
                out.append((m.start(), "dec", sign * float(f"{ip}.{frac}")))
            continue
        # split integer / fraction columns, or a comma decimal
        if len(ip) <= 3 and i + 1 < len(toks):
            nxt = toks[i + 1]
            gap = line[m.end() : nxt.start()]
            if (
                nxt.group(3) is None
                and nxt.group(1) == ""
                and 4 <= len(nxt.group(2)) <= 7
                and re.fullmatch(r" ?[,;\t|] ?", gap)
            ):
                out.append((m.start(), "split", sign * float(f"{ip}.{nxt.group(2)}")))
                skip.add(i + 1)
                continue
        if 7 <= len(ip) <= 10:
            v = int(ip)
            # A scaled integer is a coordinate only in a file that says it
            # holds coordinates: otherwise every id, size and epoch second
            # pairs with its neighbour. A quoted integer is an id, and
            # YYYYMMDD is a date.
            if (
                not geo
                or line[m.start() - 1 : m.start()] in ('"', "'")
                or re.fullmatch(r"(19|20)\d\d(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])", ip)
            ):
                continue
            out.append((m.start(), "e6", sign * v / 1e6))
            out.append((m.start(), "e7", sign * v / 1e7))
    return out


def _in_lat(v: float) -> bool:
    return -90.0 <= v <= 90.0


def _in_lng(v: float) -> bool:
    return -180.0 <= v <= 180.0


def _pair(cands: list) -> tuple[list, list]:
    """Greedy (lat, lng) pairing inside one line, same encoding family, within
    three fields (a JSON key or a timestamp may sit between them)."""
    points, used = [], set()
    for i, (_, fam, a) in enumerate(cands):
        if i in used:
            continue
        for j in range(i + 1, min(len(cands), i + 5)):
            if j in used or cands[j][1] != fam or cands[j][0] == cands[i][0]:
                continue
            b = cands[j][2]
            if abs(a) < 1 and abs(b) < 1:
                continue
            if (_in_lat(a) and _in_lng(b)) or (_in_lng(a) and _in_lat(b)):
                lat, lng = (a, b) if _in_lat(a) and _in_lng(b) else (b, a)
                points.append((lat, lng))
                used.update({i, j})
                # the other scale of the same integer is not a second field
                used.update(k for k, c in enumerate(cands) if c[0] in (cands[i][0], cands[j][0]))
                break
    leftovers = [c for k, c in enumerate(cands) if k not in used]
    return points, leftovers


@dataclass
class CoordResult:
    points: list  # (line_no, lat, lng)
    rows: int = 0
    clusters: int = 0
    max_rows: int = 0
    dwell_rows: int = 0  # rows in a place visited at least twice
    dwell_clusters: int = 0
    labelled: int = 0  # points on or just under a line naming a person's place (home, work)

    @property
    def score(self) -> int:
        return self.dwell_rows * self.dwell_clusters

    @property
    def over(self) -> bool:
        return self.max_rows > MAX_CLUSTER_ROWS or self.score > MAX_SCORE or self.labelled > 0

    def digest(self) -> str:
        return coords_digest([(la, ln) for _, la, ln in self.points])


def coords_digest(points) -> str:
    body = "\n".join(sorted(f"{la:.5f},{ln:.5f}" for la, ln in points))
    return hashlib.sha256(body.encode()).hexdigest()[:16]


def scan_coords(lines: list[str], geo: bool | None = None) -> CoordResult:
    if geo is None:
        geo = any(_GEO_WORDS.search(x) for x in lines)
    points: list[tuple[int, float, float]] = []
    pending: tuple[int, list] | None = None  # a lone field waiting for its partner on a later line
    for n, line in enumerate(lines, 1):
        for m in _ISO6709.finditer(line):
            points.append((n, float(m.group(1)), float(m.group(2))))
        dms = [
            (m.group(4), float(m.group(1)) + float(m.group(2)) / 60 + float(m.group(3)) / 3600)
            for m in _DMS.finditer(line)
        ]
        lat_dms = [(-v if h == "S" else v) for h, v in dms if h in "NS"]
        lng_dms = [(-v if h == "W" else v) for h, v in dms if h in "EW"]
        for la, ln in zip(lat_dms, lng_dms, strict=False):
            points.append((n, la, ln))
        for m in _PLUS.finditer(line):
            la, ln = _plus_decode(m.group(1))
            points.append((n, la, ln))
        cands = _line_candidates(_ISO6709.sub(" ", line), geo)
        pts, left = _pair(cands)
        points.extend((n, la, ln) for la, ln in pts)
        if pending and left and n - pending[0] <= 2:
            pts2, _ = _pair(pending[1] + [(10**9 + c[0], c[1], c[2]) for c in left])
            if pts2:
                points.extend((n, la, ln) for la, ln in pts2)
                pending = None
                continue
        if left and not pts and len({c[0] for c in left}) == 1:
            pending = (n, left)
        elif pts or (pending and n - pending[0] > 2):
            pending = None
    res = CoordResult(points=points, rows=len(points))
    # One fix labelled `home` is a residence already (review of #591: a
    # two-line `[home] lat = ... lng = ...` passed on count).
    for n in {n for n, _, _ in points}:
        if any(_PLACE_WORDS.search(lines[k]) for k in range(max(0, n - 3), n)):
            res.labelled += 1
    if not points:
        return res
    cells: dict[tuple[int, int], int] = {}
    for _, la, ln in points:
        key = (int(la // CELL_DEG), int(ln // CELL_DEG))
        cells[key] = cells.get(key, 0) + 1
    # connected components over the 8-neighbourhood, so a place straddling a
    # cell boundary is one cluster
    seen, sizes = set(), []
    for c in cells:
        if c in seen:
            continue
        stack, size = [c], 0
        seen.add(c)
        while stack:
            x, y = stack.pop()
            size += cells[(x, y)]
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    nb = (x + dx, y + dy)
                    if nb in cells and nb not in seen:
                        seen.add(nb)
                        stack.append(nb)
        sizes.append(size)
    res.clusters = len(sizes)
    res.max_rows = max(sizes)
    res.dwell_rows = sum(x for x in sizes if x >= 2)
    res.dwell_clusters = sum(1 for x in sizes if x >= 2)
    return res


