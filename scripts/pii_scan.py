# Allowlist (declarations, read from the parent commit)


class AllowlistError(Exception):
    pass


ALLOW_KINDS = ("path-exempt", "binary", "symlink", "gitlink", "large", "coords", "value", "value-re")


@dataclass
class Allowlist:
    entries: list = field(default_factory=list)  # (kind, pattern, extra, reason)
    values: set = field(default_factory=set)
    value_res: list = field(default_factory=list)

    def path_has(self, kind: str, path: str) -> bool:
        return any(k == kind and fnmatch.fnmatchcase(path, p) for k, p, _, _ in self.entries)

    def coords_digest(self, path: str) -> set:
        return {x for k, p, x, _ in self.entries if k == "coords" and fnmatch.fnmatchcase(path, p)}

    def value_allowed(self, key: str) -> bool:
        return key in self.values or any(r.fullmatch(key) for r in self.value_res)


def parse_allowlist(text: str) -> Allowlist:
    a = Allowlist()
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if " -- " not in line:
            raise AllowlistError(f"{ALLOWLIST_PATH}:{n}: every declaration needs ` -- <reason>`")
        body, reason = line.split(" -- ", 1)
        parts = body.split()
        if len(parts) < 2 or parts[0] not in ALLOW_KINDS or not reason.strip():
            raise AllowlistError(f"{ALLOWLIST_PATH}:{n}: expected `<kind> <pattern> -- <reason>`, "
                                 f"kind one of {', '.join(ALLOW_KINDS)}")
        kind, pattern = parts[0], parts[1]
        if kind == "value":
            pattern = body.split(None, 1)[1].strip()  # a value may hold spaces: `+44 7700 ...`
        extra = ""
        if kind == "coords":
            if len(parts) != 3 or not re.fullmatch(r"sha256=[0-9a-f]{16}", parts[2]):
                raise AllowlistError(f"{ALLOWLIST_PATH}:{n}: coords needs `sha256=<16 hex>` "
                                     "(scripts/pii_scan.py declare-coords <path>)")
            extra = parts[2].split("=", 1)[1]
        if kind == "value":
            a.values.add(normalise_key(pattern))
        elif kind == "value-re":
            try:
                a.value_res.append(re.compile(pattern))
            except re.error as exc:
                raise AllowlistError(f"{ALLOWLIST_PATH}:{n}: bad regex: {exc}") from exc
        a.entries.append((kind, pattern, extra, reason.strip()))
    return a


def normalise_key(value: str) -> str:
    v = normalise_line(value).strip()
    if re.fullmatch(r"[+()\d \-.]+", v) and len(digits_of(v)) >= 6:
        return digits_of(v)
    if re.fullmatch(r"[0-9a-fA-F]{8}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{12}", v):
        return v.replace("-", "").lower()
    return v.lower()


def placeholder_values(example_toml: str) -> set[str]:
    """Every quoted value in identity.example.toml is a placeholder by
    construction (it is the template a human copies)."""
    return {normalise_key(v) for v in re.findall(r'"([^"\n]{4,})"', example_toml)}


