def parse_raw_z(raw: bytes) -> list[tuple[str, str, str, str, str, str, str]]:
    """`git diff --raw -z` -> (old_mode, new_mode, old_sha, new_sha, status, src, dst)."""
    out = []
    parts = raw.split(b"\0")
    i = 0
    while i < len(parts) and parts[i]:
        meta = parts[i].decode()
        if not meta.startswith(":"):
            i += 1
            continue
        om, nm, osha, nsha, status = meta[1:].split(" ")
        src = parts[i + 1].decode("utf-8", "surrogateescape")
        if status[0] in "RC":
            dst = parts[i + 2].decode("utf-8", "surrogateescape")
            i += 3
        else:
            dst = src
            i += 2
        out.append((om, nm, osha, nsha, status, src, dst))
    return out


