# Findings


@dataclass
class Finding:
    status: str  # FAIL | ERROR
    rule: str
    path: str
    line: int
    masked: str
    fid: str
    ackable: bool = True
    note: str = ""
    key: str = ""  # normalised value; never printed
    text: str = ""  # the full line; never printed, only hashed or sent to a judge
    state: str = ""  # "", ACKED, CLEARED

    def render(self) -> str:
        where = f"{self.path}:{self.line}" if self.line else self.path
        tag = self.state or self.status
        extra = f"  ({self.note})" if self.note else ""
        ack = f"  id={self.fid}" if self.ackable else "  (not acknowledgeable)"
        return f"  {tag:<7} {self.rule:<18} {where}  {self.masked}{extra}{ack}"


def finding_id(path: str, line_text: str, *parts: str) -> str:
    """Stable id of ONE finding: path and line, plus the rule and the matched
    value's normalised key, so an acknowledgement covers that finding and not
    its neighbour on the same line (review of #591 r2, finding 6)."""
    body = "\0".join([path, line_text.rstrip(), *parts])
    return hashlib.sha256(body.encode("utf-8", "surrogateescape")).hexdigest()[:12]


def mask(value: str, *, full: bool = False) -> str:
    n = len(value)
    if full or n <= 5:
        return f"<{n} chars>"
    return f"{value[:2]}…{value[-1]} ({n} chars)"


# --------------------------------------------------------------------------
# Normalisation

_ZERO_WIDTH = dict.fromkeys(map(ord, "\u200b\u200c\u200d\u2060\ufeff\u00ad"), None)


def normalise_line(line: str) -> str:
    """NFKC folds full-width digits and letters; zero-width characters are
    dropped so one cannot be slipped inside a number. Applied per line, so the
    line count (and every reported line number) is unchanged."""
    return unicodedata.normalize("NFKC", line).translate(_ZERO_WIDTH)


def normalise_text(text: str) -> str:
    return "\n".join(normalise_line(x) for x in text.split("\n"))


def _match_fold_table() -> dict[int, str]:
    """One character to one character, so offsets survive: every dash-like
    code point to `-`, every space-like and control character to a space,
    Cyrillic and Greek letters that are drawn like Latin ones to that Latin
    letter, and Traditional Chinese to Simplified. Used only to MATCH the
    denylist; nothing else reads the folded text."""
    t: dict[int, str] = {}
    for c in "\u2010\u2011\u2012\u2013\u2014\u2015\u2212\ufe58\ufe63\uff0d\u2043":
        t[ord(c)] = "-"
    for cp in (0x00A0, 0x1680, *range(0x2000, 0x200B), 0x202F, 0x205F, 0x3000):
        t[cp] = " "
    for cp in [*range(0x00, 0x09), 0x0B, 0x0C, 0x0D, *range(0x0E, 0x20), 0x7F]:
        t[cp] = " "
    # Cyrillic and Greek letters drawn like Latin ones: (look-alike, Latin) pairs
    confusable = (
        "\u0430a\u0435e\u043eo\u0440p\u0441c\u0443y\u0445x\u0456i"
        "\u0458j\u0455s\u0501d\u051bq\u051dw\u04bbh\u04cfl\u0451e"
        "\u0410A\u0412B\u0415E\u041aK\u041cM\u041dH\u041eO\u0420P"
        "\u0421C\u0422T\u0425X\u0406I\u0408J\u0405S\u0423Y\u0391A"
        "\u0392B\u0395E\u0396Z\u0397H\u0399I\u039aK\u039cM\u039dN"
        "\u039fO\u03a1P\u03a4T\u03a5Y\u03a7X\u03bfo\u03b9i\u03bak"
        "\u03bdv\u03c1p\u03c5u\u03c4t\u03b1a"
    )
    for k, v in zip(confusable[::2], confusable[1::2], strict=True):
        t[ord(k)] = v
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from pii_cjk_fold import FOLD

    t.update(FOLD)
    return t


_MATCH_FOLD: dict[int, str] | None = None


def match_view(text: str) -> str:
    global _MATCH_FOLD
    if _MATCH_FOLD is None:
        _MATCH_FOLD = _match_fold_table()
    return text.translate(_MATCH_FOLD)


def _json_unescape(s: str) -> str:
    out = re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)), s)
    try:
        return out.encode("utf-16", "surrogatepass").decode("utf-16")
    except UnicodeError:
        return out


_B64_TOKEN = re.compile(r"[A-Za-z0-9+/_-]{16,}={0,2}")
_HEX_TOKEN = re.compile(r"(?<![0-9A-Fa-f])(?:[0-9A-Fa-f]{2}){6,}(?![0-9A-Fa-f])")
_SPELLED_AT = re.compile(r"(?i)\s*[\[(]?\s*\bat\b\s*[\])]?\s*")
_SPELLED_DOT = re.compile(r"(?i)\s*[\[(]?\s*\bdot\b\s*[\])]?\s*")
# bounds: decoding is for hiding places, not bulk data
LAYER_SEGMENTS = 64  # encoded segments tried per line
LAYER_BYTES = 256 * 1024  # decoded characters kept per line


def _readable(txt: str) -> bool:
    return bool(txt) and sum(ch.isprintable() or ch in "\t\n\r" for ch in txt) >= 0.9 * len(txt)


def _b64_texts(s: str) -> list[str]:
    """Readable text inside base64 / base64url segments (a JWT's payload,
    a data: URI, an opaque-looking config value), at most LAYER_SEGMENTS."""
    out, tried = [], 0
    for m in _B64_TOKEN.finditer(s):
        for seg in m.group().split("."):
            seg = seg.rstrip("=")
            if len(seg) < 12:
                continue
            tried += 1
            if tried > LAYER_SEGMENTS:
                return out
            raw = seg[: LAYER_BYTES * 4 // 3].replace("-", "+").replace("_", "/")
            raw = raw[: len(raw) - len(raw) % 4] if len(raw) % 4 == 1 else raw
            try:
                txt = base64.b64decode(raw + "=" * (-len(raw) % 4), validate=True).decode("utf-8")
            except (ValueError, UnicodeDecodeError):
                continue
            if _readable(txt):
                out.append(txt)
    return out


def _hex_texts(s: str) -> list[str]:
    out = []
    for i, m in enumerate(_HEX_TOKEN.finditer(s)):
        if i >= LAYER_SEGMENTS:
            break
        try:
            txt = bytes.fromhex(m.group()[: LAYER_BYTES * 2]).decode("utf-8")
        except (ValueError, UnicodeDecodeError):
            continue
        if _readable(txt) and re.search(r"[A-Za-z]{3}|[^\x00-\x7f]", txt):
            out.append(txt)
    return out


def _strip_marks(s: str) -> str:
    return "".join(ch for ch in unicodedata.normalize("NFKD", s) if not unicodedata.combining(ch))


def decoded_layers(line: str, depth: int = 2) -> list[str]:
    """Every spelling of `line` an encoding would hide: JSON `\\uXXXX`
    escapes, URL percent-encoding, HTML entities (with or without the `;`),
    base64/base64url and hex segments, combining accents, and an address
    spelled out (`name at host dot tld`). Layers are decoded again up to
    `depth`. Linear: a set dedupes, and segments and decoded size per line
    are capped (review of #591 r2: a 2 MB base64 line took minutes)."""
    seen = {line}
    layers: list[str] = []
    todo = [line]
    budget = LAYER_BYTES
    for _ in range(depth):
        nxt = []
        for cur in todo:
            cands = []
            if "\\u" in cur:
                cands.append(_json_unescape(cur))
            if "%" in cur:
                cands.append(urllib.parse.unquote_plus(cur, errors="replace"))
            if "&" in cur:
                cands.append(html.unescape(cur))
            if not cur.isascii():
                cands.append(_strip_marks(cur))
            if re.search(r"(?i)\bat\b", cur) and re.search(r"(?i)\bdot\b", cur):
                cands.append(_SPELLED_DOT.sub(".", _SPELLED_AT.sub("@", cur)))
            cands += _b64_texts(cur)
            cands += _hex_texts(cur)
            for c in cands:
                c = normalise_line(c.replace("\n", " "))[:budget]
                if c in seen:
                    continue
                seen.add(c)
                budget -= len(c)
                layers.append(c)
                nxt.append(c)
                if budget <= 0:
                    return layers
        todo = nxt
        if not todo:
            break
    return layers


def digits_of(s: str) -> str:
    return re.sub(r"\D", "", s)


def b64_canonical(s: str) -> str:
    """Standard and URL-safe base64 (and the percent-encoded forms of both)
    collapse to one spelling: url-safe alphabet, no padding."""
    s = s.replace("%2B", "+").replace("%2b", "+").replace("%2F", "/").replace("%2f", "/")
    s = s.replace("%3D", "=").replace("%3d", "=")
    return s.replace("+", "-").replace("/", "_").rstrip("=")


# --------------------------------------------------------------------------
# Denylist

KINDS = ("text", "phone", "number", "uuid", "hex", "b64")


class DenylistError(Exception):
    pass


@dataclass
class Denylist:
    source: str = ""
    count: int = 0
    # text: first token -> list of token tuples
    token_index: dict = field(default_factory=dict)
    nonascii: list = field(default_factory=list)
    numbers: list = field(default_factory=list)  # digit strings (contained-in match)
    number_rx: re.Pattern | None = None
    uuids: set = field(default_factory=set)
    hexes: set = field(default_factory=set)
    b64: list = field(default_factory=list)

    @property
    def empty(self) -> bool:
        return self.count == 0


_ALNUM_TOKEN = re.compile(r"[A-Za-z0-9]+")


def _tokens_of(value: str) -> tuple[str, ...]:
    return tuple(t.lower() for t in _ALNUM_TOKEN.findall(value))


# Token-equal to the project name is the project name: `first_last` spelled
# with an underscore cannot be told apart from the author line in LICENSE.
_PROJECT_TOKENS = {_tokens_of(v) for v in PROJECT_IDENTITY}


def phone_forms(digits: str) -> list[str]:
    """E.164 digits plus the bare-local form: the last max(8, n-3) digits,
    which every national spelling of the number contains."""
    forms = [digits]
    if len(digits) >= 10:
        forms.append(digits[-max(8, len(digits) - 3) :])
    return forms


def parse_denylist(text: str, source: str = "") -> Denylist:
    d = Denylist(source=source)
    numbers: set[str] = set()
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            raise DenylistError(f"{source}:{n}: expected `kind<TAB>value`")
        kind, value = line.split("\t", 1)
        value = match_view(normalise_line(value.strip()))
        if kind not in KINDS:
            # the "kind" of a swapped line is the value: never echo it
            raise DenylistError(f"{source}:{n}: unknown kind {mask(kind, full=True)}")
        if (
            not value
            or value.casefold() in PROJECT_IDENTITY
            or _tokens_of(value) in _PROJECT_TOKENS
        ):
            continue
        d.count += 1
        if kind == "text":
            if not value.isascii():
                # CJK and mixed-script values are matched as substrings only:
                # their ASCII fragments (a romanised given name inside a
                # Cantonese nickname) are not identifiers on their own.
                # Whitespace is not part of a CJK name (`陳 大文`).
                d.nonascii.append(re.sub(r"\s+", "", value.casefold()))
                continue
            toks = _tokens_of(value)
            if len(toks) == 1 and len(toks[0]) < 4:
                d.count -= 1
                continue
            if toks:
                variants = {toks}
                if len(toks) in (2, 3):
                    # `Family, Given` and `Family, Given Middle`
                    variants.add((toks[-1], *toks[:-1]))
                    variants.add(tuple(reversed(toks)))
                for v in variants:
                    d.token_index.setdefault(v[0], set()).add(v)
                if len(toks) > 1:
                    joined = ("".join(toks),)
                    d.token_index.setdefault(joined[0], set()).add(joined)
        elif kind == "phone":
            for f in phone_forms(digits_of(value)):
                if len(f) >= 7:
                    numbers.add(f)
        elif kind == "number":
            dg = digits_of(value)
            if len(dg) >= 7:
                numbers.add(dg)
        elif kind == "uuid":
            h = value.replace("-", "").lower()
            if re.fullmatch(r"[0-9a-f]{32}", h):
                d.uuids.add(h)
                d.hexes.add(h[:8])
        elif kind == "hex":
            d.hexes.add(value.lower())
        elif kind == "b64":
            c = b64_canonical(value)
            d.b64.append(c[:20] if len(c) >= 20 else c)
    d.numbers = sorted(numbers, key=len, reverse=True)
    if d.numbers:
        d.number_rx = re.compile("|".join(re.escape(x) for x in d.numbers))
    return d


def load_denylist() -> tuple[Denylist | None, Finding | None, str]:
    """Returns (denylist, error, notice). Missing or empty is an ERROR unless
    NORA_PII_DENYLIST_ABSENT names a reason."""
    path = os.path.expanduser(os.environ.get("NORA_PII_DENYLIST") or DEFAULT_DENYLIST)
    absent_reason = os.environ.get("NORA_PII_DENYLIST_ABSENT", "").strip()
    if not os.path.exists(path):
        if absent_reason:
            return (
                Denylist(source="<absent>"),
                None,
                (
                    f"pii: NO DENYLIST on this machine ({path}); acknowledged by "
                    f"NORA_PII_DENYLIST_ABSENT={absent_reason!r}. Shape rules only: known real "
                    "values that do not look like a phone/uuid/... will pass."
                ),
            )
        return (
            None,
            Finding(
                "ERROR",
                "denylist-missing",
                path,
                0,
                "",
                "",
                ackable=False,
                note="generate it with scripts/pii_denylist_build.py, or set "
                "NORA_PII_DENYLIST_ABSENT=<reason> on a machine that has none",
            ),
            "",
        )
    try:
        with open(path, encoding="utf-8") as fh:
            d = parse_denylist(fh.read(), path)
    except (OSError, UnicodeDecodeError, DenylistError) as exc:
        return (
            None,
            Finding("ERROR", "denylist-unreadable", path, 0, "", "", ackable=False, note=str(exc)),
            "",
        )
    if d.empty:
        return (
            None,
            Finding(
                "ERROR",
                "denylist-empty",
                path,
                0,
                "",
                "",
                ackable=False,
                note="0 entries: a broken generation, not a clean machine",
            ),
            "",
        )
    notice = ""
    try:
        if os.stat(path).st_mode & 0o077:
            notice = f"pii: warning: {path} is readable by group/other; chmod 600 it"
    except OSError:
        pass
    return d, None, notice


# --------------------------------------------------------------------------
# Allowlist (declarations, read from what the remote already has)


class AllowlistError(Exception):
    pass


ALLOW_KINDS = (
    "path-exempt",
    "binary",
    "symlink",
    "gitlink",
    "large",
    "coords",
    "value",
    "value-re",
)


@dataclass
class Allowlist:
    entries: list = field(default_factory=list)  # (kind, pattern, extra, reason)
    values: set = field(default_factory=set)
    value_res: list = field(default_factory=list)

    def path_has(self, kind: str, path: str) -> bool:
        return any(k == kind and fnmatch.fnmatchcase(path, p) for k, p, _, _ in self.entries)

    def coords_digest(self, path: str) -> set:
        return {x for k, p, x, _ in self.entries if k == "coords" and fnmatch.fnmatchcase(path, p)}

    def value_allowed(self, key: str) -> bool:
        return key in self.values or any(r.fullmatch(key) for r in self.value_res)


def parse_allowlist(text: str) -> Allowlist:
    a = Allowlist()
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if " -- " not in line:
            raise AllowlistError(f"{ALLOWLIST_PATH}:{n}: every declaration needs ` -- <reason>`")
        body, reason = line.split(" -- ", 1)
        parts = body.split()
        if len(parts) < 2 or parts[0] not in ALLOW_KINDS or not reason.strip():
            raise AllowlistError(
                f"{ALLOWLIST_PATH}:{n}: expected `<kind> <pattern> -- <reason>`, "
                f"kind one of {', '.join(ALLOW_KINDS)}"
            )
        kind, pattern = parts[0], parts[1]
        if kind not in ("value", "value-re") and too_broad(pattern):
            raise AllowlistError(
                f"{ALLOWLIST_PATH}:{n}: `{pattern}` is too broad: name the file, or a directory at "
                "least two levels deep, or a narrow pattern such as `dir/*.png` (review of #591 "
                "r2: "
                "one `path-exempt *` switched everything off)"
            )
        if kind == "value":
            pattern = body.split(None, 1)[1].strip()  # a value may hold spaces: `+44 7700 ...`
        extra = ""
        if kind == "coords":
            if len(parts) != 3 or not re.fullmatch(r"sha256=[0-9a-f]{16}", parts[2]):
                raise AllowlistError(
                    f"{ALLOWLIST_PATH}:{n}: coords needs `sha256=<16 hex>` "
                    "(scripts/pii_scan.py declare-coords <path>)"
                )
            extra = parts[2].split("=", 1)[1]
        if kind == "value":
            a.values.add(normalise_key(pattern))
        elif kind == "value-re":
            try:
                a.value_res.append(re.compile(pattern))
            except re.error as exc:
                raise AllowlistError(f"{ALLOWLIST_PATH}:{n}: bad regex: {exc}") from exc
        a.entries.append((kind, pattern, extra, reason.strip()))
    return a


MAX_DECL_FILES = 200  # a declaration matching more tracked files than this is an ERROR


def too_broad(pattern: str) -> bool:
    """`*`, `**`, a leading wildcard, or a bare wildcard directly under a
    top-level directory (`vendor/*`) exempt too much to be a declaration."""
    if "**" in pattern:
        return True
    parts = [p for p in pattern.split("/") if p]
    lead = 0
    for p in parts:
        if any(c in p for c in "*?["):
            break
        lead += 1
    if lead == len(parts):
        return False  # a literal path
    if lead == 0:
        return True
    wild = parts[lead]
    bare = set(wild) <= set("*?")
    return bare and lead < 2


def normalise_key(value: str) -> str:
    v = normalise_line(value).strip()
    if re.fullmatch(r"[+()\d \-.]+", v) and len(digits_of(v)) >= 6:
        return digits_of(v)
    if re.fullmatch(
        r"[0-9a-fA-F]{8}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{12}", v
    ):
        return v.replace("-", "").lower()
    return v.lower()


def placeholder_values(example_toml: str) -> set[str]:
    """Every quoted value in identity.example.toml is a placeholder by
    construction (it is the template a human copies)."""
    return {normalise_key(v) for v in re.findall(r'"([^"\n]{4,})"', example_toml)}


