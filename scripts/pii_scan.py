# Modes


def _outcome(rep: Report) -> set:
    return {(f.status, f.rule, f.path, f.line, f.key) for f in rep.findings}


def mode_staged(deny: Denylist) -> Report:
    """Scan the index twice: with the declarations of the newest ancestor the
    local remote-tracking refs call published, and with none. When the two
    agree (almost always) no network is needed. When the declarations change
    the outcome, they count only if the remote itself confirms it has that
    ancestor (`git ls-remote`, the same truth pre-push uses); otherwise the
    strict result stands (review of #591 r2: tracking refs can be forged)."""
    head = rev_exists("HEAD")
    base = published_base(head)
    declared = _mode_staged(deny, load_context(base), head)
    if not base:
        return declared
    strict = _mode_staged(deny, (Allowlist(), set(), []), head)
    if _outcome(strict) == _outcome(declared):
        return declared
    remote = _upstream_remote()
    try:
        confirmed = bool(remote) and base in remote_has(remote)
    except GitError:
        confirmed = False
    if confirmed:
        return declared
    strict.notices.append(
        f"pii: declarations NOT honoured: could not confirm with the remote that {base[:10]} is "
        "published (offline, or a local ref the remote does not have)"
    )
    return strict


def _upstream_remote() -> str | None:
    """The URL of the remote the current branch tracks, else `origin`."""
    name = (
        git(
            "config",
            "--get",
            "branch."
            + git("rev-parse", "--abbrev-ref", "HEAD", check=False).decode().strip()
            + ".remote",
            check=False,
        )
        .decode()
        .strip()
        or "origin"
    )
    url = git("remote", "get-url", name, check=False).decode().strip()
    return url or None


def _mode_staged(deny: Denylist, ctx: tuple, head: str | None) -> Report:
    merge_heads = []
    gitdir = git("rev-parse", "--git-dir").decode().strip()
    mh = os.path.join(gitdir, "MERGE_HEAD")
    if os.path.exists(mh):
        with open(mh) as fh:
            merge_heads = [x.strip() for x in fh.read().split() if x.strip()]
    allow, placeholders, errs = ctx
    rep = Report(findings=list(errs))
    raw = git("diff-index", "--cached", "-z", "-M", "--raw", "--no-abbrev", head or EMPTY_TREE)
    entries = parse_raw_z(raw)
    names: list[str] = []
    jobs_meta = []
    for _om, nm, osha, nsha, status, _src, dst in entries:
        if status.startswith("D") or nm == "000000":
            continue
        if dst == ALLOWLIST_PATH:
            rep.notices.append(
                f"pii: {ALLOWLIST_PATH} changed; declarations take effect once this commit is "
                "PUSHED, never in it (push it on its own, then commit what it covers)"
            )
        olds = [osha if not set(osha) <= {"0"} else None]
        olds += [f"{m}:{dst}" for m in merge_heads]
        if nm != "160000":
            names.append(nsha)
        names += [o for o in olds if o]
        jobs_meta.append((dst, nm, nsha, olds, status[0] in "ARC"))
    objs = read_objects(names)
    sc = Scanner(deny, allow, placeholders)
    rep.guard = sc.contains_denylisted
    rep.guard_lines = sc.withheld_lines
    acks = env_acks()
    for dst, nm, nsha, olds, new_path in jobs_meta:
        job = BlobJob(
            dst,
            nm,
            objs.get(nsha) if nm != "160000" else None,
            [objs.get(o) if o else None for o in olds],
            new_path,
        )
        rep.extend(judge_blob(job, sc, allow, acks))
    return rep


def _ident_findings(sc: Scanner, label: str, ident: str) -> list[Finding]:
    out = []
    for _s, _e, kind, key in sc.denylist_hits(normalise_line(ident)):
        out.append(
            Finding(
                "FAIL",
                f"denylist:{kind}",
                label,
                0,
                mask(key, full=True),
                finding_id(label, ident),
                ackable=False,
            )
        )
    for m in EMAIL_RX.finditer(ident):
        if not placeholder_email(m.group()):
            out.append(
                Finding("FAIL", "email", label, 0, mask(m.group()), finding_id(label, ident))
            )
    return out


def message_findings(sc: Scanner, body: str, label: str = "<commit-message>") -> list[Finding]:
    if not body.strip():
        return []
    scan = sc.scan_text(body, label)
    out = list(scan.findings)
    if scan.coords is not None and scan.coords.over:
        out.append(
            Finding(
                "FAIL",
                "coords",
                "<commit-message>",
                scan.coords.points[0][0],
                f"rows={scan.coords.rows} clusters={scan.coords.clusters}",
                finding_id("<commit-message>", f"<coords {scan.coords.digest()}>"),
            )
        )
    return out


def mode_message(deny: Denylist, msg_path: str) -> Report:
    head = rev_exists("HEAD")
    allow, placeholders, errs = load_context(published_base(head))
    rep = Report(findings=errs, scanned=1)
    # The WHOLE file: `git commit -m` and --cleanup=verbatim keep `#` lines
    # and text past the scissors, so stripping them first skipped text that
    # lands in the commit. Over-strict on git's own comment template is the
    # price (review of #591).
    with open(msg_path, encoding="utf-8", errors="surrogateescape") as fh:
        body = fh.read()
    sc = Scanner(deny, allow, placeholders)
    rep.guard = sc.contains_denylisted
    rep.guard_lines = sc.withheld_lines
    rep.findings += message_findings(sc, body)
    for label, var in (("<author>", "GIT_AUTHOR_IDENT"), ("<committer>", "GIT_COMMITTER_IDENT")):
        ident = git("var", var, check=False).decode("utf-8", "replace").strip()
        ident = re.sub(r"\s+\d+\s+[+-]\d{4}$", "", ident)
        rep.findings += _ident_findings(sc, label, ident)
    rep.message_lines = [
        (n, normalise_line(line))
        for n, line in enumerate(body.split("\n"), 1)
        if _judgeable(line) and not line.startswith(f"{ACK_TRAILER}:") and not line.startswith("#")
    ]
    return rep


def _batch_diffs(pairs: list[tuple[str, str]]) -> list[list[tuple]]:
    """One `git diff-tree --stdin` for every (parent, commit) pair. Its input
    line is `<commit> <parent>` (commit FIRST: the other order silently
    diffs backwards, turning every addition into a deletion); --always makes
    each pair print its header even when the diff is empty, so the output
    splits back into pairs by order. A root commit (parent = the empty tree)
    gets its own call."""
    out: list[list[tuple]] = []
    for parent, commit in pairs:
        if parent == EMPTY_TREE:
            out.append(
                parse_raw_z(
                    git("diff-tree", "-r", "-z", "--raw", "-M", "--no-abbrev", EMPTY_TREE, commit)
                )
            )
        else:
            out.append([])  # filled below
    real = [(i, pc) for i, pc in enumerate(pairs) if pc[0] != EMPTY_TREE]
    if not real:
        return out
    raw = git(
        "diff-tree",
        "--stdin",
        "--always",
        "-r",
        "-z",
        "--raw",
        "-M",
        "--no-abbrev",
        input_bytes="".join(f"{c} {p}\n" for _, (p, c) in real).encode(),
    )
    toks = raw.split(b"\0")
    i = 0
    for slot, _pair in real:
        while i < len(toks) and not toks[i]:
            i += 1
        i += 1  # the header
        entries = []
        while i < len(toks) and toks[i].startswith(b":"):
            om, nm, osha, nsha, status = toks[i][1:].decode().split(" ")
            src = toks[i + 1].decode("utf-8", "surrogateescape")
            if status[0] in "RC":
                dst = toks[i + 2].decode("utf-8", "surrogateescape")
                i += 3
            else:
                dst = src
                i += 2
            entries.append((om, nm, osha, nsha, status, src, dst))
        out[slot] = entries
    return out


def _changes_from(per_parent_entries: list[list[tuple]]) -> list[tuple[str, str, str, list]]:
    """(dst, new_mode, new_sha, olds-per-parent) for every path a commit
    changed; for a merge, only paths that differ from EVERY parent."""
    per_parent = [{e[6]: e for e in entries} for entries in per_parent_entries]
    paths = set()
    for d in per_parent:
        paths |= {k for k, e in d.items() if not e[4].startswith("D") and e[1] != "000000"}
    if len(per_parent) > 1:
        paths = {p for p in paths if all(p in d for d in per_parent)}
    out = []
    for p in sorted(paths):
        es = [d[p] for d in per_parent]
        olds = [e[2] if not set(e[2]) <= {"0"} else None for e in es]
        new_path = all(e[4][0] in "ARC" for e in es)
        out.append((p, es[0][1], es[0][3], olds, new_path))
    return out


def remote_has(remote: str) -> set[str]:
    """Every object id the TARGET remote advertises that exists here too.
    Asked of the remote itself (`git ls-remote`), never read off local
    remote-tracking refs: those go stale (a branch deleted on the remote),
    can be written by anyone (`git update-ref refs/remotes/...`) and belong
    to a different remote when pushing somewhere else (review of #591).
    Unreachable is a GitError: an ERROR, never an assumption."""
    raw = ls_remote(remote)
    ids = {ln.split("\t", 1)[0] for ln in raw.splitlines() if "\t" in ln}
    if not ids:
        return set()
    probe = git("cat-file", "--batch-check", input_bytes=("\n".join(sorted(ids)) + "\n").encode())
    return {
        ln.split(" ", 1)[0] for ln in probe.decode().splitlines() if not ln.endswith(" missing")
    }


LS_REMOTE_TIMEOUT = 20.0


def ls_remote(remote: str) -> str:
    """`git ls-remote`, never interactive and never unbounded: no terminal or
    GUI credential prompt, ssh in batch mode, and a timeout. Offline, a
    prompt, or a slow host is a GitError -- an ERROR (review of #591 r2: an
    https remote that wanted credentials hung the hook)."""
    env = dict(os.environ)
    env.update(
        GIT_TERMINAL_PROMPT="0",
        GCM_INTERACTIVE="never",
        GIT_ASKPASS="/usr/bin/false",
        SSH_ASKPASS="/usr/bin/false",
        GIT_SSH_COMMAND=env.get("GIT_SSH_COMMAND", "ssh")
        + " -o BatchMode=yes -o ConnectTimeout=10",
    )
    try:
        p = subprocess.run(  # noqa: S603 - fixed argv
            ["git", "ls-remote", remote],  # noqa: S607
            capture_output=True,
            env=env,
            stdin=subprocess.DEVNULL,
            timeout=LS_REMOTE_TIMEOUT,
        )
    except subprocess.TimeoutExpired as exc:
        raise GitError(f"git ls-remote timed out after {LS_REMOTE_TIMEOUT:.0f}s") from exc
    if p.returncode != 0:
        raise GitError(f"git ls-remote: {p.stderr.decode(errors='replace').strip()[:300]}")
    return p.stdout.decode()


def baseline(rep: Report) -> set[str]:
    """Cutover (review of #591 r2): pushing to a NEW remote -- the scrubbed
    public repository -- makes every commit "new", and the residue in the
    history can never pass. `NORA_PII_PUSH_BASELINE=<manifest>` names a file
    the scrub's content verification wrote: a `# nora-pii-baseline v1` header,
    then one object id per line, each a commit whose whole history that
    verification read clean. Those commits (and their ancestors) are treated
    as already published. The use is printed, with the manifest's digest, on
    every run; a malformed manifest is an ERROR."""
    path = os.environ.get("NORA_PII_PUSH_BASELINE", "").strip()
    if not path:
        return set()
    try:
        with open(path, encoding="utf-8") as fh:
            raw = fh.read()
    except OSError as exc:
        raise ConfigError(f"NORA_PII_PUSH_BASELINE={path!r}: {exc}") from exc
    lines = [x.strip() for x in raw.splitlines() if x.strip()]
    if not lines or not lines[0].startswith("# nora-pii-baseline v1"):
        raise ConfigError(
            f"NORA_PII_PUSH_BASELINE={path!r}: not a `# nora-pii-baseline v1` manifest"
        )
    ids = [x for x in lines[1:] if not x.startswith("#")]
    if not all(re.fullmatch(r"[0-9a-f]{40}", x) for x in ids):
        raise ConfigError(f"NORA_PII_PUSH_BASELINE={path!r}: every line must be a full object id")
    if ids:
        probe = git("cat-file", "--batch-check", input_bytes=("\n".join(ids) + "\n").encode())
        ids = [
            ln.split(" ", 1)[0] for ln in probe.decode().splitlines() if not ln.endswith(" missing")
        ]
    digest = hashlib.sha256(raw.encode()).hexdigest()[:16]
    rep.notices.append(
        f"pii: CUTOVER BASELINE in use: {len(ids)} commit(s) from {path} (sha256 {digest}) are "
        "treated as already published; everything else is scanned"
    )
    return set(ids)


def _tag_chain(sha: str) -> tuple[list[tuple[str, str, str]], str, str]:
    """Peel an annotated tag: ([(tag sha, tagger, message)], target sha,
    target type)."""
    tags = []
    typ = git("cat-file", "-t", sha).decode().strip()
    while typ == "tag":
        raw = git("cat-file", "tag", sha).decode("utf-8", "surrogateescape")
        head, _, message = raw.partition("\n\n")
        fields = dict(ln.split(" ", 1) for ln in head.splitlines() if " " in ln)
        tagger = re.sub(r"\s+\d+\s+[+-]\d{4}$", "", fields.get("tagger", ""))
        tags.append((sha, tagger, message))
        sha, typ = fields["object"], fields["type"]
    return tags, sha, typ


def mode_push(deny: Denylist, stdin_lines: list[str], remote: str | None) -> Report:
    rep = Report()
    zero = "0" * 40
    if not remote:
        rep.findings.append(
            Finding(
                "ERROR",
                "push-remote",
                "<push>",
                0,
                "",
                "",
                ackable=False,
                note="the pre-push hook passes the remote; run from it",
            )
        )
        return rep
    _PUSH_DECODED[0] = 0
    try:
        published = remote_has(remote)
        published |= baseline(rep)
    except ConfigError as exc:
        rep.findings.append(
            Finding("ERROR", "config", "<env>", 0, "", "", ackable=False, note=str(exc))
        )
        return rep
    except GitError as exc:
        rep.findings.append(
            Finding(
                "ERROR",
                "remote-unreachable",
                remote,
                0,
                "",
                "",
                ackable=False,
                note=f"could not ask the remote what it already has: {exc}",
            )
        )
        return rep
    shas: list[str] = []
    for line in stdin_lines:
        parts = line.split()
        if len(parts) < 4 or parts[1] == zero:
            continue
        local_ref, local_sha, _remote_ref, remote_sha = parts[:4]
        if local_sha == remote_sha:
            continue
        exclude = set(published)
        if remote_sha != zero and remote_sha in published:
            exclude.add(remote_sha)
        tags, target, typ = _tag_chain(local_sha)
        allow, placeholders, _errs = load_context(None)
        sc = Scanner(deny, allow, placeholders)
        for tsha, tagger, message in tags:
            fs = message_findings(sc, message) + _ident_findings(sc, "<tagger>", tagger)
            for f in fs:
                f.path = f"{local_ref} ({tsha[:10]}) {f.path}"
            rep.findings += fs
            rep.scanned += 1
        if typ in ("blob", "tree"):
            # A tag on a bare blob or tree: every object in it the remote
            # does not already reach.
            listing = git(
                "rev-list",
                "--objects",
                "--stdin",
                input_bytes=(
                    "\n".join([target] + [f"^{x}" for x in sorted(exclude)]) + "\n"
                ).encode(),
            ).decode()
            objs = [ln.split(" ", 1) for ln in listing.splitlines()]
            if typ == "blob":
                objs = [[target, "<blob>"]]
            blobs = read_objects([o[0] for o in objs])
            for o in objs:
                data = blobs.get(o[0])
                if data is None or git("cat-file", "-t", o[0]).decode().strip() != "blob":
                    continue
                path = o[1] if len(o) > 1 else "<blob>"
                sub = judge_blob(BlobJob(path, "100644", data, [None], True), sc, allow, set())
                for f in sub.findings:
                    f.path = f"{local_ref} {f.path}"
                sub.views = []
                rep.extend(sub)
            continue
        if typ != "commit":
            continue
        found = (
            git(
                "rev-list",
                f"--max-count={PUSH_MAX + 1}",
                "--stdin",
                input_bytes=(
                    "\n".join([target] + [f"^{x}" for x in sorted(exclude)]) + "\n"
                ).encode(),
            )
            .decode()
            .split()
        )
        if len(found) > PUSH_MAX:
            rep.findings.append(
                Finding(
                    "ERROR",
                    "push-too-long",
                    local_ref,
                    0,
                    f">{PUSH_MAX} commits the remote does not have",
                    "",
                    ackable=False,
                    note="raise NORA_PII_PUSH_MAX to look at all of them",
                )
            )
            found = found[:PUSH_MAX]
        shas += [x for x in found if x not in shas]
    return scan_commits(deny, shas, rep)


def scan_commits(deny: Denylist, shas: list[str], rep: Report | None = None) -> Report:
    rep = rep or Report()
    if not shas:
        return rep
    fmt = "%H%x00%P%x00%an <%ae>%x00%cn <%ce>%x00%B%x00%x01"
    raw = git("log", "--no-walk=unsorted", f"--format={fmt}", *shas).decode(
        "utf-8", "surrogateescape"
    )
    meta = {}
    for rec in raw.split("\x01"):
        rec = rec.lstrip("\n")
        if not rec:
            continue
        sha, parents, author, committer, body, _ = rec.split("\x00")
        meta[sha] = (parents.split(), author, committer, body)
    # Every diff in one diff-tree, every object and every parent's
    # declarations in one cat-file: a 200-commit push is two processes, not
    # four hundred.
    pairs, owner = [], []
    for sha in shas:
        for p in meta[sha][0] or [EMPTY_TREE]:
            pairs.append((p, sha))
            owner.append(sha)
    diffs = _batch_diffs(pairs)
    by_commit: dict[str, list] = {}
    for sha, entries in zip(owner, diffs, strict=True):
        by_commit.setdefault(sha, []).append(entries)
    changes = {sha: _changes_from(by_commit[sha]) for sha in shas}
    # Declarations come from the newest first-parent ancestor OUTSIDE the
    # range (what the remote already has), not from each commit's parent: a
    # declaration pushed in the same range as its payload exempts nothing.
    in_range = set(shas)

    def base_of(sha: str) -> str:
        c = sha
        while c in in_range:
            ps = meta[c][0]
            if not ps:
                return ""
            c = ps[0]
        return c

    bases = {sha: base_of(sha) for sha in shas}
    firsts = sorted({b for b in bases.values() if b})
    names = [c[2] for sha in shas for c in changes[sha] if c[1] != "160000"]
    names += [o for sha in shas for c in changes[sha] for o in c[3] if o]
    names += [f"{p}:{x}" for p in firsts for x in (ALLOWLIST_PATH, PLACEHOLDER_SOURCE)]
    names += list(shas)  # the raw commit objects, for their headers
    objs = read_objects(names)
    adjudications = adjudication_log()
    ctx_cache: dict[str, tuple] = {"": (Allowlist(), set(), [])}
    for p in firsts:
        ctx_cache[p] = _context_from(
            objs.get(f"{p}:{ALLOWLIST_PATH}"), objs.get(f"{p}:{PLACEHOLDER_SOURCE}"), p
        )
    for sha in shas:
        parents, author, committer, body = meta[sha]
        allow, placeholders, errs = ctx_cache[bases[sha]]
        sc = Scanner(deny, allow, placeholders)
        raw_commit = (objs.get(sha) or b"").decode("utf-8", "surrogateescape")
        tree = raw_commit[5:45] if raw_commit.startswith("tree ") else ""
        acks, unverified = verified_acks(body, tree, adjudications)
        sub = Report(findings=list(errs))
        for dst, nm, nsha, olds, new_path in changes[sha]:
            job = BlobJob(
                dst,
                nm,
                objs.get(nsha) if nm != "160000" else None,
                [objs.get(o) if o else None for o in olds],
                new_path,
            )
            sub.extend(judge_blob(job, sc, allow, acks))
        sub.findings += message_findings(sc, body)
        sub.findings += message_findings(sc, extra_headers(raw_commit), "<commit-header>")
        sub.findings += _ident_findings(sc, "<author>", author) + _ident_findings(
            sc, "<committer>", committer
        )
        for f in sub.findings:
            f.path = f"{sha[:10]} {f.path}"
        apply_acks(sub.findings, acks)
        for f in sub.findings:
            if not f.state and f.fid in unverified:
                f.note = (f.note + "; " if f.note else "") + (
                    "its `agent` ack has no matching adjudication record for this tree here"
                )
        sub.views = []
        rep.extend(sub)
    return rep


def extra_headers(raw_commit: str) -> str:
    """The commit object's headers other than tree, parent, author, committer
    and signatures (review of #591 r2: an `x-owner` header rode along
    unread). A mergetag's embedded tag -- message included -- is kept."""
    head, _, _msg = raw_commit.partition("\n\n")
    out, skip = [], False
    for line in head.split("\n"):
        if line.startswith(" "):
            if not skip:
                out.append(line[1:])
            continue
        key = line.split(" ", 1)[0]
        skip = key in ("tree", "parent", "author", "committer", "gpgsig", "gpgsig-sha256")
        if not skip:
            out.append(line)
    return "\n".join(x for x in out if not x.startswith(("-----BEGIN", "-----END")))


ADJUDICATION_LOG = "nora-pii-adjudications.jsonl"


def adjudication_log() -> dict[tuple[str, str], str]:
    """{(tree, finding id): model} for every `fake` verdict the adjudicator
    recorded in this clone."""
    out: dict[tuple[str, str], str] = {}
    try:
        with open(os.path.join(_gitdir(), ADJUDICATION_LOG), encoding="utf-8") as fh:
            for line in fh:
                try:
                    rec = json.loads(line)
                except ValueError:
                    continue
                for fid, v in (rec.get("verdicts") or {}).items():
                    if isinstance(v, dict) and v.get("verdict") == "fake":
                        out[(rec.get("tree", ""), fid)] = rec.get("model", "")
    except OSError:
        pass
    return out


def verified_acks(body: str, tree: str, log: dict) -> tuple[set[str], set[str]]:
    """(ids honoured, ids refused). A `PII-Ack` trailer is a CLAIM: `human`
    ones are honoured as claims; an `agent` one only when this clone holds the
    adjudication record for exactly this tree (review of #591 r2)."""
    ok, refused = set(), set()
    for m in re.finditer(rf"(?mi)^{ACK_TRAILER}:[ \t]*([0-9a-f]{{12}})(?:[ \t](.*))?$", body):
        fid, rest = m.group(1), (m.group(2) or "")
        if re.match(r"\(agent\b", rest.strip()) and (tree, fid) not in log:
            refused.add(fid)
        else:
            ok.add(fid)
    return ok - refused, refused


def mode_tree(deny: Denylist, rev: str, allow_from_worktree: bool) -> Report:
    commit = rev_exists(rev)
    if not commit:
        raise GitError(f"no such revision: {rev}")
    if allow_from_worktree:
        top = git("rev-parse", "--show-toplevel").decode().strip()
        try:
            with open(os.path.join(top, ALLOWLIST_PATH), encoding="utf-8") as fh:
                allow = parse_allowlist(fh.read())
        except FileNotFoundError:
            allow = Allowlist()
        ex = os.path.join(top, PLACEHOLDER_SOURCE)
        placeholders: set[str] = set()
        if os.path.exists(ex):
            with open(ex, encoding="utf-8") as fh:
                placeholders = placeholder_values(fh.read())
        errs: list[Finding] = []
    else:
        allow, placeholders, errs = load_context(commit)
    rep = Report(findings=errs)
    listing = git("ls-tree", "-r", "-z", "--full-tree", commit).split(b"\0")
    items = []
    for ent in listing:
        if not ent:
            continue
        meta, path = ent.split(b"\t", 1)
        mode, _typ, sha = meta.decode().split(" ")
        items.append((path.decode("utf-8", "surrogateescape"), mode, sha))
    objs = read_objects([s for _, m, s in items if m != "160000"])
    sc = Scanner(deny, allow, placeholders)
    for path, mode, sha in items:
        job = BlobJob(path, mode, objs.get(sha) if mode != "160000" else None, [None])
        sub = judge_blob(job, sc, allow, set())
        sub.views = []
        rep.extend(sub)
    return rep


def mode_declare_coords(path: str) -> int:
    staged = read_objects([f":{path}"]).get(f":{path}")
    if staged is not None:
        data = staged
    else:
        with open(path, "rb") as fh:
            data = fh.read()
    text, _ = _decode(data)
    if text is None:
        print(f"pii: {path} is not text", file=sys.stderr)
        return ERROR
    res = scan_coords(normalise_text(text).split("\n"))
    print(f"coords {path} sha256={res.digest()} -- <reason: why this table is generated / safe>")
    print(
        f"# rows={res.rows} clusters={res.clusters} max-in-one-place={res.max_rows} "
        f"score={res.score}",
        file=sys.stderr,
    )
    return PASS


