def _shape_placeholder(rule: str, value: str, ctx_line: str) -> bool:
    if rule in ("phone", "snowflake"):
        d = digits_of(value)
        if rule == "phone":
            halves = re.split(r"[ \-]", value)
            if len(halves) == 2 and all(re.fullmatch(r"(19|20)\d\d", h) for h in halves):
                return True  # a year range, not a number
            if len(halves) == 2 and all(re.fullmatch(r"([01]\d|2[0-4])[0-5]\d", h) for h in halves):
                return True  # a time range (0900-1800), not a number
        return placeholder_digits(d)
    if rule == "whatsapp-jid":
        return placeholder_digits(digits_of(value.split("@")[0]))
    if rule == "email":
        return placeholder_email(value)
    if rule == "uuid":
        return placeholder_hex(value.replace("-", ""))
    if rule == "signal-group":
        body = value.rstrip("=")
        return bool(re.search(r"(.)\1{4,}", body)) or not (
            re.search(r"[A-Z]", body) and re.search(r"[a-z]", body) and re.search(r"\d", body)
        )
    if rule == "tailscale":
        v = value.lower()
        return any(w in v for w in ("example", "your-tailnet", "tailnet-name", "<", "xxxx"))
    if rule == "tailscale-ip":
        return value in ("100.100.100.100", "100.64.0.0", "100.64.0.1")
    return False


