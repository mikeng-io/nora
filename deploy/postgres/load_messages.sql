-- load_messages.sql — the one-time SQLite → PostgreSQL record load (design/20 §5).
--
-- REVIEW-ONLY SCRIPT — not applied. The live store is ~41 rows / ~60 KB; nothing
-- is "migrated", the rows are loaded once with their ids PRESERVED, and the
-- identity sequence is then reseeded so the next insert lands at MAX+1.
--
-- ORDER at cutover (design/20 §5), read the state back at each step, never claim
-- it from exit 0:
--   1. docker compose up -d nora-db          # build the store
--   2. run `alembic upgrade head` against it  # the squashed 0001_pg_baseline
--      (Nora does this herself at startup, or: uv run alembic -x db=<sync-url> upgrade head)
--   3. export the 41 rows from the old SQLite file to a CSV whose COLUMNS AND
--      ORDER match the block below, e.g. from data/messages.db:
--        sqlite3 -header -csv data/messages.db \
--          'SELECT id, platform, conversation_id, conversation_type, sender_id,
--                  sender_name, ts, body, is_nora, delivery_status, raw_json,
--                  created_at, person_id, quoted_ts, media_json
--             FROM messages ORDER BY id;' > messages.csv
--   4. psql "<sync-url>" -v ON_ERROR_STOP=1 -f deploy/postgres/load_messages.sql
--   5. bring Nora up against Postgres; verify live (stats() reads 41, a real tag
--      round-trips, a Signal-magnitude ts writes without overflow).
--
-- Rollback: the old data/messages.db is moved aside, intact, not deleted;
-- rollback is repointing DATABASE_URL and reverting the branch.

BEGIN;

-- ids are inserted EXPLICITLY. This is legal because `id` is GENERATED BY
-- DEFAULT AS IDENTITY (not ALWAYS) — design/20 §2 chose BY DEFAULT for exactly
-- this. `\copy` streams the CSV from step 3 into the real column order.
\copy messages (id, platform, conversation_id, conversation_type, sender_id, sender_name, ts, body, is_nora, delivery_status, raw_json, created_at, person_id, quoted_ts, media_json) FROM 'messages.csv' WITH (FORMAT csv, HEADER true)

-- Reseed the identity sequence past the loaded ids, or the next server-assigned
-- id would collide with a loaded row. `+ 1` so the next insert is MAX+1.
SELECT setval(
  pg_get_serial_sequence('messages', 'id'),
  (SELECT COALESCE(MAX(id), 0) FROM messages),
  true      -- is_called=true → nextval() returns MAX+1, not MAX
);

COMMIT;

-- Verify (read the state back): the row count, and that a fresh insert lands at
-- MAX+1 before rolling it away.
SELECT count(*) AS loaded_rows FROM messages;

DO $$
DECLARE
  max_before bigint;
  new_id     integer;
BEGIN
  SELECT COALESCE(MAX(id), 0) INTO max_before FROM messages;
  INSERT INTO messages (platform, conversation_id, conversation_type, sender_id, ts, is_nora)
  VALUES ('signal', '__loadcheck__', 'group', '__loadcheck__', 0, 0)
  RETURNING id INTO new_id;
  ASSERT new_id = max_before + 1,
    format('reseed failed: expected id %s, got %s', max_before + 1, new_id);
  DELETE FROM messages WHERE id = new_id;   -- leave the store at exactly 41 rows
  RAISE NOTICE 'load verified: % rows, next id was %', max_before, new_id;
END $$;
