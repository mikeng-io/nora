"""xAI image generation adapter — the first `ImageGenerator` implementation.

DEC-137 / design/proposed/29: provider-agnostic port, xAI via the X Premium
OAuth subscription lane (quota-bounded, not metered billing). This module
knows xAI's wire shape; everything above it (tool, model-facing docstring)
names no provider.

NEVER raises into the caller — matching `TrackSource`/`WeatherProvider`'s
discipline in `nora.domain.ports`: every failure is a three-state
`ImageResult` (R-27), and a wiring gap is `unavailable`, never a raise and
never `nothing_found`.

Reference-image custody (design §5.1): `ImageReference` carries a marker
code, and this adapter resolves it ONLY through the injected
`reference_resolver` — a per-turn collaborator that can read the caller's
own conversation store. There is no URL/raw-bytes path in this class:
whatever the resolver returns IS the custody check. A reference that
resolves to nothing is `nothing_found`, never a fetch attempt.
"""

from __future__ import annotations

import base64
import logging
from collections.abc import Sequence
from typing import Literal

import aiohttp

from nora.domain.ports import (
    ImageReference,
    ImageResult,
    ImageSize,
    ReferenceResolver,
)

from .xai_oauth import XaiOAuth

log = logging.getLogger("nora.image_gen.xai")

XAI_API_BASE = "https://api.x.ai"
XAI_GENERATIONS_URL = f"{XAI_API_BASE}/v1/images/generations"
XAI_EDITS_URL = f"{XAI_API_BASE}/v1/images/edits"


def _hex_handle(raw: str) -> str:
    """The hex handle inside whatever the model passed — `a3f2c1`,
    `[image a3f2c1]` or a full sha256 all reduce to the same lowercase hex
    run. Kept here (infra may not import `nora.agent`), mirroring
    `tools._handle_hex` exactly so the two can never drift."""
    token = raw.strip().strip("[]").split()
    tail = token[-1] if token else ""
    return "".join(c for c in tail.lower() if c in "0123456789abcdef")


class XaiImageGenerator:
    """Satisfies `nora.domain.ports.ImageGenerator`.

    Constructor takes only collaborates (test-seam policy): an `XaiOAuth`
    lane and the model names from `[image_gen.xai]`. Generated bytes are
    returned RAW on the `ImageResult` (plus a data-URI artifact when the
    provider answered `b64_json`) — the caller decides custody: Nora's own
    `blob_store` (rustfs) and the platform attachment path. The provider
    never hosts, uploads to `drop`, or reaches for any external service.
    """

    def __init__(
        self,
        *,
        oauth: XaiOAuth,
        model: str = "grok-imagine-image",
        quality_model: str = "grok-imagine-image-quality",
        timeout_seconds: float = 90.0,
        base_url: str = XAI_API_BASE,
    ) -> None:
        self._oauth = oauth
        self._model = model
        self._quality_model = quality_model
        self._timeout = aiohttp.ClientTimeout(total=timeout_seconds)
        # Injectable for the test seam (the contract suite runs against a
        # local TestServer, never the live quota-bounded lane) — same shape
        # every other infra HTTP client uses for its base_url.
        self._generations_url = f"{base_url}/v1/images/generations"
        self._edits_url = f"{base_url}/v1/images/edits"

    # -- ImageGenerator -----------------------------------------------------

    async def generate(
        self,
        *,
        prompt: str,
        reference_images: Sequence[ImageReference] | None = None,
        size: ImageSize | None = None,
        quality: Literal["standard", "quality"] | None = None,
        reference_resolver: ReferenceResolver | None = None,
    ) -> ImageResult:
        if not prompt.strip():
            return ImageResult(status="nothing_found", reason="empty_prompt")

        auth = await self._oauth.access_token()
        if auth.status != "ok" or not auth.access_token:
            return ImageResult(
                status="unavailable",
                reason=auth.reason or "auth",
            )

        model = self._quality_model if quality == "quality" else self._model

        # Reference images: resolve custody handles ONLY through the injected
        # resolver; a code that resolves to nothing is nothing_found, never a
        # fetch attempt (design §5.0/5.1).
        refs = reference_images or ()
        payload: dict[str, object] | None = None
        form: aiohttp.FormData | None = None
        url: str
        if refs:
            if reference_resolver is None:
                return ImageResult(
                    status="unavailable", reason="no_reference_resolver"
                )
            bodies: list[bytes] = []
            for ref in refs:
                marker = _hex_handle(ref.marker_code)
                if len(marker) < 6:
                    return ImageResult(status="nothing_found", reason="bad_reference")
                try:
                    data = await reference_resolver(marker)
                except Exception:
                    log.exception("image_gen reference resolver raised")
                    data = None
                if data is None:
                    return ImageResult(
                        status="nothing_found", reason="unknown_reference",
                        provider="xai",
                    )
                bodies.append(data)

            form = aiohttp.FormData()
            form.add_field("model", model)
            form.add_field("prompt", prompt)
            form.add_field("response_format", "b64_json")
            if size is not None:
                form.add_field("aspect_ratio", size.aspect_ratio)
                # M7: same tier→resolution mapping as the generations path.
                resolution = {"small": "1k", "medium": "1k", "large": "2k"}[size.tier]
                form.add_field("resolution", resolution)
            for i, body in enumerate(bodies):
                form.add_field(
                    "image[]",
                    body,
                    filename=f"reference-{i}.png",
                    content_type="application/octet-stream",
                )
            url = self._edits_url
        else:
            payload = {
                "model": model,
                "prompt": prompt,
                "response_format": "b64_json",
            }
            if size is not None:
                payload["aspect_ratio"] = size.aspect_ratio
                # M7: honour the tier knob — xAI's API takes `resolution`
                # 1k/2k. Without this the model-facing `size` word silently
                # changed nothing (budget-2 re-roll with a "size tweak" that
                # burned a generation). Map the tier word to xAI's values.
                resolution = {"small": "1k", "medium": "1k", "large": "2k"}[size.tier]
                payload["resolution"] = resolution
            url = self._generations_url

        try:
            timeout = aiohttp.ClientTimeout(total=self._timeout.total)
            async with aiohttp.ClientSession(timeout=timeout) as session:
                headers = {"Authorization": f"Bearer {auth.access_token}"}
                if form is not None:
                    async with session.post(url, headers=headers, data=form) as resp:
                        body = await resp.json(content_type=None)
                else:
                    async with session.post(url, headers=headers, json=payload) as resp:
                        body = await resp.json(content_type=None)
        except (aiohttp.ClientError, TimeoutError, ValueError):
            return ImageResult(status="unavailable", reason="down", provider="xai")

        if resp.status == 200:
            items = body.get("data") if isinstance(body, dict) else None
            if not isinstance(items, list) or not items:
                return ImageResult(status="unavailable", reason="empty_response", provider="xai")
            first = items[0] if isinstance(items[0], dict) else {}
            # xAI is OpenAI-compatible: some models answer `b64_json` when
            # asked, some return `url`. Accept both so the adapter never
            # depends on an unverified response shape.
            b64 = first.get("b64_json")
            url_value = first.get("url")
            if isinstance(b64, str):
                try:
                    raw = base64.b64decode(b64)
                except ValueError:
                    return ImageResult(status="unavailable", reason="bad_response", provider="xai")
                # raw + media_type ride along so the caller can store the
                # image in Nora's own blob store (rustfs) and send it as a
                # platform attachment without a second fetch.
                return ImageResult(
                    status="ok",
                    artifact=f"data:image/png;base64,{b64}",
                    provider="xai",
                    raw=raw,
                    media_type="image/png",
                )
            elif isinstance(url_value, str) and url_value:
                return ImageResult(
                    status="ok", artifact=url_value, provider="xai",
                )
            else:
                return ImageResult(status="unavailable", reason="empty_response", provider="xai")

        # 403 is ambiguous on the subscription lane — quota exhaustion and
        # entitlement failures both surface as 403. Classify by body, and
        # never guess from the status alone (design §7).
        if resp.status == 403:
            code = (
                (body.get("error") or {}).get("code")
                if isinstance(body, dict)
                else None
            )
            if isinstance(code, str) and ("quota" in code.lower() or "limit" in code.lower()):
                return ImageResult(status="unavailable", reason="quota", provider="xai")
            if isinstance(code, str) and ("auth" in code.lower() or "entitle" in code.lower()):
                return ImageResult(status="unavailable", reason="auth", provider="xai")
            return ImageResult(status="unavailable", reason="unavailable", provider="xai")
        if resp.status == 429:
            return ImageResult(status="unavailable", reason="rate_limited", provider="xai")
        if resp.status in (400, 422):
            return ImageResult(status="nothing_found", reason="invalid_prompt", provider="xai")
        return ImageResult(status="unavailable", reason="down", provider="xai")

    async def health(self) -> bool:
        """A lane is healthy when it has a valid access token. No token → the
        tool will answer `unavailable`; a False here is a probe, not a raise."""
        state = await self._oauth.access_token()
        return state.status == "ok" and bool(state.access_token)
