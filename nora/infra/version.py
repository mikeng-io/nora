"""What version of herself Nora is running, and what was in each one.

WHAT THIS MODULE IS RESPONSIBLE FOR
-----------------------------------
Reading ONE baked artifact — `nora/version.json` — and answering two questions
about it fail-closed: *what am I running* and *what was in V2*. Nothing else.
It never writes, never reaches the network, and never raises.

WHY A BAKED FILE AND NOT A RUNTIME LOOKUP
-----------------------------------------
The container holds no git checkout and may not reach github.com, so "what am I
running" cannot be an API call: the answer would describe the repository, not
the artifact, and the two disagree the moment a deploy lags a merge. The file is
generated by `scripts/gen_version_manifest.py` from the tree being built (a tag
list plus each tag's annotation and commit subjects) and copied into the image
by the SAME `COPY nora/` that copies the code, so the version she reports and
the code she runs come from one filesystem snapshot. The Dockerfile then refuses
to build when the `NORA_VERSION` build argument disagrees with the file's own
`version` — that guard is what makes disagreement impossible rather than merely
unlikely.

THE THREE STATES, AND WHY THE DISTINCTION IS THE WHOLE POINT (R-27)
------------------------------------------------------------------
- `ok` — the manifest was read and it holds this version.
- `nothing_found` — the manifest was read and holds NO entry for the version
  asked about. «I have no record of a V9.»
- `unavailable` — the manifest is absent, unreadable, or does not say what is
  running. «I can't check», never «there is nothing».

A missing file is `unavailable` and NEVER `nothing_found`. Collapsing those two
is the exact wrong-source-read-as-nothing-found trap R-27 was registered for: a
build that forgot to stamp the manifest would otherwise have Nora state, with
confidence, that she has no versions at all — a false claim about herself,
sourced from a wiring gap. A dev checkout has no `version.json` (it is generated
at build time and gitignored), so `unavailable` is the ORDINARY state outside a
built image, not an exotic one.

There is deliberately no second implementation and therefore no port: every test
points this same class at a real file it wrote itself, which is the only way a
double could behave like the thing anyway (the repo's no-decorative-fakes
rule).
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path

log = logging.getLogger("nora.infra.version")

# The baked artifact, beside the package it describes. `parents[1]` is `nora/`
# — this module is `nora/infra/version.py`. Resolved from `__file__` rather than
# from a config key because the whole grounding claim is "the file that shipped
# with this code": a configurable path is a path that can point at another
# build's manifest.
DEFAULT_MANIFEST_PATH = Path(__file__).resolve().parents[1] / "version.json"

OK = "ok"
NOTHING_FOUND = "nothing_found"
UNAVAILABLE = "unavailable"


@dataclass(frozen=True)
class VersionEntry:
    """One released version, as the build recorded it.

    `notes` is the operator's own text — a tag annotation or release body — and
    is the ONLY thing the announcement relays. `changes` is the commit subjects
    the generator collected for the version; it is context for an answer to «what
    was in V2», never announcement copy (auto-generated subjects are not a note
    somebody wrote).

    Every field but `version` defaults to empty because a manifest is allowed to
    be thin: a version with no annotation has no `notes`, and answering with an
    empty string is honest where inventing one is not.
    """

    version: str
    released: str = ""
    commit: str = ""
    notes: str = ""
    changes: tuple[str, ...] = ()


@dataclass(frozen=True)
class VersionLookup:
    """R-27's three states, with the reason an operator needs when it is not `ok`.

    `known` carries every version the manifest DOES hold, and is populated on
    `nothing_found` as well as on `ok`: "I have no V9, I have V1 to V3" is a
    different and much more useful answer than "no". It stays empty on
    `unavailable`, because a manifest that could not be read cannot be quoted for
    what it contains either.
    """

    status: str
    entry: VersionEntry | None = None
    known: tuple[str, ...] = ()
    reason: str = ""


def _entry_from(raw: object) -> VersionEntry | None:
    """One manifest record, or `None` when it is not one.

    Defensive about SHAPE rather than trusting the generator, because this file
    is read by a process that cannot re-run the generator: a half-written or
    hand-edited manifest must degrade to «I can't check», not to a `TypeError`
    inside a tool call (which is a silent turn under R-5).
    """
    if not isinstance(raw, dict):
        return None
    version = raw.get("version")
    if not isinstance(version, str) or not version:
        return None
    changes = raw.get("changes")
    subjects = tuple(str(c) for c in changes) if isinstance(changes, list) else ()
    return VersionEntry(
        version=version,
        released=str(raw.get("released") or ""),
        commit=str(raw.get("commit") or ""),
        notes=str(raw.get("notes") or ""),
        changes=subjects,
    )


class VersionManifest:
    """The baked manifest, read at most once per process.

    Read-once rather than per call, and that is a grounding decision rather than
    a performance one: the running artifact cannot change under a live process,
    so the version she reports must not either. A per-call read would let a
    manifest deleted (or replaced) at runtime change her answer about the code
    she is already executing, which is precisely the disagreement the build-time
    stamp exists to rule out.

    The path arrives through `__init__` (the test-seam policy: collaborators and
    the values they are built from come in through the constructor, never through
    a module-level mutable), defaulting to the baked location so the composition
    root does not have to know where the build put it.
    """

    def __init__(self, path: Path | None = None) -> None:
        # Resolved HERE rather than as a parameter default, so the baked
        # location stays one name a test can repoint (a default is bound once,
        # at def time, and monkeypatching the constant afterwards would silently
        # do nothing — the shape that makes a wiring test decorative).
        self._path = Path(path) if path is not None else DEFAULT_MANIFEST_PATH
        self._read = False
        self._version = ""
        self._entries: dict[str, VersionEntry] = {}
        self._reason = ""

    def _load(self) -> None:
        """Read the file once, recording WHY it could not be read when it could not.

        Never raises: every failure lands in `self._reason`, which every lookup
        turns into `unavailable`. `OSError` covers absent/unreadable/permission,
        `ValueError` covers malformed JSON (`json.JSONDecodeError` is a subclass),
        and a well-formed file of the wrong SHAPE is caught by the isinstance
        checks below rather than by an exception, because a JSON array parses
        perfectly and is still not a manifest.
        """
        if self._read:
            return
        self._read = True
        try:
            raw = json.loads(self._path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            self._reason = "absent"
            log.info(
                "version manifest %s is absent — this build was not stamped "
                "(ordinary in a source checkout); version answers stay unavailable",
                self._path,
            )
            return
        except (OSError, ValueError) as exc:
            self._reason = "unreadable"
            log.warning("version manifest %s is unreadable: %s", self._path, exc)
            return
        if not isinstance(raw, dict):
            self._reason = "unreadable"
            log.warning("version manifest %s is not an object", self._path)
            return
        current = raw.get("version")
        if not isinstance(current, str) or not current:
            # A manifest that cannot say what is RUNNING is unreadable, not
            # empty: the one question this file exists to answer is unanswered,
            # so quoting the rest of it would be describing an artifact nothing
            # tied to this process.
            self._reason = "no_current_version"
            log.warning("version manifest %s names no running version", self._path)
            return
        self._version = current
        listed = raw.get("versions")
        for item in listed if isinstance(listed, list) else ():
            entry = _entry_from(item)
            if entry is not None:
                self._entries[entry.version] = entry

    @property
    def path(self) -> Path:
        return self._path

    def known(self) -> tuple[str, ...]:
        """Every version the manifest holds an entry for, oldest declaration first.

        Declaration order, not sorted: `V10` sorts before `V2` as a string, and
        the generator already writes them newest-first, which is the order a
        person reads a changelog in.
        """
        self._load()
        return tuple(self._entries)

    def current(self) -> VersionLookup:
        """What this process is running.

        `ok` carries the running version even when the manifest holds no ENTRY
        for it — «I am V3» and «here is what was in V3» are two facts, and a
        build stamped before its tag was annotated knows the first without the
        second. The entry is then a bare `VersionEntry(version=...)`: empty
        `notes`/`changes` say "nothing recorded", which is what the manifest
        actually says, rather than borrowing another version's contents.
        """
        self._load()
        if not self._version:
            return VersionLookup(status=UNAVAILABLE, reason=self._reason or "absent")
        entry = self._entries.get(self._version) or VersionEntry(version=self._version)
        return VersionLookup(status=OK, entry=entry, known=self.known())

    def lookup(self, which: str) -> VersionLookup:
        """What was in a NAMED version.

        `nothing_found` only ever means "the manifest was read and has no such
        version" — an unreadable manifest returns `unavailable` above it, so the
        two can never be confused by a caller that only reads `status`.

        Matching is case-insensitive and tolerates a bare number (`2`, `v2`,
        `V2` all reach V2): the model is quoting a person, and a case mismatch is
        not a reason to tell somebody their version does not exist.
        """
        self._load()
        if not self._version:
            return VersionLookup(status=UNAVAILABLE, reason=self._reason or "absent")
        wanted = _normalise(which)
        for name, entry in self._entries.items():
            if _normalise(name) == wanted:
                return VersionLookup(status=OK, entry=entry, known=self.known())
        return VersionLookup(status=NOTHING_FOUND, known=self.known())


def _normalise(raw: str) -> str:
    """`v2`, `V2`, ` 2 ` → `v2`. The scheme is plain V1/V2/V3 (no semver), so
    normalisation is a lowercase, a strip, and a re-attached `v` for a bare
    number — nothing that could make two DIFFERENT versions compare equal."""
    text = str(raw).strip().lower()
    if text.isdigit():
        return f"v{text}"
    return text
