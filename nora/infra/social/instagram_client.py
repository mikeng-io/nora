"""`InstagramSocialClient` — Nora's Instagram `SocialProvider`, on the
instagram-bridge's REAL contract (design/instagram-adoption/15, /17 P4).

It serves two `(platform, what)` rows over the bridge's account resources on
the private compose `nora` network:

* `instagram/story` → `GET /accounts/{igid}/story`. 200 with `found: true`
  → `ok`; 200 with `found: false` → `nothing_found`; anything else →
  `unavailable`.
* `instagram/profile` → `GET /accounts/{igid}`. 200 → `ok`; the handler's
  own 404 (`errNoProfile`) → `nothing_found`; anything else → `unavailable`.

`instagram/posts` is deliberately NOT served: no bridge route exists, and the
row answers `unavailable` without a call (P13 is the investigation).

The mapping is PER ROUTE because the two routes differ, read off the Go
handlers (`deploy/instagram-bridge/social.go`): the account route has a "no
such account" answer (404), the story route has none — an unknown igid is
`found: false` there too, which is acceptable because a story igid comes only
from the person index or from a lookup that just found the account. 409
(the session needs a human) and 503 (reconnecting) are `unavailable` on both,
as is every status nobody mapped.

**The bodies are pinned, not remembered.** `tests/fixtures/instagram_bridge/`
holds each route's bodies, GENERATED by the bridge's own handlers
(`deploy/instagram-bridge/contract_fixtures_test.go`) and read by this
client's tests. A shape change on either side fails on both. The client this
replaces POSTed `/social/story` and read a `status` envelope the bridge never
had, and nothing could notice because each side was tested against its own
idea of the other.

## What this client does NOT do, and why that is the interesting part

**It does not resolve a subject, and it does not authorize a tier.** Both used
to live here and moved to `SocialRouter` on 2026-09-22
(design/instagram-adoption/10 §"Who owns what"). The reason is not tidiness:
an authorization check inside ONE backend can only ever govern that backend's
rows, and the seven OpenCLI rows were therefore running with no subject
authorization at all while node 07 says the tier ladder governs *all* social
reads. A rule that reaches one of eight rows is not a ladder.

So `target` arrives here already RESOLVED and already AUTHORIZED: it is the
igid the person index bound, not the `person_id` the model named. This client
never sees a `person_id`, has no `SocialSubjectIndex`, and cannot produce
`ambiguous` or `refused` — those are the router's sentences, said before
anything is dispatched. It does check the igid's SHAPE before putting it in a
URL path: a decimal id or no call, so no target can name a different route.

## A story result carries the TEXT LAYER and references, never what the media shows

Every frame carries its text layer — the author's `caption`, Instagram's own
`alt_text` (`accessibility_caption`, «a photo of a plate»), the author, when
it was posted, its kind — and its media URL (design/instagram-adoption/18
§"Listing and reading one item"). That text is what lets Nora answer «is she
at the beach?» without a vision call. What the media SHOWS is not here:
`social_fetch` finds out *that* something exists, where, and what its author
and Instagram said about it; `media_fetch` finds out *what it is*.

**Where the text goes is the whole safety argument.** The caption and alt text
are stranger-written prose, so they go down exactly ONE path, the one the
profile bio already uses: type-checked as `str`, whitespace-collapsed onto one
line (so a caption cannot forge a frame line of its own), rendered into
`text`, then `wrap_outside_text` (R-13) and `clamp_chars`. They are NOT copied
into `items`: `social_fetch` hands the whole result dict to the model, so a
caption in `items` would be stranger prose OUTSIDE the untrusted wrap and
outside the clamp. `items` stays `{id, kind, taken_at, url}` — the
machine-usable handoff to `media_fetch(url=…)`, which needs nothing else.
`author` also rides the result top-level, because it is shape-checked as an
Instagram handle and so cannot carry prose. A non-string caption is dropped,
never `str()`-ed.

**A whitelist of KEY NAMES is not that rule — it is a third of it.** An
adversarial audit (2026-09-22) executed the three value channels the key
whitelist left open and got content through all three: `note` was a verbatim
unbounded passthrough into the model's instruction slot; `url` was
scheme-checked only, so any https host arrived rendered as text plus an
instruction to `media_fetch` it; and `id` accepted ANY type and `str()`-ed it,
so `id={"caption": "at the beach with tyler"}` put that caption in the result
while the guard test — which asserted the key SET and that "beach" was not in
`text` — stayed green on both counts. So every value is bound to its own
shape: nothing the bridge writes lands in `note`, the URL host must be a
MEASURED Instagram CDN host, the id must look like an id, and the only
free-text fields (caption, alt text) are strings that reach the model inside
the wrap and nowhere else. A key whitelist answers "which fields"; only a
value check answers "carrying what".

## A profile result is the account's OWN words, wrapped

A profile is different in kind: its bio and display name ARE stranger-written
prose, and the answer to «what's her Instagram like» is exactly that prose. So
the profile is rendered from the curated fields — identity (handle, name),
both follow directions, private or public, the counts, whether a story is up,
the bio — into the same `social_post` wrapper and the same clamp as a story.
Nothing is copied wholesale: `extra` (the bridge's unmodelled wire keys, "NOT
a stable contract" by its own comment) is never read, and neither id is
rendered — the fbid and the igid are identifiers, not something to say.

`social_available: false` means the bridge's SECOND call failed while the
first answered. The result is still `ok` — the account exists and was read —
and the text says in so many words which half is missing, because an empty
bio and an unread bio are different facts and the model must not say «she has
no bio» from a rate limit (R-27, one field down).

## No cursor, and stories do not paginate

A reel arrives WHOLE from the protocol, so there is no `next_cursor` on this
path and asking for more of a story is asking for something that does not
exist. `limit` is therefore a NORA-SIDE clamp, applied after the response —
worth doing anyway, because a fifteen-item story would otherwise arrive
entire and every token of a tool result is re-sent on every subsequent model
call. The route takes no limit, so nothing is told to the bridge that it
could interpret differently.

## The URLs expire, and that cuts in the design's favour

Instagram CDN URLs are signed (`oh=`, `oe=`, `_nc_sid`) and the signature IS
the authorization: measured, a story video fetches `200 video/mp4` with no
cookies, no UA and no referer, so `media_fetch` carrying no session is not a
problem. They are also valid for a window rather than indefinitely, which is
why the reel's `expiring_at` rides the result as `expires_at`: a two-step
"list now, look later" flow has to be SOON after, and a stored URL is a dead
link.

## A story must be SAID to be a story, and the result is what says it

The media vanishes in 24 hours. Nora's REPLY about it does not: every sent
message is fed to Honcho as durable conclusions
(`nora/engagement/stages/feedback.py`). So «he was at the beach» launders a
perishable observation into permanent knowledge, indistinguishable a week
later from something he actually said, while «his story from 3h ago showed a
beach» ages honestly on its own (design/instagram-adoption/06 §"a story must
be SAID to be a story"). The phrasing is the whole mitigation, because it
travels WITH the claim — a retention rule cannot reach into a Honcho
conclusion and a phrasing rule is already inside it.

Two things therefore ride an `ok` story result: `source_kind` says what this
is in one token nothing can mistake — `instagram_story`, not a bare URL that
could be anything — and `note` carries the framing, adjacent to the
`taken_at` and `expires_at` it is talking about.

**In the RESULT, not in the tool description.** Measured while compressing
prompt tokens: 54% of all tool-description text (8,602 of 16,045 tokens) is
result-handling prose read only after a call returns, paid on every call of
every turn for all 54 tools. A result-carried instruction costs nothing unless
a story was actually fetched, and it arrives at the moment the model is
choosing how to phrase the answer rather than thousands of tokens earlier.
That also sets its length: this is prose re-sent on every subsequent model
call of the turn, so it is three sentences and not a policy.
"""

