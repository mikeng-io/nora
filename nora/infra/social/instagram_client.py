"""`InstagramSocialClient` — Nora's Instagram `SocialProvider`, on the
instagram-bridge's contract.

It serves four `(platform, what)` rows over the bridge's resources on the
private compose `nora` network:

* `instagram/story` → `GET /accounts/{igid}/story`. 200 with `found: true`
  → `ok`; 200 with `found: false` → `nothing_found`; anything else →
  `unavailable`.
* `instagram/profile` → `GET /accounts/{igid}`. 200 → `ok`; the handler's
  own 404 (`errNoProfile`) → `nothing_found`; anything else → `unavailable`.
* `instagram/search` → `GET /accounts?query=` (`instagram_search`). 200
  with items → `ok`, at most `SEARCH_MAX_ACCOUNTS` of them, in the bridge's
  order: `accounts` is `{username, is_verified}` per account, and `text` is
  every account with its display name, wrapped; no igid or fbid anywhere.
  200 with no items → `nothing_found`; anything else (409, 502, 503, …) →
  `unavailable`. See `_search` and `_accounts`.
* `instagram/post` → `GET /posts/{shortcode}` (a post or reel a person pasted
  a link to). 200 → `ok`, every item in the bridge's order; the handler's own
  404 → `nothing_found`; anything else → `unavailable`. See `_post`.

And one lookup that is not a read at all, `igid_for_username`
(`InstagramAccountLookup`): `GET /accounts?username=` → the igid of the
account whose username is EXACTLY the one asked for. Only `SocialRouter` calls
it, to resolve a typed handle or a link's username before it authorizes; the
igid never reaches the model.

`instagram/posts` (a person's post LIST) is deliberately NOT served: no bridge
route exists, and the row answers `unavailable` without a call.

The mapping is PER ROUTE because the routes differ, as the Go handlers show
(`deploy/instagram-bridge/social.go`): the account route has a "no such
account" answer (404), the story route has none — an unknown igid is
`found: false` there too, which is acceptable because a story igid comes only
from the person index or from a lookup that just found the account. 409
(the session needs a human) and 503 (reconnecting) are `unavailable` on both,
as is every status nobody mapped.

**The bodies are pinned.** `tests/fixtures/instagram_bridge/` holds each
route's bodies, GENERATED by the bridge's own handlers
(`deploy/instagram-bridge/contract_fixtures_test.go`) and read by this
client's tests. A shape change on either side fails on both.

## What this client does NOT do, and why that is the interesting part

**It does not resolve a subject, and it does not authorize a tier.** Both are
`SocialRouter`'s. An authorization check inside ONE backend can only govern
that backend's rows, and the tier ladder governs *all* social reads.

So `target` arrives here already RESOLVED and already AUTHORIZED: it is the
igid the person index bound, not the `person_id` the model named. This client
never sees a `person_id`, has no `SocialSubjectIndex`, and cannot produce
`ambiguous` or `refused` — those are the router's sentences, said before
anything is dispatched. It does check the igid's SHAPE before putting it in a
URL path: a decimal id or no call, so no target can name a different route.

## Views in, one renderer out, and what each item SHOWS

Every read is built into a typed VIEW (`views.py`: `PostView`, `StoryView`,
`ProfileView`, `SearchView`) by the builders at the bottom of this module,
field by field and with a value check per field, and turned into what the
model reads by ONE renderer (`render.py`). This module writes no
model-facing dict for an `ok` answer: the wrap, the clamp, the notes and the
layout live there.

A post, reel or story read that is handed `media_fetch` (`look`, which the
router forwards for those two rows only) comes back with what each item
SHOWS: `readings.read_view` reads the first items through `media_fetch(url=…)`
itself, the url and nothing else, so the caption never reaches a vision
prompt. Handed nothing, it is the text layer and the links.

## Every frame carries its TEXT LAYER, and where the text goes is the safety argument

Every frame carries its text layer — the author's `caption`, Instagram's own
`alt_text` (`accessibility_caption`, «a photo of a plate»), the author, when
it was posted, its kind — and its media URL. That text is what lets Nora
answer «is she at the beach?» from what the poster and Instagram said, beside
what the frame shows.

**Where the text goes is the whole safety argument.** The caption and alt text
are stranger-written prose, so they go down exactly ONE path, the one the
profile bio also uses: type-checked as `str`, whitespace-collapsed onto one
line (so a caption cannot forge a frame line of its own), rendered into
`text`, then `wrap_outside_text` (R-13) and `clamp_chars`. They are NOT copied
into `items`: `instagram_read` hands the whole result dict to the model, so a
caption in `items` would be stranger prose OUTSIDE the untrusted wrap and
outside the clamp. `items` stays `{kind, url, taken_at}` — the
machine-usable handoff to `media_fetch(url=…)`, which needs nothing else.

**No `id`.** `media_fetch` takes the URL, so a frame's id is never read. It
would also be an identifier leak: when a reel item has no `pk`, the bridge's
`storyFrame` falls back to `item.ID`, which Instagram shapes as
`<pk>_<owner igid>`, so the story OWNER's igid could reach the model (R-18).
`author` rides the result top-level, because it is shape-checked as an
Instagram handle and so cannot carry prose. A non-string caption is dropped,
never `str()`-ed.

**A whitelist of KEY NAMES is not that rule — it is a third of it.** Three
value channels stay open under a key whitelist alone: a `note` passed through
verbatim into the model's instruction slot; a `url` checked only for scheme,
so any https host arrives rendered as text plus an instruction to
`media_fetch` it; and an `id` accepted of ANY type and `str()`-ed, so
`id={"caption": "at the beach with tyler"}` would put that caption in the
result. So every value is bound to its own shape: nothing the bridge writes
lands in `note`, the URL host must be a known Instagram CDN host, the id is
not read at all, and the only free-text fields (caption, alt text) are
strings that reach the model inside the wrap and nowhere else. A key
whitelist answers "which fields"; only a value check answers "carrying what".

## A profile result is the account's OWN words, wrapped

A profile is different in kind: its bio and display name ARE stranger-written
prose, and the answer to «what's her Instagram like» is exactly that prose. So
the profile is rendered from the curated fields — identity (handle, name),
both follow directions, private or public, the counts, whether a story is up,
the bio — into the same `social_post` wrapper and the same clamp as a story.
Nothing is copied wholesale: `extra` (the bridge's unmodelled wire keys, "NOT
a stable contract" by its own comment) is never read, and neither id is
rendered — the fbid and the igid are identifiers, not something to say.

`social_available: false` means the bridge's SECOND call failed while the
first answered. The result is still `ok` — the account exists and was read —
and the text says in so many words which half is missing, because an empty
bio and an unread bio are different facts and the model must not say «she has
no bio» from a rate limit (R-27, one field down).

## No cursor, and stories do not paginate

A reel arrives WHOLE from the protocol, so there is no `next_cursor` on this
path and asking for more of a story is asking for something that does not
exist. `limit` is therefore a NORA-SIDE clamp, applied after the response —
worth doing anyway, because a fifteen-item story would otherwise arrive
entire and every token of a tool result is re-sent on every subsequent model
call. The route takes no limit, so nothing is told to the bridge that it
could interpret differently.

## The URLs expire

Instagram CDN URLs are signed (`oh=`, `oe=`, `_nc_sid`) and the signature IS
the authorization: a story video fetches `200 video/mp4` with no cookies, no
UA and no referer, so `media_fetch` carrying no session is not a problem.
They are also valid for a window rather than indefinitely, which is why the
reel's `expiring_at` rides the result as `expires_at`: a two-step "list now,
look later" flow has to be SOON after, and a stored URL is a dead link.

## A story must be SAID to be a story, and the result is what says it

The media vanishes in 24 hours. Nora's REPLY about it does not: every sent
message is fed to Honcho as durable conclusions
(`nora/engagement/stages/feedback.py`). So «he was at the beach» launders a
perishable observation into permanent knowledge, indistinguishable a week
later from something he actually said, while «his story from 3h ago showed a
beach» ages honestly on its own. The phrasing is the whole mitigation, because
it travels WITH the claim — a retention rule cannot reach into a Honcho
conclusion and a phrasing rule is already inside it.

Two things therefore ride an `ok` story result: `source_kind` says what this
is in one token nothing can mistake — `instagram_story`, not a bare URL that
could be anything — and `note` carries the framing, adjacent to the
`taken_at` and `expires_at` it is talking about.

**In the RESULT, not in the tool description.** Result-handling prose in a
tool description is read only after a call returns, yet paid on every call of
every turn for every tool. A result-carried instruction costs nothing unless
a story was actually fetched, and it arrives at the moment the model is
choosing how to phrase the answer. That also sets its length: this is prose
re-sent on every subsequent model call of the turn, so it is three sentences
and not a policy.
"""

