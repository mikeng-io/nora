#: The rows this backend serves. A request for anything else reaching here is
#: a ROUTING bug, not a user error, so it is `unavailable` (a wiring gap), is
#: logged, and never reaches the bridge. `instagram/posts` is absent on
#: purpose: the bridge has no route for it.
_SERVES: frozenset[tuple[str, str]] = frozenset({
    ("instagram", "story"),
    ("instagram", "profile"),
    ("instagram", "search"),
    # One post or reel, by the shortcode of a link a person pasted.
    ("instagram", "post"),
})

#: The post route's own 404: Instagram answered that there is no such post.
#: Nora's sentence, never the bridge's message (`results.py`). It does not
#: say why (deleted, private, never existed).
POST_NOTHING_FOUND: dict[str, Any] = {
    "status": "nothing_found",
    "note": "Instagram found no post at that link. Say you couldn't find it; "
            "don't describe it.",
}

#: The post route's 501: a shortcode the bridge has no mechanism to read yet
#: (longer than 11 characters). A stable fact about the
#: link, not a passing failure, so the note says a retry will not help.
POST_UNSUPPORTED: dict[str, Any] = {
    "status": "unavailable",
    "note": "I can't read that kind of post link yet. Say so plainly; trying "
            "again won't help.",
}

#: At most this many accounts reach the model from one search, whatever the
#: bridge returned and whatever `limit` said. Stated in `instagram_search`'s
#: description, so the model knows a short list is not the whole of
#: Instagram. A person's account is almost always at rank 0 of an
#: exact-username search, so a refined query, not a longer list, is what
#: finds the rest. Every account costs its tokens again
#: on every later model call of the turn.
SEARCH_MAX_ACCOUNTS = 5

#: A display name's own ceiling, before the wrap. Instagram caps a full name
#: at 30 characters; 64 leaves room without letting one field carry a
#: paragraph of stranger prose.
_FULL_NAME_MAX_CHARS = 64

#: Zero accounts: the search RAN and matched nobody. Nora's sentence, never
#: the bridge's (`results.py`).
SEARCH_NOTHING_FOUND: dict[str, Any] = {
    "status": "nothing_found",
    "note": "Instagram's search matched no account. Say you couldn't find "
            "one; don't guess a handle.",
}

#: An igid, as the bridge parses one (`domain.ParseIGID`: a positive int64,
#: so at most 19 digits). Checked BEFORE
#: it is put in a URL path: a target that is not a decimal id could
#: otherwise name a different route (`../send`), which is a much worse wiring
#: gap than a 400.
_IGID_RE = re.compile(r"[0-9]{1,19}")

#: What an Instagram username may look like. It is rendered into the text the
#: model reads (and a story's author rides the result unwrapped), so it is
#: shape-checked rather than trusted.
_USERNAME_RE = re.compile(r"[A-Za-z0-9._]{1,30}")

#: Story media kinds, normalised. An unrecognised kind becomes `"media"`
#: rather than riding through verbatim: the value is rendered into text the
#: model reads and reasons about, and a vocabulary that can grow silently is
#: a vocabulary nothing can be asserted against.
_KINDS: frozenset[str] = frozenset({"image", "video"})

#: A hard ceiling on items regardless of `limit`, mirroring the OpenCLI path's
#: `content_max_chars`. The reel arrives whole and the caller's `limit` has
#: already been clamped at the tool layer, so this only binds if BOTH of those
#: are wrong at once — which is the case worth being defended against, since
#: what it costs is the model's whole re-sent input.
_MAX_ITEMS = 20

#: The hosts a story frame is actually served from — the
#: `FetchReel` envelope carries `https://instagram.f….fbcdn.net/…`
#: and the `scontent.*.cdninstagram.com` form
#: of the same CDN. `https://` alone is not a check: the URL is rendered into
#: text the model reads TOGETHER WITH an instruction to `media_fetch` it, so a
#: scheme-only guard lets any host on the internet arrive as an attacker-chosen
#: fetch target dressed as a story frame. Matched on the parsed hostname, never
#: on the string — `https://scontent.cdninstagram.com.evil.test/x` and
#: `https://evil.test/?u=.fbcdn.net` both defeat a substring test.
_CDN_HOST_SUFFIXES: tuple[str, ...] = (".fbcdn.net", ".cdninstagram.com")



class InstagramSocialClient(SocialProvider):
    """The instagram-bridge's account and story routes. NEVER raises.

    Collaborators through `__init__` only (test-seam policy), and there is no
    `SocialSubjectIndex` among them: `target` is the igid the ROUTER resolved
    and authorized, so this client cannot look a person up and cannot decide
    whether it may. Not having the collaborator is what makes that structural
    rather than a convention — a backend holding an index is a backend one
    edit away from carrying its own copy of the tier rule.

    `base_url` reaches the bridge as a co-networked container
    (`http://instagram-bridge:PORT`); nothing is published to the host. Every
    request carries W3C trace context (`propagation_headers`), so the bridge's
    spans join the turn's trace.
    """

    def __init__(
        self,
        *,
        base_url: str,
        timeout_seconds: float = 30.0,
        content_max_chars: int = 4000,
    ) -> None:
        self._base_url = base_url.rstrip("/")
        self._timeout_seconds = timeout_seconds
        self._content_max_chars = content_max_chars

    async def read(
        self, *, platform: str, what: str, target: str, limit: int,
        look: TurnLook | None = None,
    ) -> dict[str, Any]:
        """One read. NEVER raises (R-5).

        Three states, which is R-27's core and nothing more: `ok`,
        `nothing_found` (I looked, nothing there), `unavailable` (I could not
        look). The other two a subject read can produce — `ambiguous` and
        `refused` — are decided ABOVE this, in the router, and are never
        reached with a call to make.

        `look` is the caller's `media_fetch` and the turn's slots. With it,
        a post or a story comes back with what each item shows
        (`readings.read_view`); a profile and a search read no media and
        never use it.
        """
        try:
            return await self._read(
                platform=platform, what=what, target=target, limit=limit, look=look,
            )
        except Exception:
            # The never-raises backstop, identical in posture to the OpenCLI
            # client's: a contract violation degrades to `unavailable` and
            # never propagates into the loop.
            log.exception("instagram social read failed")
            return dict(UNAVAILABLE)

    async def _read(
        self, *, platform: str, what: str, target: str, limit: int,
        look: TurnLook | None,
    ) -> dict[str, Any]:
        if (platform, what) not in _SERVES:
            log.warning("instagram social client asked for a row it does not serve")
            return dict(UNAVAILABLE)
        if what == "search":
            # A search's target is FREE TEXT a person typed (a `named` input,
            # never resolved), not an igid, so it takes the query path and
            # never the igid shape check below.
            return await self._search(query=target, limit=limit)
        if what == "post":
            # A post's target is the SHORTCODE of a link a person pasted,
            # validated by the tool against the one link parser; checked
            # again here, because it goes into a URL path.
            code = target.strip()
            if not SHORTCODE_RE.fullmatch(code):
                log.warning("instagram social client given a target that is not a shortcode")
                return dict(UNAVAILABLE)
            return await self._post(shortcode=code, look=look)
        # `target` is the igid the router resolved out of the person index —
        # never a `person_id` and never a handle. One that is not a decimal
        # id is a routing bug in the same family as the row check above, so
        # it is a wiring gap rather than a question about the subject, and it
        # is not sent: it goes into a URL PATH, where anything else could
        # address a different route, and a blank one would be handed to the
        # bridge to decide what it means.
        igid = target.strip()
        if not _IGID_RE.fullmatch(igid):
            log.warning("instagram social client given a target that is not an igid")
            return dict(UNAVAILABLE)
        if what == "story":
            return await self._story(igid=igid, limit=limit, look=look)
        return await self._profile(igid=igid)

    async def _story(self, *, igid: str, limit: int, look: TurnLook | None) -> dict[str, Any]:
        status, payload = await self._get(f"/accounts/{igid}/story")
        if status != 200 or not isinstance(payload, dict):
            # The story route has NO "no such account" answer, so no non-200
            # here is a fact about the subject: 409 needs a human, 503 is
            # reconnecting, 400/500 and anything unmapped are ours.
            #
            # The envelope's `code` is logged, never shown: a 501
            # `stale_query` (the story doc_id rotated, or names another
            # document) and a 501 `unsupported` (none configured) both need
            # an operator, and without this line both read as one more
            # «unavailable».
            code = _error_code(payload) if isinstance(payload, dict) else None
            log.warning("instagram bridge story read answered %s (code=%s)", status, code)
            return dict(UNAVAILABLE)
        found = payload.get("found")
        if found is False:
            # The bridge found no reel: no story up, or none Nora may see —
            # `found: false` says exactly that much. This is the ONLY path to
            # `nothing_found` on this route.
            #
            # Nothing the bridge wrote reaches `note`: that slot tells the
            # model what it may say. There is one honest sentence for this
            # state and it is ours (`results.py`).
            return dict(NOTHING_FOUND)
        if found is not True:
            # No `found` at all, or not a boolean: the body is not the
            # documented shape — a wiring gap, never read as a miss.
            log.warning("instagram bridge story body carried no boolean `found`")
            return dict(UNAVAILABLE)
        view = story_view(payload, limit=limit)
        if view is None:
            # `found: true` with nothing usable in it is a wiring gap, NOT «no
            # story» — the route has a dedicated `found: false` for that and
            # this is not it. Answering `nothing_found` here would manufacture
            # a claim about the subject out of our own failure to read a body.
            log.warning("instagram bridge found a story with no usable items")
            return dict(UNAVAILABLE)
        return await self._answer(view, look)

    async def _profile(self, *, igid: str) -> dict[str, Any]:
        status, payload = await self._get(f"/accounts/{igid}")
        if status == 404:
            # `errNoProfile`: the igid names no account — a fact about the
            # subject. But only when it is the HANDLER's 404, which is the
            # error envelope with code `not_found`; Go's mux answers an
            # unmatched path with a plain-text 404, and reading THAT as «no such
            # account» would turn a wrong base URL into a confident claim about
            # a person.
            if isinstance(payload, dict) and _error_code(payload) == "not_found":
                return dict(NOTHING_FOUND)
            log.warning("instagram bridge 404 was not the account route's own")
            return dict(UNAVAILABLE)
        if status != 200 or not isinstance(payload, dict):
            return dict(UNAVAILABLE)
        view = profile_view(payload)
        if view is None:
            # A 200 with no usable identity in it is a wiring gap, not an
            # account: the handler always names the account it read.
            log.warning("instagram bridge profile body carried no usable username")
            return dict(UNAVAILABLE)
        # A profile reads no media: it is rendered, never looked at.
        return await self._answer(view, None)

    async def _search(self, *, query: str, limit: int) -> dict[str, Any]:
        """`GET /accounts?query=` → up to `SEARCH_MAX_ACCOUNTS` accounts, in
        the bridge's order.

        The query is not validated here: the tool refuses a blank or
        over-long one before anything is sent, and the bridge re-validates
        (400). A 400 reaching this line is therefore our bug, and it is
        `unavailable`, never a claim about Instagram.

        Success is
        `{"items": [...], "next_cursor": null}` with no `ok` field, failure is
        `{"error": {"code", "message"}}`. Only a 200 is read. 409 (the session
        needs a human), 502 (Instagram rejected the search), 503 (no session)
        and every status nobody mapped are `unavailable`, and the envelope's
        `message` never reaches the model.
        """
        path = "/accounts?" + urllib.parse.urlencode({"query": query})
        status, payload = await self._get(path)
        if status != 200 or not isinstance(payload, dict):
            return dict(UNAVAILABLE)
        raw = payload.get("items")
        if not isinstance(raw, list):
            # No list at all is not the documented shape: a wiring gap, never
            # read as «matched nobody».
            log.warning("instagram bridge search body carried no `items` list")
            return dict(UNAVAILABLE)
        if not raw:
            # The ONLY path to `nothing_found`: the search ran and the bridge
            # said, in its own documented shape, that it matched nobody.
            return dict(SEARCH_NOTHING_FOUND)
        view = search_view(raw, limit=limit)
        if view is None:
            # Items came back and none was usable: our failure to read a
            # body, not a fact about who exists on Instagram.
            log.warning("instagram bridge search returned no usable account")
            return dict(UNAVAILABLE)
        # A search reads no media: it is rendered, never looked at.
        return await self._answer(view, None)

    async def igid_for_username(self, *, username: str) -> UsernameLookup:
        """`GET /accounts?username=` → the igid of the ONE account whose
        username is exactly `username` (`InstagramAccountLookup`). NEVER
        raises; everything it cannot answer is `unavailable`."""
        try:
            return await self._lookup(username)
        except Exception:
            log.exception("instagram username lookup failed")
            return UsernameLookup("unavailable")

    async def _lookup(self, username: str) -> UsernameLookup:
        """The bridge filters to an exact, ASCII case-insensitive match and
        answers 0 or 1 accounts. This client does NOT trust that
        and does not re-pick either: it keeps only rows whose username IS the
        one asked for, and answers `found` only when exactly one is left.
        `items[0]` is never taken: an exact match need not be the
        search's first result, which is why the bridge filters, and a
        client that took the first row would undo that the day the bridge
        regressed.

        * 200 with no items → `none` (no such account);
        * 200 with items but no exact match, or several, or a match with no
          usable igid → `unavailable`: the bridge broke its own contract, and
          «no such account» would be a claim made from a body nobody can
          trust (`ambiguous` is not used: that word's sentence is about the
          operator's file);
        * any other status → `unavailable` (400 is our bug, the handle was
          checked before the call; 409, 502 and 503 are the bridge's).
        """
        wanted = username.strip().lstrip("@")
        if not is_handle(wanted):
            # The tool checks the handle first; one that is not a handle here
            # is a wiring gap, and it is not sent.
            log.warning("instagram username lookup given a string that is not a handle")
            return UsernameLookup("unavailable")
        path = "/accounts?" + urllib.parse.urlencode({"username": wanted})
        status, payload = await self._get(path)
        if status != 200 or not isinstance(payload, dict):
            return UsernameLookup("unavailable")
        raw = payload.get("items")
        if not isinstance(raw, list):
            log.warning("instagram bridge username lookup carried no `items` list")
            return UsernameLookup("unavailable")
        if not raw:
            return UsernameLookup("none")
        exact = [
            row for row in raw
            if isinstance(row, dict)
            and (name := _username(row.get("username"))) is not None
            and name.lower() == wanted.lower()
        ]
        if len(exact) != 1:
            log.warning("instagram bridge username lookup did not answer one exact match")
            return UsernameLookup("unavailable")
        igid = exact[0].get("igid")
        if not isinstance(igid, str) or not _IGID_RE.fullmatch(igid):
            log.warning("instagram bridge username lookup answered no usable igid")
            return UsernameLookup("unavailable")
        return UsernameLookup("found", igid)

    async def _post(self, *, shortcode: str, look: TurnLook | None) -> dict[str, Any]:
        """`GET /posts/{shortcode}` → the whole post: every item in the
        bridge's order (a carousel keeps its order), the author and the
        caption, and with `look`, what each of the first items shows.

        The same value discipline as a story: every item is `{kind, url}`
        plus `duration_seconds` for a video, the url must be on a known
        Instagram CDN host, and nothing else from the item is read. The
        caption is stranger prose, so it goes only into the wrapped, clamped
        `text`, and LAST there, so the clamp cuts it before any item. The
        shortcode the bridge echoes is not read back: the model already has
        the link it pasted, and nothing here carries an id.

        * 200 → `ok`; with no usable item it is `unavailable`, never a miss;
        * the handler's own 404 (`{"error": {"code": "not_found"}}`) →
          `nothing_found`; a 404 that is not the handler's is `unavailable`;
        * 501 (a shortcode no mechanism reads yet) → `unavailable`, saying a
          retry will not help;
        * 400, 409, 502, 503 and anything unmapped → `unavailable`.
        """
        status, payload = await self._get(f"/posts/{shortcode}")
        if status == 404:
            if isinstance(payload, dict) and _error_code(payload) == "not_found":
                return dict(POST_NOTHING_FOUND)
            log.warning("instagram bridge 404 was not the post route's own")
            return dict(UNAVAILABLE)
        if status == 501 and isinstance(payload, dict) and _error_code(payload) == "unsupported":
            return dict(POST_UNSUPPORTED)
        if status != 200 or not isinstance(payload, dict):
            return dict(UNAVAILABLE)
        view = post_view(payload)
        if view is None:
            log.warning("instagram bridge post carried no usable item")
            return dict(UNAVAILABLE)
        return await self._answer(view, look)

    async def _answer(self, view: View, look: TurnLook | None) -> dict[str, Any]:
        """An `ok` view → what the model reads, through the ONE renderer.

        A post or a story handed `look` is read first: `read_view` fills a
        `Reading` on each of its first items through `media_fetch(url=…)`,
        and one item's failure is that item's. A profile or a search is
        never looked at, whatever it is handed."""
        if look is not None and isinstance(view, (PostView, StoryView)):
            view = await read_view(view, look)
        return render(Result("ok", view=view), max_chars=self._content_max_chars)

    async def _get(self, path: str) -> tuple[int, Any]:
        """One GET on the bridge → `(status, parsed JSON or None)`. The body
        is parsed whatever the status, because the account route's 404 is
        told apart from the mux's by its body. A non-JSON body is `None`."""
        timeout = aiohttp.ClientTimeout(total=self._timeout_seconds)
        async with (
            aiohttp.ClientSession(timeout=timeout) as session,
            session.get(f"{self._base_url}{path}", headers=propagation_headers()) as response,
        ):
            status = response.status
            text = await response.text()
        if status != 200:
            # The route, not the igid: a person's identifier stays out of
            # this log line (the bridge logs it on its own host).
            log.warning("instagram bridge answered %s", status)
        try:
            return status, json.loads(text)
        except ValueError:
            if status == 200:
                log.warning("instagram bridge did not return JSON")
            return status, None



# ---- the view builders: bridge JSON → a view, one checked field at a time ------
#
# The ONLY code that reads a bridge body into something the model will see.
# Each builder reads a listed key, checks its VALUE, and writes it into a
# view; nothing is copied through, and an unlisted key is never read, so a
# body that grows an `ocr_text` or an `id` grows nothing here. `None` from a
# builder means the body held nothing usable: the caller answers
# `unavailable`, never `nothing_found`.


def story_view(payload: dict[str, Any], *, limit: int) -> StoryView | None:
    """The story route's `found: true` body → a `StoryView` of at most
    `limit` frames, or `None` when no frame is usable."""
    frames = _items(payload.get("items"), limit=limit)
    if not frames:
        return None
    # The reel's `expiring_at` bounds the whole set; it is named
    # `expires_at` in the result, beside the note that refers to it.
    expires_at = _as_int(payload.get("expiring_at"))
    return StoryView(
        author=_username(payload.get("username")),
        expires_at=expires_at,
        items=tuple(frames),
    )


def post_view(payload: dict[str, Any]) -> PostView | None:
    """The post route's 200 body → a `PostView`, every item in the bridge's
    order, or `None` when no item is usable. The shortcode the bridge echoes
    is not read."""
    items, more = _post_items(payload.get("items"))
    if not items:
        return None
    return PostView(
        author=_username(payload.get("author")),
        caption=_one_line(payload.get("caption")),
        taken_at=_as_int(payload.get("taken_at")),
        items=tuple(items),
        more=more,
    )


def profile_view(body: dict[str, Any]) -> ProfileView | None:
    """The account route's 200 → a `ProfileView`, or `None` when the body
    names no usable account.

    Built field by field, every value type-checked: a boolean that is not a
    `bool` and a count that is not an `int` are `None`, never guessed.
    Neither id is read, and neither is `extra` (the bridge's unmodelled wire
    keys, "NOT a stable contract" by its own comment). `social` is kept only
    when the bridge says its second call answered AND it holds something:
    otherwise the render says that half could not be read."""
    username = _username(body.get("username"))
    if username is None:
        return None
    full_name = body.get("full_name")
    social = body.get("social") if body.get("social_available") is True else None
    if not isinstance(social, dict) or not social:
        social = None
    return ProfileView(
        username=username,
        full_name=full_name.strip() if isinstance(full_name, str) and full_name.strip() else None,
        following=_bool(body.get("following")),
        has_story=_bool(body.get("has_story")),
        social=None if social is None else ProfileSocial(
            followed_by=_bool(social.get("followed_by")),
            is_private=_bool(social.get("is_private")),
            follower_count=_count(social.get("follower_count")),
            following_count=_count(social.get("following_count")),
            media_count=_count(social.get("media_count")),
            clips_count=_count(social.get("total_clips_count")),
            biography=_bio(social.get("biography")),
        ),
    )


def search_view(raw: list[Any], *, limit: int) -> SearchView | None:
    """The search body's `items` → at most `SEARCH_MAX_ACCOUNTS` accounts in
    the bridge's order, or `None` when none is usable."""
    accounts = _accounts(raw)
    if not accounts:
        return None
    cap = max(1, min(_cap(limit), SEARCH_MAX_ACCOUNTS))
    # The bridge's order, kept: it is Instagram's ranking, and the note
    # tells the model the first is not always the one.
    shown = accounts[:cap]
    return SearchView(accounts=tuple(shown), truncated=len(accounts) > cap)


def _accounts(raw: list[Any]) -> list[AccountView]:
    """The search body's `items` → one `AccountView` per usable row, in the
    bridge's order.

    **No id is read.** The bridge sends `igid` and `fbid` on every hit;
    neither is read, so neither can reach the model (R-18). A follow-up read
    names the account by its handle.

    * `username`: shape-checked as an Instagram handle, so it carries no
      prose; a row without a valid one is dropped (it is not an account
      anyone can name).
    * `is_verified`: `True` only when the bridge says `true`. A missing or
      malformed flag must never make an account read as verified.
    * the display name (`full_name`): stranger-written, so a `str` or
      nothing, collapsed onto one line and clamped. The renderer puts it only
      into the wrapped `text`, never into `accounts`, for the reason a story
      caption is kept out of `items`: the result dict reaches the model whole.
    """
    out: list[AccountView] = []
    for row in raw:
        if not isinstance(row, dict):
            continue
        username = _username(row.get("username"))
        if username is None:
            continue
        name = _one_line(row.get("full_name"))
        if name is not None:
            name, _clamped = clamp_chars(name, _FULL_NAME_MAX_CHARS)
        out.append(AccountView(
            username=username, is_verified=row.get("is_verified") is True, full_name=name,
        ))
    return out


def _error_code(payload: dict[str, Any]) -> str | None:
    """The new-convention error envelope's `code`, or
    `None`. Read only to tell the handler's own answer from the mux's; the
    `message` beside it never reaches the model."""
    error = payload.get("error")
    code = error.get("code") if isinstance(error, dict) else None
    return code if isinstance(code, str) else None


def _post_items(raw: Any) -> tuple[list[ItemView], bool]:
    """The post body's `items` → `(items, more than fit)`, in the bridge's
    order.

    Each item is its kind and url, plus `duration_seconds` when the bridge
    sends a non-negative number for it. Width and height are not read:
    nothing downstream uses them. A row whose url is not on a known
    Instagram CDN host is DROPPED, for the reason `_items` drops one: the url
    is handed to the model, and to `media_fetch`. At most `_MAX_ITEMS` rows,
    which is Instagram's own carousel ceiling, so a whole post fits."""
    if not isinstance(raw, list):
        return [], False
    out: list[ItemView] = []
    more = False
    for row in raw:
        if not isinstance(row, dict) or not _is_cdn_url(row.get("url")):
            continue
        if len(out) >= _MAX_ITEMS:
            more = True
            break
        kind = row.get("kind")
        duration = row.get("duration_seconds")
        out.append(ItemView(
            kind=kind if kind in _KINDS else "media",
            url=row["url"],
            duration_seconds=duration if (
                not isinstance(duration, bool) and isinstance(duration, (int, float))
                and duration >= 0
            ) else None,
        ))
    return out, more


def _bool(value: Any) -> bool | None:
    """A bool, or `None` for anything else (left out, not guessed)."""
    return value if isinstance(value, bool) else None


def _bio(value: Any) -> str | None:
    """A bio as the account wrote it (lines kept, ends trimmed), or `None`
    when there is none: a read, empty bio renders as `(none)`."""
    if isinstance(value, str) and value.strip():
        return value.strip()
    return None


def _count(value: Any) -> int | None:
    """A non-negative int count, or `None`. A bool is refused although it is
    an `int` to Python — `True followers` is a wrong answer that reads as
    data."""
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        return None
    return value


def _items(raw: Any, *, limit: int) -> list[ItemView]:
    """The story body's `items` → at most `limit` frames, each an `ItemView`
    carrying its kind, url and time and its text layer (caption, alt text).

    **Built field by field, never copied, and every value bound to a shape.**
    The text layer is present only when the bridge sent a non-empty STRING;
    the renderer puts it into the wrapped, clamped `text` and nowhere else,
    never into `items` (module docstring). A body that grows an `ocr_text`
    or a `description` still cannot leak it, because nothing reads an
    unlisted key — and nothing renders an unchecked VALUE either, which is
    the half a key whitelist does not cover.

    A malformed row is DROPPED rather than failing the whole read — one
    unparseable frame in a two-frame reel should still let the model look at
    the other — but a response with no usable row at all is `unavailable` at
    the call site above, never `nothing_found`.

    **Drop THEN clamp.** Clamping the raw list first would contradict the two
    sentences above: with `limit=1`, a two-frame reel whose FIRST frame is
    malformed would return zero rows and therefore `unavailable`, and the good
    second frame would never be examined (`FetchReel` is newest first, clamped
    to `limit=1`). The loop stops as soon as `limit` usable rows exist, so
    dropping first costs nothing on the healthy path.
    """
    if not isinstance(raw, list):
        return []
    cap = _cap(limit)
    out: list[ItemView] = []
    for row in raw:
        if not isinstance(row, dict):
            continue
        url = row.get("url")
        # https AND a known Instagram CDN host. The URL is handed to the
        # model and from there to `media_fetch`, which fetches it over NORA'S
        # OWN network — so a host this does not recognise is refused at the
        # boundary rather than being something the next tool has to defend
        # against. Scheme alone is not that check: it admits every https
        # host on the internet.
        if not _is_cdn_url(url):
            continue
        # The frame's `id` is deliberately NOT read. The model needs only the
        # URL, and the bridge's id can be `<pk>_<owner igid>` (its `storyFrame`
        # falls back to `item.ID` when a reel item has no `pk`), so carrying it
        # would hand the story owner's igid to the model (R-18). An `ItemView`
        # has no field it could go in.
        kind = row.get("kind")
        out.append(ItemView(
            kind=kind if kind in _KINDS else "media",
            url=url,
            # Carried because the ANSWER often turns on it («is this from
            # today?»), and a model asked a question about time from a block
            # with no time in it answers anyway, wrong, at a rate nothing
            # reports. Absent rather than guessed when the bridge omits it.
            taken_at=_as_int(row.get("taken_at")),
            caption=_one_line(row.get("caption")),
            alt_text=_one_line(row.get("alt_text")),
        ))
        if len(out) >= cap:
            break
    return out


def _cap(limit: Any) -> int:
    """`limit` → a usable count, 1.._MAX_ITEMS. `limit <= 0` means one item,
    decided here rather than left for anything else to interpret."""
    try:
        return max(1, min(int(limit), _MAX_ITEMS))
    except (TypeError, ValueError):
        return 1


def _is_cdn_url(value: Any) -> TypeGuard[str]:
    """A story frame's URL, or not. Parsed, never substring-matched: the
    hostname is the only part of a URL that says where a fetch lands, and
    `https://scontent.cdninstagram.com.evil.test/x` contains the allowed text
    while pointing somewhere else entirely."""
    if not isinstance(value, str) or not value.startswith("https://"):
        return False
    try:
        host = (urllib.parse.urlsplit(value).hostname or "").lower()
    except ValueError:
        return False
    return any(host == suffix[1:] or host.endswith(suffix) for suffix in _CDN_HOST_SUFFIXES)


def _one_line(value: Any) -> str | None:
    """A free-text field (caption, alt text) → one line of text, or `None`.

    Only a `str` is accepted: anything else is dropped, never `str()`-ed, for
    the same reason the frame id is not read — `str()` is how a structure
    becomes content nobody checked. Whitespace, newlines included, collapses
    to single spaces, so a caption cannot start a line of its own and pass
    itself off as another frame's line."""
    if not isinstance(value, str):
        return None
    text = " ".join(value.split())
    return text or None


def _username(value: Any) -> str | None:
    """An Instagram handle, or `None` for anything that is not one."""
    if isinstance(value, str) and _USERNAME_RE.fullmatch(value):
        return value
    return None


def _as_int(value: Any) -> int | None:
    """An epoch-seconds field, or None. A bool is REFUSED although Python
    would happily int() it — `True` becoming a 1970 timestamp is the kind of
    wrong answer that reads as data."""
    if isinstance(value, bool) or not isinstance(value, (int, float, str)):
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None
