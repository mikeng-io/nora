"""The single source of truth for Nora's tables, in their PostgreSQL shape.

Every declaration below is load-bearing; the ones that look like SQLAlchemy
defaults are not. The store was SQLite until the 2026-08-07 migration
(design/20); the quirks that shape survives here are Postgres's, not SQLite's:

- `ts`/`quoted_ts` are `sa.BigInteger` (INT8), NOT `sa.Integer` (INT4). Signal's
  millisecond timestamps are ~1.78e12, which overflows INT4's ~2.1e9
  ceiling. On SQLite `INTEGER` was 8-byte so it never showed; on Postgres INT4
  would raise `NumericValueOutOfRange` on **every** message write, silently
  under R-5. `id` stays INT4, and the INT8/INT4 asymmetry between `ts` and `id`
  is deliberate — but NOT for the reason recorded here until 2026-08-15, which
  was that `id` "is bounded forever by the per-conversation retention window".
  That premise died with `store.prune_enabled`: a deployment that keeps its
  record in full has no retention window bounding anything, and the sentence
  would have gone on reading like a guarantee.

  The real reason is that the asymmetry is not between two bounded things, it is
  between a value that ARRIVES large and one that COUNTS up. `ts` is an absolute
  epoch-millisecond figure — ~1.78e12 on its very first row, so INT4 overflows
  immediately and always. `id` starts at 1 and advances once per message, so its
  ceiling is a message COUNT: INT4's 2.147e9 is millennia of group chat, and a
  deployment that could approach it has a table size problem long before it has
  an id-width problem. (design/20 §2.)
- `id` is `sa.Identity(always=False)` → `GENERATED BY DEFAULT AS IDENTITY`, and
  `primary_key=True` makes it NOT NULL. `BY DEFAULT`, not `ALWAYS`: the one-time
  cutover load (design/20 §5) inserts explicit ids, which `ALWAYS` rejects
  without `OVERRIDING SYSTEM VALUE`; the identity sequence is reseeded after the
  load with `ALTER TABLE ... ALTER COLUMN id RESTART WITH :max+1`. There is no
  SQLite `AUTOINCREMENT`/`sqlite_autoincrement` and no nullable-PK override — the
  reflection quirks those papered over do not exist on Postgres.
- `created_at`'s server default is `sa.text("now()::text")`. The column stays
  `TEXT`; only the default's dialect changes (SQLite's `datetime('now')` has no
  Postgres equivalent, and a bare `now()` is `timestamptz` with no implicit cast
  into a `text` column — a `CREATE TABLE` type error). The format change is
  harmless because `created_at` is **write-only**: it is on no `TranscriptRow`/
  `UnattributedRow`, is never `SELECT`ed, and ordering is on `ts`/`id` only.
- `idx_messages_conv_ts` is `(conversation_id, ts DESC)`, the descending order
  declared with `sa.text("ts DESC")`. Autogenerate cannot see the per-column
  ordering (it compares the reflected plain column and reports permanent phantom
  drift), so the index is excluded from autogenerate in `migrations/env.py`,
  authored by hand in the squashed baseline, and its `ts DESC` ordering is
  asserted from `pg_index.indoption` by `tests/infra/test_schema_parity.py`.
"""

from __future__ import annotations

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql as pg

METADATA = sa.MetaData()

MESSAGES = sa.Table(
    "messages",
    METADATA,
    sa.Column("id", sa.Integer, sa.Identity(always=False), primary_key=True),
    sa.Column("platform", sa.Text, nullable=False),
    sa.Column("conversation_id", sa.Text, nullable=False),
    sa.Column("conversation_type", sa.Text, nullable=False),
    sa.Column("sender_id", sa.Text, nullable=False),
    sa.Column("sender_name", sa.Text),
    sa.Column("ts", sa.BigInteger, nullable=False),
    sa.Column("body", sa.Text),
    sa.Column("is_nora", sa.Integer, nullable=False, server_default=sa.text("0")),
    sa.Column(
        "delivery_status", sa.Text, nullable=False, server_default=sa.text("'pending'")
    ),
    sa.Column("raw_json", sa.Text),
    sa.Column(
        "created_at",
        sa.Text,
        nullable=False,
        server_default=sa.text("now()::text"),
    ),
    # The resolved person_id, or NULL when the sender mapped to nobody at the
    # moment of ingest. Written in the same INSERT (identity resolves before the
    # audit write), never by a follow-up UPDATE. Unindexed on purpose:
    # cardinality is a handful of people.
    sa.Column("person_id", sa.Text),
    # The `ts` of the row this one replies to (`dataMessage.quote.id` for
    # Signal), or NULL when the message is not a reply. BigInteger for the same
    # overflow reason `ts` is. Written in the same INSERT the parser's value
    # arrives on, never by a follow-up UPDATE. Unindexed on purpose.
    sa.Column("quoted_ts", sa.BigInteger),
    # What Nora HOLDS for this row's attachments: a JSON array of
    # `{sha256, media_type, size, filename}`, or NULL when she holds nothing —
    # which is both "there were no attachments" and "there were, and the bytes
    # could not be copied". Those two are distinguished by the body (`[image]`
    # with no handle) and by `nora_media_custody_total`, not by this column.
    #
    # ONE JSON column (as TEXT), not four scalars, because a Signal message
    # carries a LIST of attachments; and not a second table, because `prune_all`
    # already deletes messages by conversation and a child table would need a
    # cascade and a second sweep to stay consistent with it. Unindexed: nothing
    # queries it by hash, and an index here would disturb the one index that
    # matters.
    sa.Column("media_json", sa.Text),
    sa.CheckConstraint("conversation_type IN ('group','dm')"),
)

# Declared after the table so the expression index can reference its columns.
# `idx_messages_conv_ts` is excluded from Alembic autogenerate by
# `migrations/env.py::include_object` — see that hook's comment — and is authored
# by hand in the squashed baseline.
IDX_CONV_TS = sa.Index(
    "idx_messages_conv_ts", MESSAGES.c.conversation_id, sa.text("ts DESC")
)
IDX_IS_NORA = sa.Index("idx_messages_is_nora", MESSAGES.c.is_nora)


# `presence_fixes` — the presence collector's record (design/19 §3). It lives in
# the SAME `nora` database as `messages`, PLAINTEXT (DEC-54), and joins
# everything else on `person_id` — the roster's canonical id — which is the
# whole reason the store was unified onto one database (design/20).
#
# Every column mirrors a decision in design/19 §3:
# - `ts` is `sa.BigInteger` (INT8), NOT `sa.Integer`. Life360 fix timestamps are
#   epoch MILLISECONDS (~1.78e12), the identical INT4 overflow `messages.ts`
#   fixes — silent under R-5 on Postgres. `recorded_at` is BIGINT for the same
#   reason: it is `int(time.time() * 1000)`.
# - `lat`/`lng` are `NOT NULL`: a fix IS a position (the change-recorder only
#   writes when an advancing `location.timestamp` arrives, which carries
#   coordinates). A member with no position produces no row — its state rides
#   `wire_state` on its last row and the per-cycle metric, never a null-island
#   fix (design/19 §7.6).
# - `accuracy_m`/`is_driving`/`battery`/`address`/`speed_kmh` are nullable:
#   Life360 omits them for a still member, a non-driver, a phone with no
#   battery report, a coordinate that did not reverse-geocode, or a fix whose
#   own `-1` "unknown speed" sentinel `nora.infra.life360.members` already
#   collapsed to `None` before it ever reaches this table.
# - `wire_state` is `NOT NULL` TEXT holding a `nora.domain.presence.WireState`
#   value, so «sharing off» is a stored fact rather than an absent row.
# - `is_driving` is INT (0/1), matching `messages.is_nora`'s convention rather
#   than importing a Postgres BOOLEAN this schema does not otherwise use.
PRESENCE_FIXES = sa.Table(
    "presence_fixes",
    METADATA,
    sa.Column("id", sa.Integer, sa.Identity(always=False), primary_key=True),
    sa.Column("circle_id", sa.Text, nullable=False),
    sa.Column("person_id", sa.Text, nullable=False),
    # Epoch MILLISECONDS — the position's own timestamp (Life360's unit). BIGINT
    # for the same overflow reason `messages.ts` is (design/20 §2).
    sa.Column("ts", sa.BigInteger, nullable=False),
    sa.Column("lat", sa.Float, nullable=False),
    sa.Column("lng", sa.Float, nullable=False),
    sa.Column("accuracy_m", sa.Float),
    sa.Column("is_driving", sa.Integer),
    sa.Column("battery", sa.Float),
    sa.Column("address", sa.Text),
    # Life360's own reported ground speed, km/h, converted from wire m/s at
    # parse time; the wire's `-1` "unknown" sentinel is already `None` by the
    # time it reaches here (`nora.infra.life360.members._speed_kmh`).
    sa.Column("speed_kmh", sa.Float),
    sa.Column("wire_state", sa.Text, nullable=False),
    # Epoch MILLISECONDS: when Nora wrote this row, distinct from `ts`. Kept
    # separate because a stationary phone holds one fix for many minutes — `ts`
    # is the age of the POSITION, `recorded_at` the age of the OBSERVATION.
    sa.Column("recorded_at", sa.BigInteger, nullable=False),
)

# `(circle_id, person_id, ts DESC)` — the same alembic-check-blind DESC shape as
# `idx_messages_conv_ts` (design/19 §8): autogenerate cannot see the per-column
# ordering, so this index is EXCLUDED in `migrations/env.py::include_object`,
# authored by hand as raw DDL in `0002_presence_fixes`, and its `ts DESC` order
# is asserted from `pg_index.indoption` by `tests/infra/test_schema_parity.py`.
# It is the index every presence query runs on: `whereis` is the latest row for
# one `(circle_id, person_id)`; derivation reads one member's time window.
IDX_PRESENCE_MEMBER_TS = sa.Index(
    "idx_presence_member_ts",
    PRESENCE_FIXES.c.circle_id,
    PRESENCE_FIXES.c.person_id,
    sa.text("ts DESC"),
)

# presence_places — a circle's named landmarks («Home»), design/23 §3. STATIC
# household names for positions, deliberately a separate table from the fixes:
# a fix is where a person WAS (R-31-guarded), a place is somewhere the household
# chose to name. Replaced wholesale on each collector fetch (few rows, rarely
# changing), so the natural key is the primary key and there is no Identity
# column and no secondary index — every read is «all places for this circle»,
# which the PK prefix already serves.
PRESENCE_PLACES = sa.Table(
    "presence_places",
    METADATA,
    sa.Column("circle_id", sa.Text, primary_key=True),
    sa.Column("place_id", sa.Text, primary_key=True),
    sa.Column("name", sa.Text, nullable=False),
    sa.Column("lat", sa.Float, nullable=False),
    sa.Column("lng", sa.Float, nullable=False),
    sa.Column("radius_m", sa.Float),
    # Epoch MILLISECONDS: when Nora last saw this place on the wire.
    sa.Column("updated_ms", sa.BigInteger, nullable=False),
)


# `reminders` — one-shot deferred requests, the heartbeat's fire queue.
#
# Keyed by a UUID rather than an identity column, unlike every other table here:
# the id is minted by the `remind` tool INSIDE a turn and spoken back to the
# requester in the same breath, so `cancel_reminder` can name it — a value that
# has to exist before the row is written cannot come from a sequence.
#
# `platform` / `conversation_id` / `conversation_type` are all three stored, not
# just the id: every conversation key in this codebase is a TUPLE, and a row
# carrying `conversation_id` alone can build neither a `ConversationTarget`, nor
# the `ConversationSlots` key `(platform, conversation_id)`, nor a
# `Policy.is_allowed` call — all three of which the fire path makes before it
# sends a word.
#
# `created_at`/`due_at`/`fired_at` are `DateTime(timezone=True)` (timestamptz),
# NOT the epoch-milliseconds BIGINT `messages.ts` and `presence_fixes.ts` use.
# Those two carry a PLATFORM's own timestamp on the wire, in the platform's
# unit; these three are Nora's own wall-clock instants, compared against a
# `datetime` the heartbeat's injected clock produces, and a `due_at` that has to
# round-trip through `>= now` in SQL is far better served by the type Postgres
# can compare directly.
#
# `state` is TEXT with a CHECK rather than a Postgres ENUM: the same choice
# `messages.conversation_type` made, and for the same reason — a CHECK is edited
# by an ordinary migration, an ENUM needs `ALTER TYPE`. The CHECK is exactly
# what `alembic check` cannot see, which is why `0004_reminders` is hand-written
# and `tests/infra/test_schema_parity.py` reads it from `pg_constraint`.
REMINDERS = sa.Table(
    "reminders",
    METADATA,
    sa.Column("id", sa.Uuid, primary_key=True),
    sa.Column("requester_person_id", sa.Text, nullable=False),
    sa.Column("platform", sa.Text, nullable=False),
    sa.Column("conversation_id", sa.Text, nullable=False),
    sa.Column("conversation_type", sa.Text, nullable=False),
    sa.Column("text", sa.Text, nullable=False),
    sa.Column("created_at", sa.DateTime(timezone=True), nullable=False),
    sa.Column("due_at", sa.DateTime(timezone=True), nullable=False),
    sa.Column("state", sa.Text, nullable=False),
    # NULL until the row fires, and NULL forever on one that is cancelled.
    sa.Column("fired_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column("outcome", sa.Text, nullable=True),
    # ── recurrence (DEC-85) ──────────────────────────────────────────────────
    # A recurring reminder is a CHAIN of these rows, one per occurrence, and
    # only one of them is ever `pending`. `recurrence = 'none'` is the whole of
    # the pre-DEC-85 table, which is why every column here is nullable with a
    # server default: the migration adds them to live rows without touching one.
    sa.Column(
        "recurrence", sa.Text, nullable=False, server_default=sa.text("'none'"),
    ),
    # An IANA zone NAME, never an offset — a recurrence keeps a local wall
    # clock across DST, which an offset cannot express (`RecurrenceRule.tz`).
    sa.Column("recurrence_tz", sa.Text, nullable=True),
    sa.Column("recurrence_count", sa.Integer, nullable=True),
    sa.Column("recurrence_until", sa.DateTime(timezone=True), nullable=True),
    # The join key across a series' occurrences, and the namespace their ids are
    # derived from (`uuid5(series_id, occurrence)`).
    sa.Column("series_id", sa.Uuid, nullable=True),
    # The FIRST occurrence's `due_at`. Every later one is computed from this,
    # never from its predecessor, so monthly/yearly clamping cannot compound.
    sa.Column("series_anchor_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column(
        "occurrence", sa.Integer, nullable=False, server_default=sa.text("0"),
    ),
    sa.CheckConstraint(
        "state IN ('pending','firing','done','cancelled','failed')",
        name="ck_reminders_state",
    ),
    sa.CheckConstraint(
        "recurrence IN ('none','daily','weekly','monthly','yearly')",
        name="ck_reminders_recurrence_kind",
    ),
    # ALL-OR-NOTHING, and the database's copy of `Series | None`. The domain
    # cannot represent a half-set recurrence (the fields live on one optional
    # value object); without this constraint the TABLE could, and a row with a
    # `recurrence` but no `series_anchor_at` would read back as a reminder whose
    # next occurrence is uncomputable — one that fires once and then vanishes
    # with nothing anywhere saying why. `alembic check` is blind to this, which
    # is why 0005 is hand-written like 0004.
    sa.CheckConstraint(
        "(recurrence = 'none' AND recurrence_tz IS NULL "
        "AND recurrence_count IS NULL AND recurrence_until IS NULL "
        "AND series_id IS NULL AND series_anchor_at IS NULL AND occurrence = 0) "
        "OR (recurrence <> 'none' AND recurrence_tz IS NOT NULL "
        "AND recurrence_count >= 1 AND series_id IS NOT NULL "
        "AND series_anchor_at IS NOT NULL AND occurrence >= 0 "
        "AND occurrence < recurrence_count)",
        name="ck_reminders_recurrence",
    ),
)

# Declared after the table, house style. `(state, due_at)` ASCENDING — the one
# query the tick runs every wake is `state = 'pending' AND due_at <= now ORDER BY
# due_at`, which this serves as a prefix scan. No DESC column, so unlike
# `idx_messages_conv_ts` and `idx_presence_member_ts` this one has nothing
# autogenerate is blind to; it is still authored by hand in `0004_reminders`
# because the CHECK constraint on the same table is.
IDX_REMINDERS_DUE = sa.Index(
    "idx_reminders_due", REMINDERS.c.state, REMINDERS.c.due_at
)


# `version_announcements` — the ledger that makes "announce a version once, ever"
# true across a restart or a crash-loop (DEC-97, R-42).
#
# THE PRIMARY KEY IS THE MECHANISM, not bookkeeping. The claim is
# `INSERT … ON CONFLICT DO NOTHING`, so taking a version-in-a-room is a
# compare-and-set in ONE statement, exactly as `reminders.claim` puts its state
# predicate in the WHERE clause (R-37). A row EXISTING — in any state — is what
# bars a second announcement, so a process that died mid-turn never re-announces
# on the next boot. That is the same at-most-once decision R-37b made and for the
# same reason: nothing links a row to a message that may already have been
# delivered, so a retry double-posts anything that crashed after egress, and an
# upgrade note posted twice is worse than one never posted.
#
# Keyed by `(version, platform, conversation_id)` and not by `version` alone: she
# lives in more than one room, each room is a separate turn that can separately
# fail, and one room's failure must not consume another room's announcement.
#
# `announced_at` is stamped when the row is CLAIMED, not when it is resolved: it
# records when this version was taken, which is the fact boot recovery needs to
# read afterwards. `state`/`outcome` carry what happened — the fire path's own
# §8.1 outcome string, so an operator asking "why did V3 never appear in that
# group" reads the answer rather than inferring it from silence (R-5 keeps the
# failure out of the room, so this row is its only trace).
#
# `state` is TEXT with a CHECK, like `reminders.state`, and for the same reason:
# a CHECK is edited by an ordinary migration where an ENUM needs `ALTER TYPE` —
# and it is exactly what `alembic check` is blind to, which is why
# `0006_version_announcements` is hand-written and the parity gate reads it back
# out of `pg_constraint`.
VERSION_ANNOUNCEMENTS = sa.Table(
    "version_announcements",
    METADATA,
    sa.Column("version", sa.Text, primary_key=True),
    sa.Column("platform", sa.Text, primary_key=True),
    sa.Column("conversation_id", sa.Text, primary_key=True),
    sa.Column("announced_at", sa.DateTime(timezone=True), nullable=False),
    sa.Column("state", sa.Text, nullable=False),
    sa.Column("outcome", sa.Text, nullable=True),
    sa.CheckConstraint(
        "state IN ('announcing','done','failed')",
        name="ck_version_announcements_state",
    ),
)


# `artifacts` — `drop`'s own artifact metadata (Nora Drop spec §3, §4, §7a).
# Written by `deploy/drop`'s internal `POST /api/artifacts`, a SEPARATE Python
# app/venv from Nora herself that reaches this table with its own Postgres
# client (asyncpg), never through this package — this declaration exists so
# ONE alembic chain (this one, run at Nora's and presence's own startup,
# `nora/app/composition.py`/`nora/presence/composition.py`) owns the schema
# both sides read/write, rather than `drop` growing a second, ad-hoc migration
# tool for a table in the same database (CLAUDE.md: "follow that convention,
# not a fresh ad-hoc schema tool").
#
# `id` is minted by `drop` itself, NOT an Identity column — it doubles as the
# RustFS object key, so the row and the bytes must agree on a name chosen
# before either is written, the same reason `reminders.id` cannot come from a
# sequence (this file's own note on that table, above).
#
# `slug` is a SEPARATE, short, public-facing value (the same base58-ish
# alphabet `deploy/shortener/worker/shortener.js` uses for link slugs) — the
# thing a `GET /d/<slug>` URL path actually contains. Kept apart from `id` so
# `artifact_id` can keep naming the row for a future admin/expiry surface
# without that surface reparsing it back out of a URL
# (`ArtifactRegistration`'s own docstring, `nora/domain/ports.py`). UNIQUE,
# not primary — the row's identity is `id`.
#
# `expires_at` is epoch-MILLISECONDS, matching `PresenceFix.ts`'s unit
# (`ArtifactIngest.register`'s own docstring) and deliberately NOT a
# `DateTime` like `reminders.due_at`: this value crosses the HTTP boundary
# from a caller (a future Compute tool, or `drop`'s own client) that never
# gets a live SQLAlchemy type to compare against, so the wire format IS the
# storage format — the same choice `messages.ts` made for the same reason.
#
# No CHECK constraint and no expression index here, unlike `reminders` or
# `version_announcements` — this table has neither, so there is nothing
# `alembic check` is blind to; `0007_drop_artifacts` is autogenerated and left
# that way rather than hand-typed for no reason.
ARTIFACTS = sa.Table(
    "artifacts",
    METADATA,
    sa.Column("id", sa.Text, primary_key=True),
    sa.Column("slug", sa.Text, nullable=False, unique=True),
    sa.Column("title", sa.Text, nullable=False),
    sa.Column("media_type", sa.Text, nullable=False),
    sa.Column("size_bytes", sa.BigInteger, nullable=False),
    sa.Column(
        "created_at", sa.DateTime(timezone=True), nullable=False,
        server_default=sa.text("now()"),
    ),
    sa.Column("expires_at", sa.BigInteger, nullable=True),
)


