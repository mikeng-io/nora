"""The single source of truth for Nora's tables, in their PostgreSQL shape.

Every declaration below is load-bearing; the ones that look like SQLAlchemy
defaults are not.

- `ts`/`quoted_ts` are `sa.BigInteger` (INT8), NOT `sa.Integer` (INT4). Signal's
  millisecond timestamps are ~1.78e12, which overflows INT4's ~2.1e9 ceiling;
  INT4 would raise `NumericValueOutOfRange` on **every** message write, silently
  under R-5. `id` stays INT4: the asymmetry is between a value that ARRIVES
  large (`ts`, an absolute epoch-millisecond figure, overflowing INT4 on its
  first row) and one that COUNTS up (`id` starts at 1 and advances once per
  message, so its ceiling is a message count: INT4's 2.147e9 is far beyond
  any deployment).
- `id` is `sa.Identity(always=False)` → `GENERATED BY DEFAULT AS IDENTITY`, and
  `primary_key=True` makes it NOT NULL. `BY DEFAULT`, not `ALWAYS`: a bulk load
  that inserts explicit ids is rejected by `ALWAYS` without `OVERRIDING SYSTEM
  VALUE`, and the sequence must then be reseeded with
  `ALTER TABLE ... ALTER COLUMN id RESTART WITH :max+1`.
- `created_at`'s server default is `sa.text("now()::text")`. The column is
  `TEXT`, and a bare `now()` is `timestamptz` with no implicit cast into a
  `text` column (a `CREATE TABLE` type error). The format is harmless because
  `created_at` is **write-only**: it is on no `TranscriptRow`/`UnattributedRow`,
  is never `SELECT`ed, and ordering is on `ts`/`id` only.
- `idx_messages_conv_ts` is `(conversation_id, ts DESC)`, the descending order
  declared with `sa.text("ts DESC")`. Autogenerate cannot see the per-column
  ordering (it compares the reflected plain column and reports permanent phantom
  drift), so the index is excluded from autogenerate in `migrations/env.py`,
  authored by hand in the squashed baseline, and its `ts DESC` ordering is
  asserted from `pg_index.indoption` by `tests/infra/test_schema_parity.py`.
"""

