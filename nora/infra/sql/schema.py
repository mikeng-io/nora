    # moment of ingest. Written in the same INSERT (identity resolves before the
    # audit write), never by a follow-up UPDATE. Unindexed on purpose:
    # cardinality is a handful of people.
    sa.Column("person_id", sa.Text),
    # The `ts` of the row this one replies to (`dataMessage.quote.id` for
    # Signal), or NULL when the message is not a reply. BigInteger for the same
    # overflow reason `ts` is. Written in the same INSERT the parser's value
    # arrives on, never by a follow-up UPDATE. Unindexed on purpose.
    sa.Column("quoted_ts", sa.BigInteger),
    # What Nora HOLDS for this row's attachments: a JSON array of
    # `{sha256, media_type, size, filename}`, or NULL when she holds nothing —
    # which is both "there were no attachments" and "there were, and the bytes
    # could not be copied". Those two are distinguished by the body (`[image]`
    # with no handle) and by `nora_media_custody_total`, not by this column.
    #
    # ONE JSON column (as TEXT), not four scalars, because a Signal message
    # carries a LIST of attachments; and not a second table, because `prune_all`
    # already deletes messages by conversation and a child table would need a
    # cascade and a second sweep to stay consistent with it. Unindexed: nothing
    # queries it by hash, and an index here would disturb the one index that
    # matters.
    sa.Column("media_json", sa.Text),
    # The shared file links recognised in `body` at ingest: a JSON array of
    # `{provider, file_id, url[, resource_key]}`, or NULL when there were none.
    # `media_json`'s shape and its reasons (a list per message, no child table
