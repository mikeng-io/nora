# The memory index (migration `0105_memory_index`): a PROJECTION of every store into
# one node table and one edge table, written only by
# `nora.infra.sql.memory_index` and rebuilt, never restored (`NOT_RESTORED`).
# The closed vocabularies are `nora.domain.memory_index`'s; the migration spells
# them out, and the parity gate compares the two.
MEMORY_NODE = sa.Table(
    "memory_node",
    METADATA,
    sa.Column("id", sa.BigInteger, sa.Identity(always=False), primary_key=True),
    sa.Column("kind", sa.Text, nullable=False),
    sa.Column("source_id", sa.Text, nullable=False),
    sa.Column("unit", sa.Text),
    sa.Column("origin_room", sa.Text),
    sa.Column("persons", pg.ARRAY(sa.Text), nullable=False,
              server_default=sa.text("'{}'::text[]")),
    sa.Column("exclude_persons", pg.ARRAY(sa.Text), nullable=False,
              server_default=sa.text("'{}'::text[]")),
    sa.Column("lineage", pg.JSONB, nullable=False, server_default=sa.text("'[]'::jsonb")),
    sa.Column("sha256", sa.Text),
    sa.Column("text", sa.Text, nullable=False, server_default=sa.text("''")),
    sa.Column("at_ms", sa.BigInteger),
    sa.Column("state", sa.Text, nullable=False, server_default=sa.text("'live'")),
    sa.Column(
        "projected_at", sa.DateTime(timezone=True), nullable=False,
        server_default=sa.text("clock_timestamp()"),
    ),
    # When the node's vector became owed (0111): written with the row, and
    # reset only when the input its vector is made from changes
    # (`_cleared_when`), never by a re-projection of the same input, so a
    # node's wait for its vector is `clock_timestamp() - owed_since`.
    sa.Column(
        "owed_since", sa.DateTime(timezone=True), nullable=False,
        server_default=sa.text("clock_timestamp()"),
    ),
    # The dense channel (0106). The node is its own embedding queue: `project()` clears all six when
    # the input the vector was made from changes (`embed_input`: the `text`,
    # or the `bytes` its `sha256` names), and the embedding worker fills a
    # NULL `embedding`. `embedding_model` is the
    # fingerprint it was made with (`nora.infra.embedder.fingerprint`), so a
    # vector of another model reads as unembedded. `embedded_at` (epoch ms) is
    # the last attempt, a failed one included; `embed_attempts` counts the
    # failures since the input last changed, and backs the node off;
    # `embed_error` names the last one's class, never content.
    sa.Column("embedding", HALFVEC(EMBEDDING_DIMENSIONS)),
    sa.Column("embedding_model", sa.Text),
    sa.Column("embedded_at", sa.BigInteger),
    sa.Column("embed_attempts", sa.Integer, nullable=False, server_default=sa.text("0")),
    sa.Column("embed_error", sa.Text),
    sa.Column("embed_input", sa.Text),
    sa.UniqueConstraint("kind", "source_id", name="uq_memory_node_kind_source"),
    sa.CheckConstraint(f"kind IN ({_in_list(MEMORY_NODE_KINDS)})", name="ck_memory_node_kind"),
    sa.CheckConstraint(
        f"state IN ({_in_list(MEMORY_NODE_STATES)})", name="ck_memory_node_state",
    ),
    # A node that is not an entity carries a scope, or no read could ever place
    # it and it would be either invisible or visible everywhere.
    sa.CheckConstraint(
        f"kind IN ({_in_list(MEMORY_HUB_KINDS)}) "
        "OR unit IS NOT NULL OR origin_room IS NOT NULL "
        "OR cardinality(persons) > 0",
        name="ck_memory_node_has_a_scope",
    ),
    sa.CheckConstraint(
        f"embed_input IS NULL OR embed_input IN ({_in_list(MEMORY_EMBED_INPUTS)})",
        name="ck_memory_node_embed_input",
    ),
)
IDX_MEMORY_NODE_UNIT = sa.Index("idx_memory_node_unit", MEMORY_NODE.c.unit)
IDX_MEMORY_NODE_ORIGIN_ROOM = sa.Index("idx_memory_node_origin_room", MEMORY_NODE.c.origin_room)
