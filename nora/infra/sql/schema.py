# Facts a fact is warranted by. A junction table rather than an array column:
# answering "which facts depend on this one" (a premise superseded leaves every
# fact deduced from it standing on a retracted foundation) is an unindexable
# array-containment scan with an array, an indexed lookup with this table. Both
# FKs target `fact.id`; `idx_fact_premise_premise_fact_id` below serves the
# reverse direction the composite PK does not (it indexes `fact_id` first).
# "warrant_kind = 'premises' ⇒ at least one premise" is a cross-table invariant
# Postgres CHECK constraints cannot express, and this table does not fake it
# with a trigger; nothing in the database enforces it.
FACT_PREMISE = sa.Table(
    "fact_premise",
    METADATA,
    # CASCADE on both ends (migration 0040): run-scoped rollback — "void
    # everything run X wrote" — is a supported operation, and a subsystem whose
    # writer is a model with no human in the loop needs an undo. Without it,
    # deleting a fact is blocked by its premise rows before `fact_asserter`'s
    # own cascade runs.
    sa.Column("fact_id", pg.UUID(as_uuid=False),
              sa.ForeignKey("fact.id", name="fact_premise_fact_id_fkey",
                            ondelete="CASCADE"),
              primary_key=True),
    sa.Column("premise_fact_id", pg.UUID(as_uuid=False),
              sa.ForeignKey("fact.id", name="fact_premise_premise_fact_id_fkey",
                            ondelete="CASCADE"),
              primary_key=True),
    # The one cycle cheap to rule out at the row level: a fact cannot be its
    # own premise. Longer cycles (A premises B premises A) are NOT detected
    # here — that needs a graph walk, not a row CHECK — and are left as a
    # known gap rather than silently assumed away.
    sa.CheckConstraint(
        "fact_id <> premise_fact_id",
        name="fact_premise_no_self_reference_check",
    ),
)

