# one `(circle_id, person_id)`; derivation reads one member's time window.
IDX_PRESENCE_MEMBER_TS = sa.Index(
    "idx_presence_member_ts",
    PRESENCE_FIXES.c.circle_id,
    PRESENCE_FIXES.c.person_id,
    sa.text("ts DESC"),
)

