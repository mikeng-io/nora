# `reminders` — one-shot deferred requests, the heartbeat's fire queue.
#
# Keyed by a UUID rather than an identity column, unlike every other table here:
# the id is minted by the `remind` tool INSIDE a turn and spoken back to the
# requester in the same breath, so `cancel_reminder` can name it — a value that
# has to exist before the row is written cannot come from a sequence.
#
# `platform` / `conversation_id` / `conversation_type` are all three stored, not
# just the id: every conversation key in this codebase is a TUPLE, and a row
# carrying `conversation_id` alone can build neither a `ConversationTarget`, nor
# the `ConversationSlots` key `(platform, conversation_id)`, nor a
# `Policy.is_allowed` call — all three of which the fire path makes before it
# sends a word.
#
# `created_at`/`due_at`/`fired_at` are `DateTime(timezone=True)` (timestamptz),
# NOT the epoch-milliseconds BIGINT `messages.ts` and `presence_fixes.ts` use.
# Those two carry a PLATFORM's own timestamp on the wire, in the platform's
# unit; these three are Nora's own wall-clock instants, compared against a
# `datetime` the heartbeat's injected clock produces, and a `due_at` that has to
# round-trip through `>= now` in SQL is far better served by the type Postgres
# can compare directly.
#
# `state` is TEXT with a CHECK rather than a Postgres ENUM: the same choice
# `messages.conversation_type` made, and for the same reason — a CHECK is edited
# by an ordinary migration, an ENUM needs `ALTER TYPE`. The CHECK is exactly
# what `alembic check` cannot see, which is why `0004_reminders` is hand-written
# and `tests/infra/test_schema_parity.py` reads it from `pg_constraint`.
REMINDERS = sa.Table(
    "reminders",
    METADATA,
    sa.Column("id", sa.Uuid, primary_key=True),
    sa.Column("requester_person_id", sa.Text, nullable=False),
    sa.Column("platform", sa.Text, nullable=False),
    sa.Column("conversation_id", sa.Text, nullable=False),
    sa.Column("conversation_type", sa.Text, nullable=False),
    sa.Column("text", sa.Text, nullable=False),
    sa.Column("created_at", sa.DateTime(timezone=True), nullable=False),
    sa.Column("due_at", sa.DateTime(timezone=True), nullable=False),
    sa.Column("state", sa.Text, nullable=False),
    # NULL until the row fires, and NULL forever on one that is cancelled.
    sa.Column("fired_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column("outcome", sa.Text, nullable=True),
    # ── recurrence (DEC-85) ──────────────────────────────────────────────────
    # A recurring reminder is a CHAIN of these rows, one per occurrence, and
    # only one of them is ever `pending`. `recurrence = 'none'` is the whole of
    # the pre-DEC-85 table, which is why every column here is nullable with a
    # server default: the migration adds them to live rows without touching one.
    sa.Column(
        "recurrence", sa.Text, nullable=False, server_default=sa.text("'none'"),
    ),
    # An IANA zone NAME, never an offset — a recurrence keeps a local wall
    # clock across DST, which an offset cannot express (`RecurrenceRule.tz`).
    sa.Column("recurrence_tz", sa.Text, nullable=True),
    sa.Column("recurrence_count", sa.Integer, nullable=True),
    # EVERY N UNITS (#109). Server default 1 so the migration adds it to live
    # rows without a backfill: every rule written before 2026-09-07 meant
    # "every unit", which is exactly 1. NOT NULL for the same reason
    # `occurrence` is — a null here would make the step uncomputable, and the
    # all-or-nothing CHECK below cannot help with a column that is legitimately
    # present on a `none` row too.
    sa.Column(
        "recurrence_interval", sa.Integer, nullable=False,
        server_default=sa.text("1"),
    ),
    sa.Column("recurrence_until", sa.DateTime(timezone=True), nullable=True),
    # The join key across a series' occurrences, and the namespace their ids are
    # derived from (`uuid5(series_id, occurrence)`).
    sa.Column("series_id", sa.Uuid, nullable=True),
    # The FIRST occurrence's `due_at`. Every later one is computed from this,
    # never from its predecessor, so monthly/yearly clamping cannot compound.
    sa.Column("series_anchor_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column(
        "occurrence", sa.Integer, nullable=False, server_default=sa.text("0"),
    ),
    # ── event-model abstraction (DEC-139) ────────────────────────────────────
    # `kind` names WHAT the row is; `"reminder"` is the whole of the
    # pre-DEC-139 table, so the default keeps every live row satisfying the
    # NOT NULL without a backfill pass. `payload` is the kind's denormalized
    # shape (JSONB permits a structured map without a migration).
    sa.Column(
        "kind", sa.Text, nullable=False, server_default=sa.text("'reminder'"),
    ),
    sa.Column("payload", pg.JSONB, nullable=True),
    sa.CheckConstraint(
        "state IN ('pending','firing','done','cancelled','failed')",
        name="ck_reminders_state",
    ),
    sa.CheckConstraint(
        "recurrence IN ('none','minutely','hourly','daily','weekly','monthly','yearly')",
        name="ck_reminders_recurrence_kind",
    ),
    # ALL-OR-NOTHING, and the database's copy of `Series | None`. The domain
    # cannot represent a half-set recurrence (the fields live on one optional
    # value object); without this constraint the TABLE could, and a row with a
    # `recurrence` but no `series_anchor_at` would read back as a reminder whose
    # next occurrence is uncomputable — one that fires once and then vanishes
    # with nothing anywhere saying why. `alembic check` is blind to this, which
    # is why 0005 is hand-written like 0004.
    sa.CheckConstraint(
        "(recurrence = 'none' AND recurrence_tz IS NULL "
        "AND recurrence_count IS NULL AND recurrence_until IS NULL "
        "AND series_id IS NULL AND series_anchor_at IS NULL AND occurrence = 0) "
        "OR (recurrence <> 'none' AND recurrence_tz IS NOT NULL "
        "AND recurrence_count >= 1 AND series_id IS NOT NULL "
        "AND series_anchor_at IS NOT NULL AND occurrence >= 0 "
        "AND occurrence < recurrence_count)",
        name="ck_reminders_recurrence",
    ),
    sa.CheckConstraint(
        "recurrence_interval >= 1",
        name="ck_reminders_recurrence_interval",
    ),
)

